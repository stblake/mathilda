typedef bool (*bs_real_fn)(double, double, double*);
typedef bool (*bs_cplx_fn)(double, double, double, double*, double*);
static const bs_real_fn BS_REAL[4] = { sf_bessel_j_r, sf_bessel_y_r, sf_bessel_i_r, sf_bessel_k_r };
static const bs_cplx_fn BS_CPLX[4] = { sf_bessel_j_c, sf_bessel_y_c, sf_bessel_i_c, sf_bessel_k_c };

bool sf_bessel_nd(int kind, double nre, double nim, double zre, double zim,
                  double* rr, double* ri) {
    if (kind < 0 || kind > 3 || nim != 0.0) return false;
    if (zim == 0.0) {
        double v;
        if (!BS_REAL[kind](nre, zre, &v)) return false;
        *rr = v; *ri = 0.0;
        return true;
    }
    return BS_CPLX[kind](nre, zre, zim, rr, ri);
}

bool sf_bessel_scalar(int kind, double nu, double zr, double zi,
                      double* rr, double* ri, bool* is_real) {
    if (kind < 0 || kind > 3) return false;
    if (zi == 0.0) {
        double v;
        if (BS_REAL[kind](nu, zr, &v)) { *rr = v; *ri = 0.0; *is_real = true; return true; }
    }
    *is_real = false;
    return BS_CPLX[kind](nu, zr, zi, rr, ri);
}

typedef bool (*ai_real_fn)(double, double*);
typedef bool (*ai_cplx_fn)(double, double, double*, double*);
static const ai_real_fn AI_REAL[4] = { sf_airy_ai_r, sf_airy_aip_r, sf_airy_bi_r, sf_airy_bip_r };
static const ai_cplx_fn AI_CPLX[4] = { sf_airy_ai_c, sf_airy_aip_c, sf_airy_bi_c, sf_airy_bip_c };

bool sf_airy_nd(int which, double zre, double zim, double* rr, double* ri) {
    if (which < 0 || which > 3) return false;
    if (zim == 0.0) {
        double v;
        if (!AI_REAL[which](zre, &v)) return false;
        *rr = v; *ri = 0.0;
        return true;
    }
    return AI_CPLX[which](zre, zim, rr, ri);
}

bool sf_airy_scalar(int which, double zr, double zi,
                    double* rr, double* ri, bool* is_real) {
    if (which < 0 || which > 3) return false;
    *is_real = (zi == 0.0);
    return sf_airy_nd(which, zr, zi, rr, ri);
}
