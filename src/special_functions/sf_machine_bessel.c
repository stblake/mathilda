#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

#define BS_EPS     1.0e-17          /* series / CF stopping tolerance */
#define BS_MAXNU   1000.0           /* order cap (no Debye expansion) */
#define BS_HANKEL_R 21.0            /* |z| from which Hankel reaches 2^-56 */
#define BS_TEMME_R  1.25            /* Temme series below, tables / CF2 above */

/* ======================================================================== */
/* Complex arithmetic on (re, im) pairs                                     */
/* ======================================================================== */

typedef struct { double re, im; } cx;

static inline cx cxm(double r, double i) { cx z; z.re = r; z.im = i; return z; }
static inline cx cadd(cx a, cx b) { return cxm(a.re + b.re, a.im + b.im); }
static inline cx csub(cx a, cx b) { return cxm(a.re - b.re, a.im - b.im); }
static inline cx cneg(cx a) { return cxm(-a.re, -a.im); }
static inline cx cconj(cx a) { return cxm(a.re, -a.im); }
static inline cx cscal(cx a, double s) { return cxm(a.re * s, a.im * s); }
static inline cx cmul(cx a, cx b) {
    return cxm(a.re * b.re - a.im * b.im, a.re * b.im + a.im * b.re);
}
/* i * a */
static inline cx cmuli(cx a) { return cxm(-a.im, a.re); }
/* Smith's division (CACM 5 (1962) 435): no overflow from squaring |b|. */
static inline cx cdiv(cx a, cx b) {
    if (fabs(b.re) >= fabs(b.im)) {
        double r = b.im / b.re, d = b.re + b.im * r;
        return cxm((a.re + a.im * r) / d, (a.im - a.re * r) / d);
    } else {
        double r = b.re / b.im, d = b.re * r + b.im;
        return cxm((a.re * r + a.im) / d, (a.im * r - a.re) / d);
    }
}
static inline cx cinv(cx b) {
    /* one division; the operands here are far from overflow (|b| < 1e150) */
    if (fmax(fabs(b.re), fabs(b.im)) < 1e150) {
        double d = 1.0 / (b.re * b.re + b.im * b.im);
        return cxm(b.re * d, -b.im * d);
    }
    return cdiv(cxm(1.0, 0.0), b);
}
static inline double cnorm1(cx a) { return fabs(a.re) + fabs(a.im); }
static inline bool cfinite(cx a) { return isfinite(a.re) && isfinite(a.im); }
static inline cx cexpz(cx a) {
    double e = exp(a.re);
    if (a.im == 0.0) return cxm(e, 0.0);
    return cxm(e * cos(a.im), e * sin(a.im));
}
static inline cx clogz(cx a) {
    if (a.im == 0.0 && a.re > 0.0) return cxm(log(a.re), 0.0);
    return cxm(log(hypot(a.re, a.im)), atan2(a.im, a.re));
}
/* Principal square root; the real axis is exact. */
static inline cx csqrtz(cx a) {
    if (a.im == 0.0) {
        if (a.re >= 0.0) return cxm(sqrt(a.re), a.im);
        return cxm(0.0, copysign(sqrt(-a.re), a.im));
    }
    double m = hypot(a.re, a.im);
    double t = sqrt(0.5 * (m + fabs(a.re)));
    if (a.re >= 0.0) return cxm(t, a.im / (2.0 * t));
    return cxm(fabs(a.im) / (2.0 * t), copysign(t, a.im));
}

/* sin(pi x), cos(pi x) with exact zeros at the integers / half-integers: the
 * argument is reduced exactly (x - n/2 is exact for the n nearest 2x) before
 * the multiplication by pi rounds. */
static void sincospi(double x, double* s, double* c) {
    double r = fmod(x, 2.0);                     /* exact, |r| < 2 */
    double n = nearbyint(2.0 * r);               /* quadrant, |n| <= 4 */
    double f = r - 0.5 * n;                      /* exact, |f| <= 1/4 */
    double sf = (f == 0.0) ? 0.0 : sin(M_PI * f);
    double cf = (f == 0.0) ? 1.0 : cos(M_PI * f);
    int q = ((int)n % 4 + 4) % 4;
    switch (q) {
        case 0:  *s = sf;  *c = cf;  break;
        case 1:  *s = cf;  *c = -sf; break;
        case 2:  *s = -sf; *c = -cf; break;
        default: *s = -cf; *c = sf;  break;
    }
    if (*s == 0.0) *s = 0.0;                     /* no signed zeros */
    if (*c == 0.0) *c = 0.0;
}
static inline cx cispi(double x) { double s, c; sincospi(x, &s, &c); return cxm(c, s); }

/* Horner. Deliberately a plain multiply-add, not fma(): without -mfma (the
 * portable build) fma() is a libm call, which would cost more than the whole
 * polynomial; the tables are generated so that this evaluation stays within
 * ~1 ulp (tools/sf_accuracy/gen_*_tables.py --check models it). */
static inline double horner(const double* c, int deg, double t) {
    double s = c[deg];
    for (int k = deg - 1; k >= 0; k--) s = s * t + c[k];
    return s;
}

/* Error-free transforms (Knuth's TwoSum; TwoProd by fma). */
static inline void two_sum(double a, double b, double* s, double* e) {
    double x = a + b, bb = x - a;
    *e = (a - (x - bb)) + (b - bb);
    *s = x;
}
static inline void two_prod(double a, double b, double* p, double* e) {
    double x = a * b;
    *e = fma(a, b, -x);
    *p = x;
}

/* a*b - c*d as hi + lo. */
static void dd_diff_prod(double a, double b, double c, double d, double* hi, double* lo) {
    double p, pe, q, qe, s, se;
    two_prod(a, b, &p, &pe);
    two_prod(c, d, &q, &qe);
    two_sum(p, -q, &s, &se);
    *hi = s; *lo = se + (pe - qe);
}

/* A machine answer: finite, and not lost to gradual underflow. */
static inline bool real_ok(double v) {
    return isfinite(v) && (v == 0.0 || fabs(v) >= DBL_MIN);
}
static inline bool cx_ok(cx v) {
    if (!cfinite(v)) return false;
    double m = fmax(fabs(v.re), fabs(v.im));
    return m == 0.0 || m >= DBL_MIN;
}

