#define AIRY_SQRT_PI_INV   0.5641895835477563      /* 1/sqrt(pi) */
#define AIRY_HALF_SPI_INV  0.28209479177387814     /* 1/(2 sqrt(pi)) */
#define TWO_THIRDS_HI      0.6666666666666666
#define TWO_THIRDS_LO      3.700743415417188e-17

/* zeta = (2/3) x^{3/2}, x > 0, as an unevaluated sum hi + lo. */
static void airy_zeta_dd(double x, double* hi, double* lo) {
    double s = sqrt(x);
    double slo = fma(-s, s, x) / (2.0 * s);       /* sqrt x = s + slo */
    double p = x * s;
    double plo = fma(x, s, -p) + x * slo;         /* x^{3/2} = p + plo */
    double h = p * TWO_THIRDS_HI;
    *lo = fma(p, TWO_THIRDS_HI, -h) + (p * TWO_THIRDS_LO + plo * TWO_THIRDS_HI);
    *hi = h;
}


enum { AIRY_AI = 0, AIRY_AIP = 1, AIRY_BI = 2, AIRY_BIP = 3 };

static const double* const AIRY_TAB_NEG[4] = {
    sf_airy_tab_neg_ai, sf_airy_tab_neg_aip, sf_airy_tab_neg_bi, sf_airy_tab_neg_bip };
static const double* const AIRY_TAB_MID[4] = {
    sf_airy_tab_mid_ai, sf_airy_tab_mid_aip, sf_airy_tab_mid_bi, sf_airy_tab_mid_bip };
static const double* const AIRY_TAB_POS[4] = {
    sf_airy_tab_pos_ai, sf_airy_tab_pos_aip, sf_airy_tab_pos_bi, sf_airy_tab_pos_bip };

/* Evaluate the region table at x. The interval width is a power of two and
 * every centre a multiple of half of it, so x - centre is exact (Sterbenz)
 * and so is the scaling to t in [-1, 1]. */
static inline double airy_tab(const double* tab, double lo, int nint, int deg,
                              double w, double x) {
    int i = (int)((x - lo) / w);
    if (i < 0) i = 0;
    if (i >= nint) i = nint - 1;
    double c = lo + ((double)i + 0.5) * w;
    double t = (x - c) * (2.0 / w);
    return horner(tab + (size_t)i * (size_t)(deg + 1), deg, t);
}

/* x >= 10: Poincare expansions, DLMF 9.7.5-9.7.8. */
static bool airy_asym_pos(int which, double x, double* out) {
    double zh, zl;
    airy_zeta_dd(x, &zh, &zl);
    double q = sqrt(sqrt(x));                      /* x^{1/4} */
    double iz = 1.0 / zh;
    const double* c = (which == AIRY_AI || which == AIRY_BI) ? AIRY_U : AIRY_V;
    double t = (which == AIRY_AI || which == AIRY_AIP) ? -iz : iz;
    double s = horner(c, 25, t);
    double v;
    if (which == AIRY_AI || which == AIRY_AIP) {
        double e = exp(-zh);
        if (!(e >= DBL_MIN)) return false;
        e *= (1.0 - zl);
        v = (which == AIRY_AI) ? e * s * AIRY_HALF_SPI_INV / q
                               : -q * e * s * AIRY_HALF_SPI_INV;
    } else {
        double e = exp(zh);
        if (!isfinite(e)) return false;
        e *= (1.0 + zl);
        v = (which == AIRY_BI) ? e * s * AIRY_SQRT_PI_INV / q
                               : q * e * s * AIRY_SQRT_PI_INV;
    }
    if (!real_ok(v)) return false;
    *out = v;
    return true;
}

/* x <= -10: DLMF 9.7.9-9.7.12, with the phase zeta + pi/4 from the
 * double-double zeta. */
static bool airy_asym_neg(int which, double x, double* out) {
    double ax = -x, zh, zl;
    airy_zeta_dd(ax, &zh, &zl);
    double q = sqrt(sqrt(ax));
    double iz = 1.0 / zh, y = -iz * iz;
    const double* c = (which == AIRY_AI || which == AIRY_BI) ? AIRY_U : AIRY_V;
    /* even part sum (-1)^j c_{2j} zeta^{-2j}, odd part sum (-1)^j c_{2j+1} zeta^{-2j-1} */
    double ev = 0.0, od = 0.0;
    for (int j = 12; j >= 0; j--) {
        ev = fma(ev, y, c[2 * j]);
        od = fma(od, y, c[2 * j + 1]);
    }
    od *= iz;
    double sz = sin(zh), cz = cos(zh);
    double sn = sz + cz * zl, cs = cz - sz * zl;   /* sin, cos of zeta */
    const double R2 = 0.70710678118654752;
    double sth = (sn + cs) * R2, cth = (cs - sn) * R2;   /* of zeta + pi/4 */
    double v;
    switch (which) {
        case AIRY_AI:  v = (sth * ev - cth * od) * AIRY_SQRT_PI_INV / q; break;
        case AIRY_BI:  v = (cth * ev + sth * od) * AIRY_SQRT_PI_INV / q; break;
        case AIRY_AIP: v = -q * (cth * ev + sth * od) * AIRY_SQRT_PI_INV; break;
        default:       v = q * (sth * ev - cth * od) * AIRY_SQRT_PI_INV; break;
    }
    if (!real_ok(v)) return false;
    *out = v;
    return true;
}

static bool airy_real(int which, double x, double* out) {
    if (!isfinite(x)) return false;
    double v;
    if (x < SF_AIRY_NEG_LO) return airy_asym_neg(which, x, out);
    if (x < SF_AIRY_MID_LO) {
        v = airy_tab(AIRY_TAB_NEG[which], SF_AIRY_NEG_LO, SF_AIRY_NEG_N, SF_AIRY_NEG_DEG,
                     (SF_AIRY_NEG_HI - SF_AIRY_NEG_LO) / SF_AIRY_NEG_N, x);
    } else if (x < SF_AIRY_POS_LO) {
        v = airy_tab(AIRY_TAB_MID[which], SF_AIRY_MID_LO, SF_AIRY_MID_N, SF_AIRY_MID_DEG,
                     (SF_AIRY_MID_HI - SF_AIRY_MID_LO) / SF_AIRY_MID_N, x);
    } else if (x < SF_AIRY_POS_HI) {
        double f = airy_tab(AIRY_TAB_POS[which], SF_AIRY_POS_LO, SF_AIRY_POS_N, SF_AIRY_POS_DEG,
                            (SF_AIRY_POS_HI - SF_AIRY_POS_LO) / SF_AIRY_POS_N, x);
        double zh, zl;
        airy_zeta_dd(x, &zh, &zl);
        if (which == AIRY_AI || which == AIRY_AIP) v = f * (exp(-zh) * (1.0 - zl));
        else                                       v = f * (exp(zh) * (1.0 + zl));
    } else {
        return airy_asym_pos(which, x, out);
    }
    if (!real_ok(v)) return false;
    *out = v;
    return true;
}

bool sf_airy_ai_r(double x, double* out)  { return airy_real(AIRY_AI, x, out); }
bool sf_airy_aip_r(double x, double* out) { return airy_real(AIRY_AIP, x, out); }
bool sf_airy_bi_r(double x, double* out)  { return airy_real(AIRY_BI, x, out); }
bool sf_airy_bip_r(double x, double* out) { return airy_real(AIRY_BIP, x, out); }

