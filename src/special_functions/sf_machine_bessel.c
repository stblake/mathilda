/* ---- I_0, I_1, K_0, K_1 of a real x > 0 ----------------------------------
 *
 * The orders the real line meets most get their own ~1 ulp kernels (the
 * generic core above composes Steed's CF2, CF1 and the Wronskian and lands at
 * a few ulps). Regions as in Cephes i0/i1/k0/k1, the fits regenerated by
 * tools/sf_accuracy/gen_bessel01_tables.py (see there for the method):
 *   I: x <= 2 ascending series in t = x^2/4 (positive terms); 2 < x < 32
 *      piecewise Chebyshev fits of I e^-x; x >= 32 Hankel (DLMF 10.40.1).
 *   K: x <= 1/2 the log series (DLMF 10.31.1/2); 1/2 < x < 32 piecewise fits
 *      of K e^x; x >= 32 Hankel (DLMF 10.40.2).
 * The exponential is never fitted: exp() carries it, for exact x. */
static inline double bes_tab(const double* tab, double lo, int nint, int deg,
                             double w, double x) {
    int i = (int)((x - lo) / w);
    if (i < 0) i = 0;
    if (i >= nint) i = nint - 1;
    double c = lo + ((double)i + 0.5) * w;
    return horner(tab + (size_t)i * (size_t)(deg + 1), deg, (x - c) * (2.0 / w));
}
#define BES_REGION(R, T, x) \
    bes_tab(T, SF_BES_##R##_LO, SF_BES_##R##_N, SF_BES_##R##_DEG, \
            (SF_BES_##R##_HI - SF_BES_##R##_LO) / SF_BES_##R##_N, x)

static double bes_i01(int nu, double x) {             /* x > 0 */
    if (x <= 2.0) {
        double t = 0.25 * x * x;
        return nu == 0 ? horner(sf_bes_ser_i0, SF_BES_NSER - 1, t)
                       : 0.5 * x * horner(sf_bes_ser_i1, SF_BES_NSER - 1, t);
    }
    if (x < SF_BES_IB_LO)
        return exp(x) * BES_REGION(IA, nu == 0 ? sf_bes_tab_ia_i0 : sf_bes_tab_ia_i1, x);
    if (x < SF_BES_IB_HI)
        return exp(x) * BES_REGION(IB, nu == 0 ? sf_bes_tab_ib_i0 : sf_bes_tab_ib_i1, x);
    double s = horner(nu == 0 ? sf_bes_asy_i0 : sf_bes_asy_i1, SF_BES_NASYM - 1, 1.0 / x);
    return exp(x) * (s / sqrt(x));
}

static double bes_k01(int nu, double x) {             /* x > 0 */
    if (x <= SF_BES_KA_LO) {
        double t = 0.25 * x * x, l = log(0.5 * x);
        if (nu == 0)
            return fma(-l, horner(sf_bes_ser_i0, SF_BES_NSER - 1, t),
                       horner(sf_bes_ser_k0, SF_BES_NSER - 1, t));
        double i1 = 0.5 * x * horner(sf_bes_ser_i1, SF_BES_NSER - 1, t);
        return 1.0 / x + fma(l, i1, -0.25 * x * horner(sf_bes_ser_k1, SF_BES_NSER - 1, t));
    }
    if (x < SF_BES_KB_LO)
        return exp(-x) * BES_REGION(KA, nu == 0 ? sf_bes_tab_ka_k0 : sf_bes_tab_ka_k1, x);
    if (x < SF_BES_KC_LO)
        return exp(-x) * BES_REGION(KB, nu == 0 ? sf_bes_tab_kb_k0 : sf_bes_tab_kb_k1, x);
    if (x < SF_BES_KD_LO)
        return exp(-x) * BES_REGION(KC, nu == 0 ? sf_bes_tab_kc_k0 : sf_bes_tab_kc_k1, x);
    if (x < SF_BES_KD_HI)
        return exp(-x) * BES_REGION(KD, nu == 0 ? sf_bes_tab_kd_k0 : sf_bes_tab_kd_k1, x);
    double s = horner(nu == 0 ? sf_bes_asy_k0 : sf_bes_asy_k1, SF_BES_NASYM - 1, 1.0 / x);
    return exp(-x) * (s / sqrt(x));
}

/* Integer orders of J and Y on the real line go to the C library's jn / yn
 * (measured <= 2.7 ulp of the local magnitude over the benchmark domain and
 * a wide band, tools/sf_accuracy/bessel.py), reflected by hand so a negative
 * order does not depend on the library's convention. */
#define BS_LIBM_NMAX 200.0

bool sf_bessel_j_r(double nu, double x, double* out) {
    if (!isfinite(nu) || !isfinite(x)) return false;
    if (nu == floor(nu) && fabs(nu) <= BS_LIBM_NMAX) {
        int n = (int)fabs(nu);
        double v = jn(n, x);
        if (nu < 0.0 && (n & 1)) v = -v;
        if (!real_ok(v)) return false;
        *out = v;
        return true;
    }
    if (x == 0.0) {
        if (nu > 0.0) { *out = 0.0; return true; }
        return false;                             /* pole (or integer: above) */
    }
    if (x < 0.0) return false;                    /* complex */
    double re, im;
    if (!sf_bessel_j_c(nu, x, 0.0, &re, &im)) return false;
    *out = re;
    return true;
}

bool sf_bessel_y_r(double nu, double x, double* out) {
    if (!isfinite(nu) || !(x > 0.0) || !isfinite(x)) return false;
    if (nu == floor(nu) && fabs(nu) <= BS_LIBM_NMAX) {
        int n = (int)fabs(nu);
        double v = yn(n, x);
        if (nu < 0.0 && (n & 1)) v = -v;
        if (!real_ok(v)) return false;
        *out = v;
        return true;
    }
    double re, im;
    if (!sf_bessel_y_c(nu, x, 0.0, &re, &im)) return false;
    *out = re;
    return true;
}

bool sf_bessel_i_r(double nu, double x, double* out) {
    if (!isfinite(nu) || !isfinite(x)) return false;
    bool isint = (nu == floor(nu));
    if (x == 0.0) {
        if (nu == 0.0) { *out = 1.0; return true; }
        if (nu > 0.0 || isint) { *out = 0.0; return true; }
        return false;
    }
    if (x < 0.0 && !isint) return false;          /* complex */
    double re, im;
    if (isint && fabs(nu) <= 1.0) {
        re = bes_i01((int)fabs(nu), fabs(x));
        if (!real_ok(re)) return false;
    } else if (!sf_bessel_i_c(nu, fabs(x), 0.0, &re, &im)) return false;
    if (x < 0.0 && fmod(fabs(nu), 2.0) == 1.0) re = -re;
    *out = re;
    return true;
}

bool sf_bessel_k_r(double nu, double x, double* out) {
    if (!isfinite(nu) || !(x > 0.0) || !isfinite(x)) return false;
    nu = fabs(nu);
    if (nu == floor(nu) && nu <= BS_MAXNU) {
        /* K_0, K_1 from the tables, then UPWARD recurrence (stable for K):
         * K_{k+1} = K_{k-1} + (2k/x) K_k */
        double k0 = bes_k01(0, x);
        double v = k0;
        if (nu >= 1.0) {
            double k1 = bes_k01(1, x);
            int n = (int)nu;
            for (int k = 1; k < n; k++) {
                double kn = fma(2.0 * (double)k / x, k1, k0);
                k0 = k1; k1 = kn;
                if (!isfinite(k1)) return false;
            }
            v = k1;
        }
        if (!real_ok(v) || v == 0.0) return false;    /* underflow */
        *out = v;
        return true;
    }
    double re, im;
    if (!sf_bessel_k_c(nu, x, 0.0, &re, &im)) return false;
    *out = re;
    return true;
}

