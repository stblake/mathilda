static bool order_ok(double nu) { return isfinite(nu) && fabs(nu) <= BS_MAXNU; }

bool sf_bessel_i_c(double nu, double zr, double zi, double* rr, double* ri) {
    if (!order_ok(nu) || !isfinite(zr) || !isfinite(zi)) return false;
    if (zr == 0.0 && zi == 0.0) return false;
    if (zi == 0.0 && zr < 0.0) {
        /* the cut, upper side: I_nu(-x) = e^{i nu pi} I_nu(x) (DLMF 10.34.1) */
        double v;
        if (!sf_bessel_i_r(nu, -zr, &v)) return false;
        cx I = cscal(cispi(nu), v);
        if (!cx_ok(I)) return false;
        *rr = I.re; *ri = I.im;
        return true;
    }
    bool isint = (nu == floor(nu));
    if (isint) nu = fabs(nu);
    cx I, K, z = cxm(zr, zi);
    if (zr >= 0.0) {
        if (!ik_any_rhp(nu, z, false, &I, &K)) return false;
    } else {
        cx w = cneg(z);
        if (!ik_any_rhp(nu, w, false, &I, &K)) return false;
        double sg = (zi < 0.0) ? -1.0 : 1.0;
        I = cmul(cispi(sg * nu), I);
    }
    if (zi == 0.0 && (zr > 0.0 || isint)) I.im = 0.0;
    if (!cx_ok(I)) return false;
    *rr = I.re; *ri = I.im;
    return true;
}

bool sf_bessel_k_c(double nu, double zr, double zi, double* rr, double* ri) {
    if (!order_ok(nu) || !isfinite(zr) || !isfinite(zi)) return false;
    if (zr == 0.0 && zi == 0.0) return false;
    nu = fabs(nu);
    if (zi == 0.0 && zr < 0.0) {
        /* the cut, upper side (DLMF 10.34.2, m = 1):
         *   K_nu(-x) = e^{-i nu pi} K_nu(x) - i pi I_nu(x) */
        double k, i;
        if (!sf_bessel_k_r(nu, -zr, &k) || !sf_bessel_i_r(nu, -zr, &i)) return false;
        cx K = csub(cscal(cispi(-nu), k), cxm(0.0, M_PI * i));
        if (!cx_ok(K)) return false;
        *rr = K.re; *ri = K.im;
        return true;
    }
    cx Iv, Kv, I1, K1, z = cxm(zr, zi), K;
    if (zr >= 0.0) {
        if (!ik_rhp(nu, z, NEED_K, &Iv, &Kv, &I1, &K1)) return false;
        K = Kv;
    } else {
        cx w = cneg(z);
        if (!ik_rhp(nu, w, NEED_I | NEED_K, &Iv, &Kv, &I1, &K1)) return false;
        double sg = (zi < 0.0) ? -1.0 : 1.0;
        /* K(w e^{s i pi}) = e^{-s i nu pi} K(w) - s i pi I(w) */
        K = csub(cmul(cispi(-sg * nu), Kv), cscal(cmuli(Iv), sg * M_PI));
    }
    if (zi == 0.0 && zr > 0.0) K.im = 0.0;
    if (!cx_ok(K)) return false;
    *rr = K.re; *ri = K.im;
    return true;
}

/* J_nu(z) and (if want_y) Y_nu(z) off the cut, through u = -i z (Re u >= 0
 * once Im z >= 0; conjugate symmetry below the axis):
 *   J_a = e^{i a pi/2} I_a(u),  Y_a = -(2/pi) e^{-i a pi/2} K_a(u) + i e^{i a pi/2} I_a(u)
 * at a = |nu|, and a negative order by the reflections (DLMF 10.4.7-8)
 *   J_{-a} = cos(a pi) J_a - sin(a pi) Y_a,  Y_{-a} = sin(a pi) J_a + cos(a pi) Y_a,
 * which keep J and Y apart where the I/K form of a negative order would make
 * two large terms cancel (near half-integer orders). */
static bool jy_core(double nu, double zr, double zi, bool want_y, cx* Jo, cx* Yo) {
    bool lower = zi < 0.0;
    if (lower) zi = -zi;
    cx u = cxm(zi, -zr);                         /* -i z, Re u >= 0 */
    double a = fabs(nu);
    bool isint = (nu == floor(nu));
    bool need_y = want_y || (nu < 0.0 && !isint);
    cx Iv = cxm(0.0, 0.0), Kv = Iv, I1 = Iv, K1 = Iv;
    if (!ik_rhp(a, u, NEED_I | (need_y ? NEED_K : 0), &Iv, &Kv, &I1, &K1)) return false;
    cx ph = cispi(0.5 * a);
    cx J = cmul(ph, Iv);
    cx Y = cxm(0.0, 0.0);
    if (need_y)
        Y = cadd(cscal(cmul(cconj(ph), Kv), -2.0 / M_PI), cmuli(J));
    if (nu < 0.0) {
        if (isint) {
            if (fmod(a, 2.0) == 1.0) { J = cneg(J); Y = cneg(Y); }
        } else {
            double s, c; sincospi(a, &s, &c);
            cx Jn = csub(cscal(J, c), cscal(Y, s));
            cx Yn = cadd(cscal(J, s), cscal(Y, c));
            J = Jn; Y = Yn;
        }
    }
    if (lower) { J = cconj(J); Y = cconj(Y); }
    *Jo = J; *Yo = Y;
    return cfinite(J) && (!want_y || cfinite(Y));
}

bool sf_bessel_j_c(double nu, double zr, double zi, double* rr, double* ri) {
    if (!order_ok(nu) || !isfinite(zr) || !isfinite(zi)) return false;
    if (zr == 0.0 && zi == 0.0) return false;
    if (zi == 0.0 && zr < 0.0) {
        /* the cut, upper side: J_nu(-x) = e^{i nu pi} J_nu(x) (DLMF 10.11.1),
         * so the modulus is the real kernel's and the phase is exact */
        double v;
        if (!sf_bessel_j_r(nu, -zr, &v)) return false;
        cx J = cscal(cispi(nu), v);
        if (!cx_ok(J)) return false;
        *rr = J.re; *ri = J.im;
        return true;
    }
    cx J, Y;
    if (!jy_core(nu, zr, zi, false, &J, &Y)) return false;
    if (zi == 0.0 && (zr > 0.0 || nu == floor(nu))) J.im = 0.0;
    if (!cx_ok(J)) return false;
    *rr = J.re; *ri = J.im;
    return true;
}

bool sf_bessel_y_c(double nu, double zr, double zi, double* rr, double* ri) {
    if (!order_ok(nu) || !isfinite(zr) || !isfinite(zi)) return false;
    if (zr == 0.0 && zi == 0.0) return false;
    if (zi == 0.0 && zr < 0.0) {
        /* the cut, upper side (DLMF 10.11.2, m = 1):
         *   Y_nu(-x) = e^{-i nu pi} Y_nu(x) + 2 i cos(nu pi) J_nu(x) */
        double y, j, s, c;
        if (!sf_bessel_y_r(nu, -zr, &y) || !sf_bessel_j_r(nu, -zr, &j)) return false;
        sincospi(nu, &s, &c);
        cx Y = cadd(cscal(cxm(c, -s), y), cxm(0.0, 2.0 * c * j));
        if (!cx_ok(Y)) return false;
        *rr = Y.re; *ri = Y.im;
        return true;
    }
    cx J, Y;
    if (!jy_core(nu, zr, zi, true, &J, &Y)) return false;
    if (zi == 0.0 && zr > 0.0) Y.im = 0.0;
    if (!cx_ok(Y)) return false;
    *rr = Y.re; *ri = Y.im;
    return true;
}

