/* sf_machine_bessel.c -- raw-double Bessel J/Y/I/K and Airy kernels, real and
 * complex. See sf_machine_bessel.h for the contract.
 *
 * ------------------------------------------------------------------------
 * Bessel functions of complex argument (real order)
 * ------------------------------------------------------------------------
 * The scheme is Amos's (D. E. Amos, "A portable package for Bessel functions
 * of a complex argument and nonnegative order", ACM TOMS 12 (1986) 265-273,
 * Algorithm 644): every function is reduced to I_nu and K_nu of an argument in
 * the closed RIGHT half plane, where they are computed by a small set of
 * regional methods, and then carried to the rest of the plane by the
 * analytic-continuation and connection formulas.
 *
 *   J_nu(z) = e^{i nu pi/2} I_nu(-i z)                        (DLMF 10.27.6)
 *   Y_nu(z) = -(2/pi) e^{-i nu pi/2} K_nu(-i z)
 *             + i e^{i nu pi/2} I_nu(-i z)          (from 10.27.8 and 10.4.4)
 *       for Im z >= 0 (Re(-iz) = Im z >= 0); conjugate symmetry otherwise.
 *   I_nu(z e^{+-i pi}) = e^{+-i nu pi} I_nu(z)                (DLMF 10.34.1)
 *   K_nu(z e^{+-i pi}) = e^{-+i nu pi} K_nu(z) -+ i pi I_nu(z) (DLMF 10.34.2)
 *   I_{-nu} = I_nu + (2/pi) sin(nu pi) K_nu,   K_{-nu} = K_nu  (DLMF 10.27.2/3)
 *
 * In the right half plane, with nu = n + mu, |mu| <= 1/2:
 *   - |z| large (|z| >= 21, nu^2 < |z|): the Hankel asymptotic expansions
 *     (DLMF 10.40.2, 10.40.5), summed until the term falls below 2^-56 of
 *     the sum -- at |z| >= 21 the smallest term is ~e^{-2|z|} < 1e-18;
 *   - K_mu, K_{mu+1} for |z| <= 2: Temme's series (N. M. Temme, "On the
 *     numerical evaluation of the modified Bessel function of the third
 *     kind", J. Comput. Phys. 19 (1975) 324-337), with 1/Gamma(1 +- mu)
 *     from its Taylor series (DLMF 5.7.1);
 *   - K_mu, K_{mu+1} for 2 < |z| < 21: for mu = 0 and mu = -+1/3 (the integer
 *     and the Airy orders) Taylor continuation of the modified Bessel equation
 *     from tabulated nodes (ktab_eval); for any other mu, Steed's algorithm
 *     for Temme's continued fraction CF2 (I. J. Thompson and A. R. Barnett,
 *     "Modified Bessel functions I_nu(z) and K_nu(z) of real order and complex
 *     argument, to selected accuracy", Comput. Phys. Commun. 47 (1987)
 *     245-257), which is accurate but needs 30-160 iterations there;
 *   - K_nu, K_{nu+1} by UPWARD recurrence from K_mu, K_{mu+1} (the stable
 *     direction for K);
 *   - I_nu: the ascending series where |z|^2/4 <= nu + 1 (terms decrease from
 *     the first, so the sum cannot cancel badly), otherwise Miller's backward
 *     recurrence normalised by a Gegenbauer / Neumann sum (i_miller; Amos's
 *     CMLRI). It needs no K, so I and J cost ~|z| complex multiplies.
 * Orders are capped (|nu| <= 1000): beyond that the uniform (Debye)
 * expansions would be the right tool and are not implemented, so the kernel
 * declines and the MPFR path answers.
 *
 * ------------------------------------------------------------------------
 * Airy functions
 * ------------------------------------------------------------------------
 * REAL x: piecewise polynomials generated by tools/sf_accuracy/
 * gen_airy_tables.py (Chebyshev interpolation at 50 digits, converted to the
 * monomial basis on each interval) for -10 <= x <= 10 -- the functions
 * themselves on [-10, 2], and on [2, 10] the scaled Ai e^zeta, Bi e^-zeta, so
 * the exponential is carried by exp() -- and the Poincare asymptotic expansions
 * (DLMF 9.7.5-9.7.12) beyond. zeta = (2/3) x^{3/2} is formed in double-double
 * there: the functions are ill-conditioned in zeta (an absolute error d in zeta
 * is a relative error d in e^{-zeta}), and a plain double zeta at x = 100 would
 * already cost ~600 ulps.
 *
 * COMPLEX z: the Maclaurin series for |z| <= 1, and beyond it the Bessel
 * representations of DLMF 9.6.1-9.6.3,
 *   Ai(z)  = (1/pi) sqrt(z/3) K_{1/3}(zeta),
 *   Ai'(z) = -(z/(pi sqrt 3)) K_{2/3}(zeta),
 *   Bi(z)  = sqrt(z/3) (I_{-1/3}(zeta) + I_{1/3}(zeta)),
 *   Bi'(z) = (z/sqrt 3) (I_{-2/3}(zeta) + I_{2/3}(zeta)),
 * with zeta on the sheet arg zeta = (3/2) arg z, |arg zeta| <= 3 pi/2: where
 * Re zeta < 0 the I/K continuation formulas above carry it back to the right
 * half plane (Amos's CAIRY/CBIRY do the same). One core call at order -1/3
 * yields all four of I_{-1/3}, K_{1/3}, I_{2/3}, K_{2/3}. The double-double
 * zeta's low part is folded back in by first-order Taylor correction,
 * d Ai/d zeta = Ai'/sqrt z, d Ai'/d zeta = sqrt z Ai (from Ai'' = z Ai).
 */
#include "sf_machine_bessel.h"
