/* Rational coefficient R(k) of F(a; b) when every upper parameter pairs by
 * an integer difference with a lower parameter or with the 1 of k!; NULL
 * otherwise. */
static Expr* lerch_coefficient(Expr* const* A, int np, Expr* const* B, int nq,
                               const Expr* k) {
    if (np != nq + 1 || np > HR_MAXD) return NULL;
    Expr* L[HR_MAXD + 1];
    int nl = 0;
    for (int j = 0; j < nq; j++) L[nl++] = B[j];
    Expr* one = expr_new_integer(1);
    L[nl++] = one;
    bool used[HR_MAXD + 1] = { false };
    Expr* fac[4 * HR_MAXPOST + 8];
    int nf = 0;
    bool ok = true;
    for (int i = 0; i < np && ok; i++) {
        HrPar pa;
        if (!hr_par_split(A[i], &pa)) { ok = false; break; }
        int pick = -1; int64_t dn = 0;
        for (int j = 0; j < nl; j++) {
            if (used[j]) continue;
            HrPar pb;
            if (!hr_par_split(L[j], &pb)) continue;
            int64_t dd;
            bool hit = par_int_diff(&pa, &pb, &dd) && dd >= -HR_MAXPOST && dd <= HR_MAXPOST;
            hr_par_free(&pb);
            if (hit) { pick = j; dn = dd; break; }
        }
        hr_par_free(&pa);
        if (pick < 0) { ok = false; break; }
        used[pick] = true;
        /* (a)_k/(b)_k, a = b + dn */
        const Expr* bb = L[pick];
        if (dn > 0) {
            for (int64_t m = 0; m < dn && nf < (int)(sizeof fac / sizeof fac[0]) - 1; m++)
                fac[nf++] = mk2(SYM_Times,
                    mk2(SYM_Plus, mk2(SYM_Plus, expr_copy((Expr*)bb), expr_copy((Expr*)k)),
                        expr_new_integer(m)),
                    mk2(SYM_Power, mk2(SYM_Plus, expr_copy((Expr*)bb), expr_new_integer(m)),
                        expr_new_integer(-1)));
        } else if (dn < 0) {
            for (int64_t m = 0; m < -dn && nf < (int)(sizeof fac / sizeof fac[0]) - 1; m++)
                fac[nf++] = mk2(SYM_Times,
                    mk2(SYM_Plus, expr_copy(A[i]), expr_new_integer(m)),
                    mk2(SYM_Power,
                        mk2(SYM_Plus, mk2(SYM_Plus, expr_copy(A[i]), expr_copy((Expr*)k)),
                            expr_new_integer(m)),
                        expr_new_integer(-1)));
        }
    }
    expr_free(one);
    if (!ok) { for (int i = 0; i < nf; i++) expr_free(fac[i]); return NULL; }
    if (nf == 0) return expr_new_integer(1);
    return ev(mk1(SYM_Together, expr_new_function(expr_new_symbol(SYM_Times), fac, (size_t)nf)));
}

/* The formula is a theorem, but its assembly here (pairing, Apart, range
 * reduction, roots of unity) is code. The result in w is checked against
 * the series, as a generated certificate is, before it is used. */
static bool verify_cert(const Expr* f0, Expr* const* a0, int p, Expr* const* b0, int q);

static Expr* lerch_closed(Expr* const* A, int np, Expr* const* B, int nq, const Expr* z) {
    Expr* k = expr_new_symbol("Hrep`k");
    Expr* R = lerch_coefficient(A, np, B, nq, k);
    Expr* out = NULL;
    if (R) {
        Expr* r = ev(expr_new_function(expr_new_symbol("Hrep`lerch"),
                     (Expr*[]){ R, expr_copy(k), expr_new_symbol(HR_W) }, 3));
        if (r && closed_finite(r) && !(r->type == EXPR_SYMBOL &&
                                       strcmp(r->data.symbol.name, "$Failed") == 0) &&
            verify_cert(r, A, np, B, nq)) {
            Expr* rz = hr_subst(r, HR_W, z);
            out = hr_tidy(rz);
        }
        if (r) expr_free(r);
    }
    expr_free(k);
    return out;
}


/* The Formula algorithm on (a; b), no transformations. */
static Expr* pfq_direct(Expr* const* a, size_t p, Expr* const* b, size_t q,
                        const Expr* z, int pass) {
    if (p > HR_MAXD || q > HR_MAXD) return NULL;
    /* Copy, cancel equal upper/lower pairs, sort. */
    Expr* A[HR_MAXD]; Expr* B[HR_MAXD];
    int np = 0, nq = 0;
    for (size_t i = 0; i < p; i++) A[np++] = expr_copy(a[i]);
    for (size_t j = 0; j < q; j++) {
        bool cancelled = false;
        for (int i = 0; i < np; i++) {
            if (expr_eq(A[i], b[j])) {
                expr_free(A[i]);
                A[i] = A[--np];
                cancelled = true;
                break;
            }
        }
        if (!cancelled) B[nq++] = expr_copy(b[j]);
    }
    qsort(A, (size_t)np, sizeof(Expr*), expr_sort_cmp);
    qsort(B, (size_t)nq, sizeof(Expr*), expr_sort_cmp);
    /* A lower parameter that is a nonpositive integer: undefined; an upper
     * one: a polynomial, which HypergeometricPFQ already expands. */
    Expr* out = NULL;
    for (int i = 0; i < np; i++) {
        int64_t n, d;
        if (is_rational(A[i], &n, &d) && d == 1 && n <= 0) goto done;
    }
    for (int j = 0; j < nq; j++) {
        int64_t n, d;
        if (is_rational(B[j], &n, &d) && d == 1 && n <= 0) goto done;
    }
    /* Certificates and the derivative formula first; then the Lerch Phi
     * formula, which is exact and cheap; then certificates generated by
     * integration, which call Integrate. */
    {
        bool saved = hr_allow_integration;
        hr_allow_integration = (pass == 1);
        HrAnswer ans; memset(&ans, 0, sizeof ans);
        if (solve_module(A, np, B, nq, &ans, 0)) {
            out = answer_expr(&ans, z);
            answer_free(&ans);
        }
        hr_allow_integration = saved;
        if (!out && pass == 0) out = lerch_closed(A, np, B, nq, z);
    }
done:
    for (int i = 0; i < np; i++) expr_free(A[i]);
    for (int j = 0; j < nq; j++) expr_free(B[j]);
    return out;
}

/* prefactor * (closed form of F(a'; b'; z')), or NULL. Consumes pre, zz and
 * the parameter arrays' contents. */
static Expr* via_image(Expr* pre, Expr** A, size_t p, Expr** B, size_t q, Expr* zz,
                       int pass) {
    Expr* r = pfq_direct(A, p, B, q, zz, pass);
    for (size_t i = 0; i < p; i++) expr_free(A[i]);
    for (size_t j = 0; j < q; j++) expr_free(B[j]);
    expr_free(zz);
    if (!r) { expr_free(pre); return NULL; }
    return hr_tidy(mk2(SYM_Times, pre, r));
}

static Expr* neg(Expr* e) { return mk2(SYM_Times, expr_new_integer(-1), e); }
static Expr* sub2(const Expr* x, const Expr* y) {
    return ev(mk2(SYM_Plus, expr_copy((Expr*)x), neg(expr_copy((Expr*)y))));
}

