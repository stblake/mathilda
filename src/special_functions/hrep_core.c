/*
 * hrep_core.c -- Roach's Formula algorithm for pFq (ISSAC '96).
 *
 * ---------------------------------------------------------------------
 * The module
 * ---------------------------------------------------------------------
 * Let theta = w d/dw. F(a;b;w) satisfies
 *
 *     L F = [ w U(theta) - V(theta) ] F = 0,
 *     U(theta) = prod_j (theta + a_j),   V(theta) = theta prod_k (theta + b_k - 1),
 *
 * an ODE of order d = max(p, q+1). Every contiguous F(a + m; b + n; w)
 * (m, n integer vectors) lies in the Q(params)(w)-module spanned by the
 * companion basis of the origin (a0; b0):
 *
 *     B = [ f0, theta f0, ..., theta^(d-1) f0 ],   f0 = F(a0; b0; w),
 *
 * and theta acts on a coefficient row vector C (meaning C . B) by
 *
 *     (theta C)_k = w C_k' + C_(k-1) + C_(d-1) c_k,
 *
 * where theta^d f0 = sum_k c_k theta^k f0 is read off the origin's ODE.
 * A certificate is therefore just (a0, b0, f0): the derivative matrix is
 * never entered by hand. This is Roach's [a0, b0, B, C, M, rho] with
 * B the companion basis, M its companion matrix and rho = 1.
 *
 * ---------------------------------------------------------------------
 * Shift and inverse-shift operators (Roach '96 sec. 3-5)
 * ---------------------------------------------------------------------
 *   A_i   : a_i -> a_i + 1   F <- F + theta F / a_i                 (a_i != 0)
 *   B_i   : b_i -> b_i - 1   F <- F + theta F / (b_i - 1)           (b_i != 1)
 *
 * Each inverse is one polynomial division of the ODE by the shift's linear
 * theta factor. The remainder constant is exactly Roach's alpha_0 / beta_0
 * definedness condition.
 *
 *   A_i^-1 : a_i -> a' = a_i - 1. With (theta + a') G = a' F and the ODE of
 *            G, write V = Q (theta + a') + r, r = V(-a'). Then
 *               G = (a'/r) [ w prod_{j != i} (theta + a_j) - Q(theta) ] F,
 *            defined iff r = (1 - a_i) prod_k (b_k - a_i) != 0.
 *   B_i^-1 : b_i -> b_i + 1. With (theta + b_i) H = b_i F, write
 *            U = Q (theta + b_i) + r, r = U(-b_i). Then
 *               H = (b_i/r) [ w^-1 theta prod_{k != i} (theta + b_k - 1)
 *                              - Q(theta) ] F,
 *            defined iff r = prod_j (a_j - b_i) != 0 and b_i != 0.
 *
 * ---------------------------------------------------------------------
 * Strategy (Roach '96 sec. 8-11)
 * ---------------------------------------------------------------------
 * Parameters split into residue classes (symbolic part, rational part mod 1).
 * A certificate matches when each class holds the same numbers of upper and
 * lower parameters; they pair in sorted order. Each parameter then moves to
 * its target in one bucket. Down-movers go in ascending target order and
 * up-movers in descending order: Roach's Y-below-Y0 left-to-right /
 * Y-above-Y0 right-to-left rule. Every step is checked as it is taken, and
 * a step whose definedness constant vanishes abandons the candidate. The
 * answer is never a guess: either the walk is proper and the result is an
 * identity, or the next candidate is tried.
 *
 * Derivative formula (Roach '96 sec. 17): when an upper parameter exceeds a
 * lower one by n in Z+, F(a, c; b, d) = P(theta) F(c; d) with
 * P(l) = (b + l)_n / (b)_n. The reduced function is solved recursively and
 * P(theta) is applied in its module.
 *
 * Symbolic parameters are generic: a definedness constant that is a nonzero
 * rational function of them counts as nonzero. That is the usual meaning of
 * a CAS identity in symbolic parameters, and it is what
 * FunctionExpand[HypergeometricPFQ[...]] promises.
 *
 * Arithmetic is native FLINT fmpz_mpoly_q through TowerCRE handles; Expr is
 * touched only to read parameters and to assemble the answer. Without
 * FLINT every entry declines.
 *
 * Memory: every Expr built here is owned and freed here. The TowerCRE
 * arena is released in one tcre_free per solve.
 */

