static Expr* mk1(const char* h, Expr* a) {
    return expr_new_function(expr_new_symbol(h), (Expr*[]){ a }, 1);
}
static Expr* mk2(const char* h, Expr* a, Expr* b) {
    return expr_new_function(expr_new_symbol(h), (Expr*[]){ a, b }, 2);
}
static Expr* ev(Expr* e) { return eval_and_free(e); }

/* e /. sym -> val, evaluated. Borrows e and val. */
Expr* hr_subst(const Expr* e, const char* sym, const Expr* val) {
    Expr* rule = mk2(SYM_Rule, expr_new_symbol(sym), expr_copy((Expr*)val));
    return ev(mk2(SYM_ReplaceAll, expr_copy((Expr*)e), rule));
}

static bool is_head(const Expr* e, const char* h) {
    return e && e->type == EXPR_FUNCTION &&
           e->data.function.head->type == EXPR_SYMBOL &&
           e->data.function.head->data.symbol.name == h;
}

/* Collect the symbols of e (other than heads) into names[], deduplicated.
 * Returns false when there are more than cap of them. */
static bool collect_symbols(const Expr* e, const char** names, int* n, int cap) {
    if (!e) return true;
    if (e->type == EXPR_SYMBOL) {
        const char* s = e->data.symbol.name;
        for (int i = 0; i < *n; i++) if (strcmp(names[i], s) == 0) return true;
        if (*n >= cap) return false;
        names[(*n)++] = s;
        return true;
    }
    if (e->type != EXPR_FUNCTION) return true;
    for (size_t i = 0; i < e->data.function.arg_count; i++)
        if (!collect_symbols(e->data.function.args[i], names, n, cap)) return false;
    return true;
}

/* ------------------------------------------------------------------ */
/*  Parameters: symbolic part + rational part                          */
/* ------------------------------------------------------------------ */

static int64_t gcd64(int64_t a, int64_t b) {
    if (a < 0) a = -a;
    if (b < 0) b = -b;
    while (b) { int64_t t = a % b; a = b; b = t; }
    return a ? a : 1;
}

/* Split e = sym + n/d (sym NULL when e is rational). The rational part is the
 * sum of the numeric terms of a Plus. Returns false when a rational part does
 * not fit in int64. */
bool hr_par_split(const Expr* e, HrPar* out) {
    out->sym = NULL; out->n = 0; out->d = 1;
    int64_t n, d;
    if (is_rational(e, &n, &d)) { out->n = n; out->d = d; return true; }
    if (is_head(e, SYM_Plus)) {
        size_t k = e->data.function.arg_count;
        Expr** rest = malloc(sizeof(Expr*) * k);
        size_t nr = 0;
        int64_t an = 0, ad = 1;
        for (size_t i = 0; i < k; i++) {
            Expr* t = e->data.function.args[i];
            if (is_rational(t, &n, &d)) {
                /* an/ad + n/d */
                int64_t g = gcd64(ad, d);
                int64_t l = ad / g * d;
                an = an * (l / ad) + n * (l / d);
                ad = l;
                int64_t h = gcd64(an, ad);
                an /= h; ad /= h;
            } else {
                rest[nr++] = expr_copy(t);
            }
        }
        if (nr == 0) { free(rest); out->n = an; out->d = ad; return true; }
        out->sym = (nr == 1) ? rest[0]
                 : ev(expr_new_function(expr_new_symbol(SYM_Plus), rest, nr));
        if (nr != 1) { /* expr_new_function took the array contents */ }
        free(rest);
        out->n = an; out->d = ad;
        return true;
    }
    /* (1 + n)/2 is Times[1/2, 1 + n]: split its expansion n/2 + 1/2, so it
     * lands in the residue class of n/2 */
    if (is_head(e, SYM_Times)) {
        Expr* x = ev(mk1("Expand", expr_copy((Expr*)e)));
        bool ok = is_head(x, SYM_Plus) && hr_par_split(x, out);
        expr_free(x);
        if (ok) return true;
        out->sym = NULL; out->n = 0; out->d = 1;
    }
    out->sym = expr_copy((Expr*)e);
    return true;
}

void hr_par_free(HrPar* p) {
    if (p->sym) expr_free(p->sym);
    p->sym = NULL;
}

static bool same_sym(const HrPar* x, const HrPar* y) {
    if (!x->sym || !y->sym) return x->sym == y->sym;
    return expr_eq(x->sym, y->sym);
}

/* x - y as an integer when x and y are in one residue class. */
static bool par_int_diff(const HrPar* x, const HrPar* y, int64_t* k) {
    if (!same_sym(x, y)) return false;
    /* x.n/x.d - y.n/y.d */
    int64_t g = gcd64(x->d, y->d);
    int64_t l = x->d / g * y->d;
    int64_t num = x->n * (l / x->d) - y->n * (l / y->d);
    if (num % l != 0) return false;
    *k = num / l;
    return true;
}

static double par_value(const HrPar* x) { return (double)x->n / (double)x->d; }

/* ------------------------------------------------------------------ */
/*  The module                                                         */
/* ------------------------------------------------------------------ */

typedef struct {
    TowerCRE* t;
    int d;
    int c[HR_MAXD];   /* theta^d f0 = sum c[k] theta^k f0 */
    int C[HR_MAXD];   /* current coefficients */
    int w, wi, one, zero;
} HrMod;

static int H(HrMod* m, const Expr* e) { return tcre_from_expr(m->t, e); }

/* out = theta in. */
static bool m_theta(HrMod* m, const int* in, int* out) {
    int d = m->d;
    for (int k = 0; k < d; k++) {
        int dk = tcre_deriv(m->t, in[k], HR_W);
        if (dk < 0) return false;
        int r = tcre_mul(m->t, m->w, dk);
        if (k > 0) r = tcre_add(m->t, r, in[k - 1]);
        int s = tcre_mul(m->t, in[d - 1], m->c[k]);
        r = tcre_add(m->t, r, s);
        if (r < 0) return false;
        out[k] = r;
    }
    return true;
}

/* out = (theta + alpha) in. */
static bool m_theta_plus(HrMod* m, int alpha, const int* in, int* out) {
    int tmp[HR_MAXD];
    if (!m_theta(m, in, tmp)) return false;
    for (int k = 0; k < m->d; k++) {
        out[k] = tcre_add(m->t, tmp[k], tcre_mul(m->t, alpha, in[k]));
        if (out[k] < 0) return false;
    }
    return true;
}

static void v_scale(HrMod* m, int s, const int* in, int* out) {
    for (int k = 0; k < m->d; k++) out[k] = tcre_mul(m->t, s, in[k]);
}
static void v_sub(HrMod* m, const int* x, const int* y, int* out) {
    for (int k = 0; k < m->d; k++) out[k] = tcre_sub(m->t, x[k], y[k]);
}
static void v_copy(HrMod* m, const int* x, int* out) {
    for (int k = 0; k < m->d; k++) out[k] = x[k];
}

/* Polynomials in theta with handle coefficients, p[0..deg]. */
typedef struct { int deg; int c[HR_MAXD + 2]; } HrPoly;

static void poly_one(HrMod* m, HrPoly* P) { P->deg = 0; P->c[0] = m->one; }

/* P <- P (theta + s) */
static void poly_mul_lin(HrMod* m, HrPoly* P, int s) {
    HrPoly R; R.deg = P->deg + 1;
    for (int k = 0; k <= R.deg; k++) R.c[k] = m->zero;
    for (int k = 0; k <= P->deg; k++) {
        R.c[k + 1] = tcre_add(m->t, R.c[k + 1], P->c[k]);
        R.c[k]     = tcre_add(m->t, R.c[k], tcre_mul(m->t, P->c[k], s));
    }
    *P = R;
}

/* P = Q (theta + s) + r: synthetic division at theta = -s. */
static void poly_div_lin(HrMod* m, const HrPoly* P, int s, HrPoly* Q, int* r) {
    int root = tcre_sub(m->t, m->zero, s);
    if (P->deg == 0) { Q->deg = 0; Q->c[0] = m->zero; *r = P->c[0]; return; }
    Q->deg = P->deg - 1;
    int acc = P->c[P->deg];
    for (int k = P->deg - 1; k >= 0; k--) {
        Q->c[k] = acc;
        acc = tcre_add(m->t, P->c[k], tcre_mul(m->t, root, acc));
    }
    *r = acc;
}

/* out = P(theta) in, by Horner. */
static bool m_apply_poly(HrMod* m, const HrPoly* P, const int* in, int* out) {
    int R[HR_MAXD], T[HR_MAXD];
    v_scale(m, P->c[P->deg], in, R);
    for (int k = P->deg - 1; k >= 0; k--) {
        if (!m_theta(m, R, T)) return false;
        for (int j = 0; j < m->d; j++)
            R[j] = tcre_add(m->t, T[j], tcre_mul(m->t, P->c[k], in[j]));
    }
    v_copy(m, R, out);
    return true;
}

/* Build the module of the origin (a0; b0): companion coefficients and
 * C = [1, 0, ..., 0]. */
static bool m_init(HrMod* m, int p, const int* a0, int q, const int* b0) {
    int d = (p > q + 1) ? p : q + 1;
    if (d > HR_MAXD || d < 1) return false;
    m->d = d;
    HrPoly U, V;
    poly_one(m, &U);
    for (int j = 0; j < p; j++) poly_mul_lin(m, &U, a0[j]);
    poly_one(m, &V);
    poly_mul_lin(m, &V, m->zero);                    /* theta */
    for (int k = 0; k < q; k++)
        poly_mul_lin(m, &V, tcre_sub(m->t, b0[k], m->one));
    /* L_j = w u_j - v_j, j = 0..d */
    int L[HR_MAXD + 1];
    for (int j = 0; j <= d; j++) {
        int u = (j <= U.deg) ? U.c[j] : m->zero;
        int v = (j <= V.deg) ? V.c[j] : m->zero;
        L[j] = tcre_sub(m->t, tcre_mul(m->t, m->w, u), v);
    }
    if (tcre_is_zero(m->t, L[d]) != 0) return false;
    int minus_inv = tcre_div(m->t, tcre_sub(m->t, m->zero, m->one), L[d]);
    for (int k = 0; k < d; k++) m->c[k] = tcre_mul(m->t, minus_inv, L[k]);
    m->C[0] = m->one;
    for (int k = 1; k < d; k++) m->C[k] = m->zero;
    return true;
}

/* ------------------------------------------------------------------ */
/*  Shift steps. a[], b[] are the current parameter handles; each step  */
/*  updates C and the moved parameter. Return false when undefined.     */
/* ------------------------------------------------------------------ */

static bool nonzero(HrMod* m, int h) { return tcre_is_zero(m->t, h) == 0; }

static bool step_a_up(HrMod* m, int* a, int i) {
    if (!nonzero(m, a[i])) return false;
    int T[HR_MAXD];
    if (!m_theta(m, m->C, T)) return false;
    int inv = tcre_div(m->t, m->one, a[i]);
    for (int k = 0; k < m->d; k++)
        m->C[k] = tcre_add(m->t, m->C[k], tcre_mul(m->t, inv, T[k]));
    a[i] = tcre_add(m->t, a[i], m->one);
    return true;
}

static bool step_b_down(HrMod* m, int* b, int i) {
    int bm1 = tcre_sub(m->t, b[i], m->one);
    if (!nonzero(m, bm1)) return false;
    int T[HR_MAXD];
    if (!m_theta(m, m->C, T)) return false;
    int inv = tcre_div(m->t, m->one, bm1);
    for (int k = 0; k < m->d; k++)
        m->C[k] = tcre_add(m->t, m->C[k], tcre_mul(m->t, inv, T[k]));
    b[i] = bm1;
    return true;
}

static bool step_a_down(HrMod* m, int p, int* a, int q, int* b, int i) {
    int ap = tcre_sub(m->t, a[i], m->one);            /* a' */
    HrPoly V; poly_one(m, &V);
    poly_mul_lin(m, &V, m->zero);
    for (int k = 0; k < q; k++) poly_mul_lin(m, &V, tcre_sub(m->t, b[k], m->one));
    HrPoly Q; int r;
    poly_div_lin(m, &V, ap, &Q, &r);
    if (!nonzero(m, r)) return false;
    /* S1 = w prod_{j != i} (theta + a_j) C */
    int S1[HR_MAXD], T[HR_MAXD];
    v_copy(m, m->C, S1);
    for (int j = 0; j < p; j++) {
        if (j == i) continue;
        if (!m_theta_plus(m, a[j], S1, T)) return false;
        v_copy(m, T, S1);
    }
    v_scale(m, m->w, S1, S1);
    int S2[HR_MAXD];
    if (!m_apply_poly(m, &Q, m->C, S2)) return false;
    v_sub(m, S1, S2, T);
    v_scale(m, tcre_div(m->t, ap, r), T, m->C);
    a[i] = ap;
    return true;
}

static bool step_b_up(HrMod* m, int p, int* a, int q, int* b, int i) {
    if (!nonzero(m, b[i])) return false;
    HrPoly U; poly_one(m, &U);
    for (int j = 0; j < p; j++) poly_mul_lin(m, &U, a[j]);
    HrPoly Q; int r;
    poly_div_lin(m, &U, b[i], &Q, &r);
    if (!nonzero(m, r)) return false;
    /* S1 = w^-1 theta prod_{k != i} (theta + b_k - 1) C */
    int S1[HR_MAXD], T[HR_MAXD];
    v_copy(m, m->C, S1);
    for (int k = 0; k < q; k++) {
        if (k == i) continue;
        if (!m_theta_plus(m, tcre_sub(m->t, b[k], m->one), S1, T)) return false;
        v_copy(m, T, S1);
    }
    if (!m_theta(m, S1, T)) return false;
    v_scale(m, m->wi, T, S1);
    int S2[HR_MAXD];
    if (!m_apply_poly(m, &Q, m->C, S2)) return false;
    v_sub(m, S1, S2, T);
    v_scale(m, tcre_div(m->t, b[i], r), T, m->C);
    b[i] = tcre_add(m->t, b[i], m->one);
    return true;
}

/* ------------------------------------------------------------------ */
/*  A walk: one candidate (certificate instance + pairing)             */
/* ------------------------------------------------------------------ */

typedef struct {
    bool is_a;     /* upper (true) or lower parameter */
    int idx;       /* index into the current a[] / b[] arrays */
    int64_t k;     /* signed number of unit steps (target - origin) */
    double tval;   /* target value, for the ordering rule */
} HrMove;

static int move_cmp(const void* x, const void* y) {
    const HrMove* u = x; const HrMove* v = y;
    bool du = u->k < 0, dv = v->k < 0;
    if (du != dv) return du ? -1 : 1;           /* down-movers first */
    if (du) return (u->tval < v->tval) ? -1 : (u->tval > v->tval);   /* ascending */
    return (u->tval > v->tval) ? -1 : (u->tval < v->tval);           /* descending */
}

static bool run_moves(HrMod* m, int p, int* a, int q, int* b,
                      HrMove* mv, int nm) {
    qsort(mv, (size_t)nm, sizeof *mv, move_cmp);
    for (int s = 0; s < nm; s++) {
        int64_t k = mv[s].k;
        for (int64_t j = 0; j < (k < 0 ? -k : k); j++) {
            bool ok;
            if (mv[s].is_a) ok = (k > 0) ? step_a_up(m, a, mv[s].idx)
                                         : step_a_down(m, p, a, q, b, mv[s].idx);
            else            ok = (k < 0) ? step_b_down(m, b, mv[s].idx)
                                         : step_b_up(m, p, a, q, b, mv[s].idx);
            if (!ok) return false;
        }
    }
    return true;
}

/* ------------------------------------------------------------------ */
/*  Matching a target against an instantiated origin                   */
/* ------------------------------------------------------------------ */

/* Pair target t[0..n-1] with origin o[0..n-1], class by class, in sorted
 * order; perm[i] = index of the origin paired with t[i], k[i] = t - o.
 * False when the classes differ or the relative order of the class
 * members is not preserved (a proper walk would have to cross). */
static int idx_cmp_ctx_n;
static const HrPar* idx_cmp_ctx;
static int idx_cmp(const void* x, const void* y) {
    double u = par_value(&idx_cmp_ctx[*(const int*)x]);
    double v = par_value(&idx_cmp_ctx[*(const int*)y]);
    return (u < v) ? -1 : (u > v);
}

static bool pair_lists(const HrPar* t, const HrPar* o, int n, int* perm, int64_t* k) {
    bool used[HR_MAXD + 2] = { false };
    int ti[HR_MAXD + 2];
    for (int i = 0; i < n; i++) ti[i] = i;
    idx_cmp_ctx = t; idx_cmp_ctx_n = n;
    qsort(ti, (size_t)n, sizeof(int), idx_cmp);
    int oi[HR_MAXD + 2];
    for (int i = 0; i < n; i++) oi[i] = i;
    idx_cmp_ctx = o;
    qsort(oi, (size_t)n, sizeof(int), idx_cmp);
    /* Greedy in sorted order: each target takes the smallest unused origin
     * of its class. Sorted-order pairing within a class keeps relative
     * order. */
    for (int s = 0; s < n; s++) {
        int i = ti[s];
        int pick = -1; int64_t kk = 0;
        for (int r = 0; r < n; r++) {
            int j = oi[r];
            if (used[j]) continue;
            int64_t dk;
            if (par_int_diff(&t[i], &o[j], &dk)) { pick = j; kk = dk; break; }
        }
        if (pick < 0) return false;
        used[pick] = true;
        perm[i] = pick; k[i] = kk;
    }
    return true;
}

/* ------------------------------------------------------------------ */
/*  Solve one function: certificate lookup + walk                      */
/* ------------------------------------------------------------------ */

typedef struct {
    Expr* f0;            /* origin closed form in HR_W (owned) */
    int p, q;
    Expr* a0[HR_MAXD];   /* origin parameters, evaluated (owned) */
    Expr* b0[HR_MAXD];
    int64_t dist;
    int family;          /* tie-break: a static entry before a family */
    int order;           /* tie-break: certificate table order */
} HrCand;

static void cand_free(HrCand* c) {
    if (c->f0) expr_free(c->f0);
    for (int i = 0; i < c->p; i++) if (c->a0[i]) expr_free(c->a0[i]);
    for (int i = 0; i < c->q; i++) if (c->b0[i]) expr_free(c->b0[i]);
    memset(c, 0, sizeof *c);
}

/* Total walk length from origin to target; -1 when no pairing exists. */
static int64_t cand_distance(const HrCand* c, const HrPar* ta, int p,
                             const HrPar* tb, int q, int* pa, int64_t* ka,
                             int* pb, int64_t* kb) {
    HrPar oa[HR_MAXD], ob[HR_MAXD];
    int64_t dist = -1;
    int na = 0, nb = 0;
    for (; na < p; na++) if (!hr_par_split(c->a0[na], &oa[na])) goto out;
    for (; nb < q; nb++) if (!hr_par_split(c->b0[nb], &ob[nb])) goto out;
    if (!pair_lists(ta, oa, p, pa, ka)) goto out;
    if (!pair_lists(tb, ob, q, pb, kb)) goto out;
    dist = 0;
    for (int i = 0; i < p; i++) dist += ka[i] < 0 ? -ka[i] : ka[i];
    for (int i = 0; i < q; i++) dist += kb[i] < 0 ? -kb[i] : kb[i];
out:
    for (int i = 0; i < na; i++) hr_par_free(&oa[i]);
    for (int i = 0; i < nb; i++) hr_par_free(&ob[i]);
    return dist;
}

/* Family parameters, in solving order. */
static const char* const HR_FAMPAR[] = { HR_AL, HR_BE };
#define HR_NFAMPAR 2

/* e with the first n family parameters replaced by vals[], evaluated.
 * Consumes e. */
static Expr* fam_subst(Expr* e, Expr* const* vals, int n) {
    if (n > HR_NFAMPAR) n = HR_NFAMPAR;
    if (n <= 0) return ev(e);
    Expr* rules[HR_NFAMPAR];
    for (int i = 0; i < n; i++)
        rules[i] = mk2(SYM_Rule, expr_new_symbol(HR_FAMPAR[i]), expr_copy(vals[i]));
    Expr* lst = expr_new_function(expr_new_symbol(SYM_List), rules, (size_t)n);
    /* Substitute under Hold: evaluating the template first would let a rule
     * for symbolic parameters fire (Hrep`phi[w, 1, al] -> LerchPhi) before
     * the value of al arrives. */
    return ev(mk1("ReleaseHold", mk2(SYM_ReplaceAll, mk1("Hold", e), lst)));
}

/* Instantiate certificate `cert` with its family parameters set to vals[]
 * (nv of them; 0 for a static certificate). False when its condition
 * evaluates to False. */
static bool cand_make(const HrCert* cert, Expr* const* vals, int nv, HrCand* c) {
    memset(c, 0, sizeof *c);
    c->p = cert->p; c->q = cert->q;
    for (int i = 0; i < cert->p; i++)
        c->a0[i] = fam_subst(parse_expression(cert->a[i]), vals, nv);
    for (int i = 0; i < cert->q; i++)
        c->b0[i] = fam_subst(parse_expression(cert->b[i]), vals, nv);
    if (cert->cond) {
        Expr* v = fam_subst(parse_expression(cert->cond), vals, nv);
        bool bad = v->type == EXPR_SYMBOL && v->data.symbol.name == SYM_False;
        expr_free(v);
        if (bad) { cand_free(c); return false; }
    }
    c->f0 = fam_subst(parse_expression(cert->f0), vals, nv);
    return true;
}

static bool mentions(const Expr* e, const char* sym) {
    if (!e) return false;
    if (e->type == EXPR_SYMBOL) return strcmp(e->data.symbol.name, sym) == 0;
    if (e->type != EXPR_FUNCTION) return false;
    if (mentions(e->data.function.head, sym)) return true;
    for (size_t i = 0; i < e->data.function.arg_count; i++)
        if (mentions(e->data.function.args[i], sym)) return true;
    return false;
}

/* The value of family parameter `par` that pairs template t (after the
 * earlier parameters are substituted; linear in par, free of the later ones)
 * with target x: (x - c0)/c1. NULL when t does not involve par alone. */
static Expr* family_solve(const Expr* t, const char* par, int k, const Expr* x) {
    if (!mentions(t, par)) return NULL;
    for (int j = k + 1; j < HR_NFAMPAR; j++) if (mentions(t, HR_FAMPAR[j])) return NULL;
    Expr* zero = expr_new_integer(0), *one = expr_new_integer(1);
    Expr* c0 = hr_subst(t, par, zero);
    Expr* c1v = hr_subst(t, par, one);
    expr_free(zero); expr_free(one);
    Expr* c1 = ev(mk2(SYM_Plus, c1v, mk2(SYM_Times, expr_new_integer(-1), expr_copy(c0))));
    Expr* v = NULL;
    if (!(c1->type == EXPR_INTEGER && c1->data.integer == 0) && !mentions(c1, par)) {
        /* expanded: 2 (-1/2 + (1 + n)/2) is n */
        v = ev(mk1("Expand", mk2(SYM_Times,
                   mk2(SYM_Plus, expr_copy((Expr*)x),
                       mk2(SYM_Times, expr_new_integer(-1), expr_copy(c0))),
                   mk2(SYM_Power, expr_copy(c1), expr_new_integer(-1)))));
    }
    expr_free(c0); expr_free(c1);
    return v;
}

#define HR_MAXCAND 64

/* The answer's module for target (a; b): fills *f0 and the coefficient
 * vector (as Expr in HR_W, owned, length *d). */
typedef struct {
    int d;
    Expr* f0;              /* origin closed form */
    Expr* coef[HR_MAXD];   /* answer = sum coef[k] theta^k f0 */
} HrAnswer;

static void answer_free(HrAnswer* r) {
    if (r->f0) expr_free(r->f0);
    for (int k = 0; k < r->d; k++) if (r->coef[k]) expr_free(r->coef[k]);
    memset(r, 0, sizeof *r);
}

static int cand_dist_cmp(const void* x, const void* y) {
    const HrCand* u = x; const HrCand* v = y;
    /* A static certificate in the residue class beats any family instance:
     * its answer is in elementary or classical functions, where a family
     * gives the general special function (BesselI of half-integer order
     * rather than Sinh and Cosh). Then shortest walk, then table order. */
    if (u->family != v->family) return u->family - v->family;
    if (u->dist != v->dist) return (u->dist < v->dist) ? -1 : 1;
    return u->order - v->order;
}

/* Walk candidate c to the target; on success fill ans. Borrows everything. */
static bool walk_candidate(const HrCand* c, Expr* const* a, int p, Expr* const* b,
                           int q, const HrPar* ta, const HrPar* tb,
                           HrAnswer* ans, Expr* const* post_lin, int npost) {
    int pa[HR_MAXD], pb[HR_MAXD];
    int64_t ka[HR_MAXD], kb[HR_MAXD];
    if (cand_distance(c, ta, p, tb, q, pa, ka, pb, kb) < 0) return false;

    /* Generators: HR_W plus every symbol of the parameters. */
    const char* gens[32]; int ng = 0;
    gens[ng++] = HR_W;
    for (int i = 0; i < p; i++) if (!collect_symbols(a[i], gens, &ng, 32)) return false;
    for (int i = 0; i < q; i++) if (!collect_symbols(b[i], gens, &ng, 32)) return false;
    for (int i = 0; i < p; i++) if (!collect_symbols(c->a0[i], gens, &ng, 32)) return false;
    for (int i = 0; i < q; i++) if (!collect_symbols(c->b0[i], gens, &ng, 32)) return false;
    for (int i = 0; i < npost; i++) if (!collect_symbols(post_lin[i], gens, &ng, 32)) return false;

    HrMod M; memset(&M, 0, sizeof M);
    M.t = tcre_new(gens, ng);
    if (!M.t) return false;
    bool ok = false;
    Expr* zero = expr_new_integer(0), *one = expr_new_integer(1);
    Expr* wsym = expr_new_symbol(HR_W);
    Expr* wi = mk2(SYM_Power, expr_new_symbol(HR_W), expr_new_integer(-1));
    M.zero = H(&M, zero); M.one = H(&M, one); M.w = H(&M, wsym); M.wi = H(&M, wi);
    expr_free(zero); expr_free(one); expr_free(wsym); expr_free(wi);
    if (M.zero < 0 || M.one < 0 || M.w < 0 || M.wi < 0) goto done;

    /* Current parameters, in TARGET order: cur_a[i] starts at the origin
     * parameter paired with target a[i]. */
    int cur_a[HR_MAXD], cur_b[HR_MAXD], oa[HR_MAXD], ob[HR_MAXD];
    for (int i = 0; i < p; i++) {
        oa[i] = H(&M, c->a0[pa[i]]);
        if (oa[i] < 0) goto done;
        cur_a[i] = oa[i];
    }
    for (int i = 0; i < q; i++) {
        ob[i] = H(&M, c->b0[pb[i]]);
        if (ob[i] < 0) goto done;
        cur_b[i] = ob[i];
    }
    if (!m_init(&M, p, oa, q, ob)) goto done;

    HrMove mv[2 * HR_MAXD]; int nm = 0;
    for (int i = 0; i < p; i++) if (ka[i]) {
        mv[nm].is_a = true; mv[nm].idx = i; mv[nm].k = ka[i];
        mv[nm].tval = par_value(&ta[i]); nm++;
    }
    for (int i = 0; i < q; i++) if (kb[i]) {
        mv[nm].is_a = false; mv[nm].idx = i; mv[nm].k = kb[i];
        mv[nm].tval = par_value(&tb[i]); nm++;
    }
    if (!run_moves(&M, p, cur_a, q, cur_b, mv, nm)) goto done;

    /* Derivative-formula factors: C <- prod (theta + s)/s, s = post_lin[i]. */
    for (int i = 0; i < npost; i++) {
        int s = H(&M, post_lin[i]);
        if (s < 0 || !nonzero(&M, s)) goto done;
        int T[HR_MAXD];
        if (!m_theta_plus(&M, s, M.C, T)) goto done;
        v_scale(&M, tcre_div(M.t, M.one, s), T, M.C);
    }

    ans->d = M.d;
    ans->f0 = expr_copy(c->f0);
    for (int k = 0; k < M.d; k++) {
        Expr* e = tcre_to_expr(M.t, M.C[k]);
        if (!e) goto done;
        ans->coef[k] = ev(e);
    }
    ok = true;
done:
    tcre_free(M.t);
    if (!ok) answer_free(ans);
    return ok;
}

static bool hr_solve(Expr* const* a, int p, Expr* const* b, int q,
                     Expr* const* post, int npost, HrAnswer* ans, int depth);

/* Derivative formula: remove one (upper a_i, lower b_j) pair with
 * a_i - b_j = n in Z+, since
 *     F(a_i, c; b_j, d) = prod_{m=0}^{n-1} (theta + b_j + m)/(b_j + m) F(c; d).
 * The factors join `post` (theta polynomials commute) and the reduced
 * function is solved recursively. */
static bool solve_by_derivative(Expr* const* a, int p, Expr* const* b, int q,
                                Expr* const* post, int npost,
                                HrAnswer* ans, int depth) {
    for (int i = 0; i < p; i++) {
        HrPar pi;
        if (!hr_par_split(a[i], &pi)) continue;
        for (int j = 0; j < q; j++) {
            HrPar pj;
            if (!hr_par_split(b[j], &pj)) continue;
            int64_t n;
            bool hit = par_int_diff(&pi, &pj, &n) && n > 0 && npost + n <= HR_MAXPOST;
            hr_par_free(&pj);
            if (!hit) continue;
            hr_par_free(&pi);
            Expr* ra[HR_MAXD]; Expr* rb[HR_MAXD];
            int rp = 0, rq = 0;
            for (int k = 0; k < p; k++) if (k != i) ra[rp++] = a[k];
            for (int k = 0; k < q; k++) if (k != j) rb[rq++] = b[k];
            Expr* np2[HR_MAXPOST];
            int nn = 0;
            for (int k = 0; k < npost; k++) np2[nn++] = expr_copy(post[k]);
            for (int64_t m = 0; m < n; m++)
                np2[nn++] = ev(mk2(SYM_Plus, expr_copy(b[j]), expr_new_integer(m)));
            bool ok = hr_solve(ra, rp, rb, rq, np2, nn, ans, depth + 1);
            for (int k = 0; k < nn; k++) expr_free(np2[k]);
            return ok;
        }
        hr_par_free(&pi);
    }
    return false;
}

typedef struct {
    const HrCert* ct;
    Expr* const* a; int p;
    Expr* const* b; int q;
    const HrPar* ta; const HrPar* tb;
    HrCand* cands; int* nc;
    int order;
} HrEnum;

/* Fix family parameter k (of ct->family) in every consistent way, then add
 * the instantiated candidate. vals[0..k-1] are fixed. */
static void enum_family(HrEnum* en, int k, Expr** vals) {
    if (*en->nc >= HR_MAXCAND || en->ct->family > HR_NFAMPAR) return;
    if (k >= en->ct->family) {
        HrCand c;
        if (!cand_make(en->ct, vals, k, &c)) return;
        int pa[HR_MAXD], pb[HR_MAXD];
        int64_t ka[HR_MAXD], kb[HR_MAXD];
        c.dist = cand_distance(&c, en->ta, en->p, en->tb, en->q, pa, ka, pb, kb);
        if (c.dist < 0) { cand_free(&c); return; }
        c.family = en->ct->family ? 1 : 0;
        c.order = en->order;
        en->cands[(*en->nc)++] = c;
        return;
    }
    if (k < 0 || k >= HR_NFAMPAR) return;
    const char* par = HR_FAMPAR[k];
    for (int role = 0; role < 2; role++) {
        int nt = role ? en->ct->q : en->ct->p;
        for (int ti = 0; ti < nt; ti++) {
            Expr* t = fam_subst(parse_expression(role ? en->ct->b[ti] : en->ct->a[ti]), vals, k);
            int nx = role ? en->q : en->p;
            for (int xi = 0; xi < nx && *en->nc < HR_MAXCAND; xi++) {
                Expr* v = family_solve(t, par, k, role ? en->b[xi] : en->a[xi]);
                if (!v) break;            /* this template does not fix par */
                vals[k] = v;
                enum_family(en, k + 1, vals);
                expr_free(v);
            }
            expr_free(t);
        }
    }
}

