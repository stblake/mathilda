(* ========================================================================== *)
(* Ideal.m -- fractional ideals of the integral closure O = K[x]<w_0..w_m-1>, *)
(*            i.e. divisors supported at the finite places, [T] Ch 5 Sec 3     *)
(*            pp.59-62 and Ch 2 Sec 2 pp.25-26.                               *)
(*                                                                            *)
(* A divisor delta supported at finite places corresponds to the fractional   *)
(* ideal I(delta) = { u : ord_P u >= delta_P at every finite P }, and          *)
(* I(delta1 + delta2) = I(delta1) I(delta2), I(-delta) = I(delta)^(-1) (O is   *)
(* a Dedekind domain).  An ideal is stored as                                 *)
(*     <|\"M\" -> M, \"den\" -> den|>                                           *)
(* meaning the K[x]-module spanned by the rows of the polynomial matrix M (in *)
(* Hermite normal form) divided by den, a monic polynomial over the PRIME     *)
(* field (Q or GF(p)).                                                        *)
(*                                                                            *)
(* For a residue alpha of the remainder (N/E) Y dx, the divisor of the places *)
(* with residue alpha is generated by h = N Y - alpha E' and Bp ([T] p.60):   *)
(* at an unramified place P over a root of Bp, ord_P(Bp) = 1 and              *)
(* h(P) = E'(x0) (Res_P - alpha), so min(ord_P h, ord_P Bp) is 1 exactly when  *)
(* the residue at P is alpha; away from the roots of Bp, Bp is a unit.         *)
(* ========================================================================== *)

idealFromGenerators::usage = "idealFromGenerators[F, B, gens] is the ideal of O generated by the integral elements gens (coordinate lists with polynomial entries over F).";
idealFromGenerators[F_Association, B_Association, gens_List] := Module[{x = B["x"], rows},
  rows = Flatten[Table[afTimesPoly[F, B, afUnit[B, k], g], {g, gens}, {k, 0, B["m"] - 1}], 1];
  <|"M" -> hnf[F, rows, x], "den" -> 1|>];

residueIdeal::usage = "residueIdeal[F, B, alpha, N, Ep, Bp] is the ideal of the divisor of the places with residue alpha (alpha != 0) of the remainder (N/E) Y dx, Ep = E'. Closed form: those places lie over the roots of A = gcd(Bp, N^m G - alpha^m Ep^m), one over each root, where Y = phi = alpha Ep/N mod A; since A is prime to every d_k, the ideal is spanned by A w_0 and w_k - (phi^k/d_k mod A) w_0 (index deg A in O, which is the degree of the divisor). Equal to residueIdealGeneric.";
residueIdeal[F_Association, B_Association, alpha_, N_, Ep_, Bp_] := Module[
  {x = B["x"], m = B["m"], A, Nin, phi, rows},
  A = kGCD[F, Bp, kc[F, N^m B["G"] - alpha^m Ep^m], x];
  If[A === 0 || kDeg[F, A, x] <= 0, Return[idealUnit[B]]];
  Nin = kExtGCD[F, kRem[F, N, A, x], A, x];
  If[Nin[[1]] =!= 1, throwInternal["ResidueIdealNNotInvertible"]];
  phi = kRem[F, alpha Ep Nin[[2]], A, x];
  rows = Prepend[
    Table[
      With[{dinv = kExtGCD[F, kRem[F, B["d"][[k + 1]], A, x], A, x]},
        If[dinv[[1]] =!= 1, throwInternal["ResidueIdealDNotInvertible"]];
        ReplacePart[Table[0, {m}], {1 -> kRem[F, -kc[F, phi^k] dinv[[2]], A, x], k + 1 -> 1}]],
      {k, 1, m - 1}],
    ReplacePart[Table[0, {m}], 1 -> A]];
  <|"M" -> hnf[F, rows, x], "den" -> 1|>];

residueData::usage = "residueData[F, B, alpha, N, Ep, Bp] is {A, phi}: A = gcd(Bp, N^m G - alpha^m Ep^m), whose roots carry the places with residue alpha (one over each root), and phi = alpha Ep/N mod A, the value of Y at those places. A is 1 when no place has residue alpha.";
residueData[F_Association, B_Association, alpha_, N_, Ep_, Bp_] := Module[{x = B["x"], A, Nin},
  A = kGCD[F, Bp, kc[F, N^B["m"] B["G"] - alpha^B["m"] Ep^B["m"]], x];
  If[A === 0 || kDeg[F, A, x] <= 0, Return[{1, 0}]];
  Nin = kExtGCD[F, kRem[F, N, A, x], A, x];
  If[Nin[[1]] =!= 1, throwInternal["ResidueIdealNNotInvertible"]];
  {A, kRem[F, alpha Ep Nin[[2]], A, x]}];

residueGenerators::usage = "residueGenerators[F, B, alpha, N, Ep, Bp, sign, k] is {gens, den, det}: two integral generators, a denominator and the determinant of the module the generators span, for the ideal of k Delta(alpha) (sign = 1) or -k Delta(alpha) (sign = -1), k >= 1. Over a root of A the place with residue alpha is unramified with Y = phi there; phi_k, the Hensel lift of phi modulo A^k (phi_k^m = G mod A^k), is the k-adic expansion of that branch of Y, so k Delta = (A^k, Y - phi_k) (determinant A^k); and -k Delta = (A^k, H_k)/A^k with H_k = (Y^m - G)/(Y - phi_k) mod A^k, which vanishes to order k at the other places over A (determinant A^(k (m-1))).";
residueGenerators[F_Association, B_Association, alpha_, N_, Ep_, Bp_, sign_Integer, k_Integer : 1] := Module[
  {m = B["m"], x = B["x"], A, phi, Ak, g1},
  {A, phi} = residueData[F, B, alpha, N, Ep, Bp];
  If[A === 1, Return[{{afOne[B]}, 1, 1}]];
  Ak = kc[F, A^k];
  phi = henselRoot[F, B["G"], m, phi, A, k, x];
  g1 = If[sign > 0,
    PadRight[{kc[F, -phi], 1}, m],
    Table[kRem[F, B["d"][[j + 1]] kc[F, phi^(m - 1 - j)], Ak, x], {j, 0, m - 1}]];
  {{PadRight[{Ak}, m], g1}, If[sign > 0, 1, kMonic[F, Ak, x]] /. 0 -> 1,
   If[sign > 0, kMonic[F, Ak, x], kMonic[F, kc[F, Ak^(m - 1)], x]]}];

henselRoot::usage = "henselRoot[F, G, m, phi, A, k, x] lifts the root phi of Y^m = G modulo A (m phi^(m-1) invertible mod A: the places are unramified) to a root modulo A^k by Newton's iteration, doubling the precision each step.";
henselRoot[F_Association, G_, m_Integer, phi0_, A_, k_Integer, x_Symbol] := Module[{phi = phi0, prec = 1, mod, inv},
  While[prec < k,
    prec = Min[2 prec, k];
    mod = kc[F, A^prec];
    inv = kExtGCD[F, kRem[F, m phi^(m - 1), mod, x], mod, x];
    If[inv[[1]] =!= 1, throwInternal["HenselNotUnramified"]];
    phi = kRem[F, phi - (phi^m - G) inv[[2]], mod, x]];
  phi];

idealTimesGenerators::usage = "idealTimesGenerators[F, B, I, {gens, den}, detJ] is the product of the ideal I with the ideal spanned by gens and divided by den: Hermite form of the products of I's rows with the generators (2m products for two generators instead of m^2). detJ, when given, is the determinant of the module spanned by gens; the Hermite form is then taken modulo det(I) detJ (hnfModDet).";
idealTimesGenerators[F_Association, B_Association, I_Association, {gens_List, den_}, detJ_ : None] := Module[{x = B["x"], rows, dd, H, nat},
  dd = kc[F, I["den"] den];
  dd = kc[F, dd kInv[F, kLC[F, dd, x]]];
  nat = nativeIdeal[F, B, I["M"], gens, If[detJ === None, None, kc[F, (Times @@ Diagonal[I["M"]]) detJ]], dd];
  If[nat =!= None, Return[nat]];
  rows = Flatten[Table[afTimesPoly[F, B, r, g], {r, I["M"]}, {g, gens}], 1];
  (* With the determinant of the generator ideal known, det(I J) = det I det J *)
  (* bounds the module and the Hermite form is computed modulo it.            *)
  H = If[detJ === None, hnf[F, rows, x],
    hnfModDet[F, rows, x, kc[F, (Times @@ Diagonal[I["M"]]) detJ]]];
  idealReduce[F, B, <|"M" -> H, "den" -> dd|>]];

divisorIdeal::usage = "divisorIdeal[F, B, alphas, b, N, Ep, Bp] is the ideal of the divisor Sum_i b_i Delta(alpha_i) (b_i integers of either sign), built by multiplying, for each i, the two-generator ideal of |b_i| Delta(alpha_i) or of its inverse (residueGenerators, Hensel-lifted): one product per residue whatever b_i.";
divisorIdeal[F_Association, B_Association, alphas_List, b_List, N_, Ep_, Bp_] := Module[{I = idealUnit[B], g},
  Do[
    If[b[[i]] =!= 0,
      g = residueGenerators[F, B, alphas[[i]], N, Ep, Bp, Sign[b[[i]]], Abs[b[[i]]]];
      I = idealTimesGenerators[F, B, I, Most[g], Last[g]]],
    {i, Length[b]}];
  I];

residueIdealGeneric::usage = "residueIdealGeneric[F, B, alpha, N, Ep, Bp] is the residue ideal computed from its two generators N Y - alpha Ep and Bp by a Hermite normal form of the 2m products with the basis ([T] p.60). Slower; kept as an independent cross-check of residueIdeal.";
residueIdealGeneric[F_Association, B_Association, alpha_, N_, Ep_, Bp_] := Module[{h, bp},
  h = PadRight[{kc[F, -alpha Ep], kc[F, N]}, B["m"]];
  bp = PadRight[{kc[F, Bp]}, B["m"]];
  idealFromGenerators[F, B, {h, bp}]];

idealTimes::usage = "idealTimes[F, B, I, J] is the product of the fractional ideals I and J.";
idealTimes[F_Association, B_Association, I_Association, J_Association] := Module[{x = B["x"], rows, D, den, nat},
  (* det(I J) = det I det J for the numerator modules (norms are multiplicative *)
  (* in a Dedekind domain), so the Hermite form is taken modulo it.            *)
  D = kc[F, (Times @@ Diagonal[I["M"]]) (Times @@ Diagonal[J["M"]])];
  den = kMonic[F, kc[F, I["den"] J["den"]], x] /. 0 -> 1;
  nat = nativeIdeal[F, B, I["M"], J["M"], D, den];
  If[nat =!= None, Return[nat]];
  rows = Flatten[Table[afTimesPoly[F, B, r, s], {r, I["M"]}, {s, J["M"]}], 1];
  idealReduce[F, B, <|"M" -> hnfModDet[F, rows, x, D], "den" -> den|>]];

nativeIdeal::usage = "nativeIdeal[F, B, rows, gens, D, den] is the ideal <|\"M\" -> H, \"den\" -> d|> of the module spanned by the products r g (r in rows, g in gens, both coordinate lists of integral elements) divided by den, in lowest terms -- one call of the FLINT` Hermite-form kernel (products by the multiplication table B[\"mult\"], elimination modulo D unless D is None, common factors of den removed) -- or None when the kernels are off or decline (the caller then runs the package routines). The products, the Hermite form and idealReduce of the package routines in one step, with the same result.";
nativeIdeal[F_Association, B_Association, rows_List, gens_List, D_, den_] := Module[{r},
  If[!nativeQ[], Return[None]];
  r = FLINT`PolynomialHermiteForm[rows, B["x"], "Products" -> {gens, B["mult"]},
    Sequence @@ If[D === None, {}, {"DeterminantMultiple" -> D}], "Denominator" -> den,
    Sequence @@ nativeOpts[F]];
  If[ListQ[r], <|"M" -> r[[1]], "den" -> r[[2]]|>, None]];

idealPower::usage = "idealPower[F, B, I, k] is I^k for an integer k (k < 0 inverts first; k = 0 gives O).";
idealPower[F_Association, B_Association, I_Association, k_Integer] := Module[{r, base, e},
  If[k < 0, Return[idealPower[F, B, idealInverse[F, B, I], -k]]];
  r = idealUnit[B]; base = I; e = k;
  While[e > 0,
    If[OddQ[e], r = idealTimes[F, B, r, base]];
    e = Quotient[e, 2];
    If[e > 0, base = idealTimes[F, B, base, base]]];
  r];

idealUnit::usage = "idealUnit[B] is the unit ideal O.";
idealUnit[B_Association] := <|"M" -> IdentityMatrix[B["m"]], "den" -> 1|>;

idealInverse::usage = "idealInverse[F, B, I] is the inverse fractional ideal { u : u I in O } ([T] Ch 2 Sec 2). With I = rows(M)/den: u = Sum c_k w_k lies in rows(M)^(-1) iff c . Mult(r_i) is polynomial for every row r_i. The n^2 columns of the matrices Mult(r_i) span a module with Hermite basis H, the condition reads c . H^T polynomial, so the inverse is spanned by the rows of (H^T)^(-1) = adj(H)^T / det(H), multiplied by den.";
idealInverse[F_Association, B_Association, I_Association] := Module[
  {x = B["x"], m = B["m"], cols, H, det, adjT, nrm, cof, rows},
  cols = Flatten[Table[
      With[{Mr = afMultMatrix[F, B, r]}, Table[Mr[[All, l]], {l, m}]],
      {r, I["M"]}], 1];
  H = hnf[F, cols, x];
  det = kc[F, Times @@ Table[H[[i, i]], {i, m}]];
  adjT = Transpose[polyAdjugate[F, H, x]];
  (* make the denominator a prime-field polynomial: det -> its norm *)
  nrm = kMonic[F, kNorm[F, det], x];
  If[F["Type"] === "NF", nrm = Expand[nrm]];
  cof = kExactQuo[F, nrm, det, x];
  rows = Map[kc[F, # cof I["den"]] &, adjT, {2}];
  idealReduce[F, B, <|"M" -> hnf[F, rows, x], "den" -> nrm|>]];

polyAdjugate::usage = "polyAdjugate[F, H, x] is the adjugate of the square polynomial matrix H over F[x] (the FLINT` kernel when nativeQ[], else cofactor expansion; H is small).";
polyAdjugate[F_Association, H_List, x_Symbol] := Module[{n = Length[H], nat},
  If[n === 1, Return[{{1}}]];
  If[nativeQ[],
    nat = FLINT`PolynomialDetAdjugate[H, x, Sequence @@ nativeOpts[F]];
    If[ListQ[nat], Return[nat[[2]]]]];
  Table[kc[F, (-1)^(i + j) Det[Drop[H, {j}, {i}]]], {i, n}, {j, n}]];

idealReduce::usage = "idealReduce[F, B, I] removes from I = M/den every irreducible prime-field factor q of den that divides all entries of M, so that the representation stays small.";
idealReduce[F_Association, B_Association, I_Association] := Module[{x = B["x"], M = I["M"], den = I["den"], g, nat},
  If[FreeQ[den, x], Return[<|"M" -> M, "den" -> den|>]];
  If[nativeQ[],
    nat = FLINT`PolynomialHermiteForm[M, x, "Denominator" -> den, Sequence @@ nativeOpts[F]];
    If[ListQ[nat], Return[<|"M" -> nat[[1]], "den" -> nat[[2]]|>]]];
  (* Over Q and GF(p) the common factor of den and every entry is a gcd:     *)
  (* divide it out, repeatedly (a square in den may need two passes).        *)
  If[F["Type"] =!= "NF",
    g = Fold[kGCD[F, #1, #2, x] &, den, Select[Flatten[M], # =!= 0 &]];
    While[kDeg[F, g, x] > 0,
      M = Map[kExactQuo[F, #, g, x] &, M, {2}]; den = kExactQuo[F, den, g, x];
      g = Fold[kGCD[F, #1, #2, x] &, den, Select[Flatten[M], # =!= 0 &]]];
    den = kMonic[F, den, x];
    Return[<|"M" -> hnf[F, M, x], "den" -> den|>]];
  (* Over Q(theta) the factors of den are over Q: a polynomial q over Q       *)
  (* divides an entry e = Sum_k e_k(x) t^k exactly when it divides every       *)
  (* t-coefficient e_k, so the common factor is a gcd over Q as well -- no     *)
  (* factorisation of den (a norm, often of high degree with huge             *)
  (* coefficients in the reduced class arithmetic).                           *)
  g = commonDenFactor[F, den, M, x];
  While[Exponent[g, x] > 0,
    M = Map[kExactQuo[F, #, g, x] &, M, {2}]; den = Expand[Together[den/g]];
    g = commonDenFactor[F, den, M, x]];
  den = kMonic[F, den, x];
  <|"M" -> hnf[F, M, x], "den" -> If[den === 0, throwInternal["idealZeroDen"], den]|>];

commonDenFactor::usage = "commonDenFactor[F, den, M, x] is the gcd over Q of the prime-field polynomial den and every t-coefficient of every entry of the matrix M over Q(theta): the largest factor of den dividing all entries.";
commonDenFactor[F_Association, den_, M_List, x_Symbol] :=
  Fold[PolynomialGCD, den,
    Select[Flatten[If[# === 0, {}, CoefficientList[kc[F, #], F["t"]]] & /@ Flatten[M]], # =!= 0 &]];

twoGenerators::usage = "twoGenerators[F, B, I] is {{D w_0, r}, D}: two generators of the numerator module of I (D = its determinant, which lies in it by the adjugate, and r a pseudo-random F[x]-combination of its rows), checked to generate the module (a Hermite form modulo D); None when the first eight choices of r fail. Products with I then cost 2m element products instead of m^2.";
twoGenerators[F_Association, B_Association, I_Association] := Module[
  {x = B["x"], m = B["m"], D, rows, r, H, ok = None, tries = 0, coeffs},
  D = kMonic[F, kc[F, Times @@ Diagonal[I["M"]]], x];
  If[kDeg[F, D, x] <= 0, Return[{{afOne[B]}, 1}]];
  (* r = Sum c_i rows_i with pseudo-random c_i: a fixed small pattern (the     *)
  (* former Mod[., 7] coefficients) repeats over GF(p) and can stay inside a    *)
  (* proper submodule on every try, which silently sent every class addition   *)
  (* through the m^2-product idealTimes.  Linear terms in x from the second    *)
  (* try on cover modules no constant combination generates with D.           *)
  While[ok === None && tries < 8,
    tries++;
    coeffs = Table[twoGenCoeff[i, tries, 0] + If[tries > 1, twoGenCoeff[i, tries, 1] x, 0], {i, m}];
    r = kc[F, #] & /@ Total[coeffs I["M"]];
    rows = Flatten[Table[afTimesPoly[F, B, afUnit[B, k], g], {g, {PadRight[{D}, m], r}}, {k, 0, m - 1}], 1];
    H = hnfModDet[F, rows, x, D];
    If[H === I["M"], ok = {{PadRight[{D}, m], r}, D}]];
  ok];

twoGenCoeff::usage = "twoGenCoeff[i, try, k] is a deterministic pseudo-random integer in [-500001, 500001] (a polynomial hash of its arguments) used as a combination coefficient by twoGenerators.";
twoGenCoeff[i_Integer, try_Integer, k_Integer] :=
  Mod[7919 i^3 + 104729 try i + 31337 try^2 + 65537 k (i + try) + 17, 1000003] - 500001;

idealEqualQ::usage = "idealEqualQ[F, B, I, J] is True when the fractional ideals I and J are equal (same Hermite form after scaling to a common denominator).";
idealEqualQ[F_Association, B_Association, I_Association, J_Association] := Module[{x = B["x"]},
  hnf[F, Map[kc[F, # J["den"]] &, I["M"], {2}], x] ===
  hnf[F, Map[kc[F, # I["den"]] &, J["M"], {2}], x]];
