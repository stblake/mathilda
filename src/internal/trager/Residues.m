(* Residues.m -- residues of the Hermite remainder, their Q-basis, and the    *)
(*               residue field, [T] Ch 5 Sec 2 pp.56-59; [B] Sec 2.5.          *)
(*                                                                            *)
(* After Hermite reduction a component is r = (N(x)/E(x)) Y dx with E         *)
(* squarefree.  Split E = Bp C, C = gcd(E, G): over a root of C the places    *)
(* are branch places, where the residue of a Y-component is zero ([T] Ch 5    *)
(* Sec 4 pp.62-63; [T] Appendix A).  Over a root x0 of Bp the m places are    *)
(* unramified, Y(P) runs over the m-th roots of G(x0), and                    *)
(*     Res_P r = N(x0) Y(P) / E'(x0)            ([T] Theorem 2 p.57).         *)
(* Hence the residues at the places over x0 are the m roots of               *)
(* Z^m = N(x0)^m G(x0) / E'(x0)^m, and all residues are the roots of          *)
(*     R(Z) = S(Z^m),  S(W) = Res_x(W E'^m - N^m G, Bp)                       *)
(* -- the double resultant of [T] eq. (7) p.58 in closed form, because        *)
(* Res_Y(Z E' - N Y, Y^m - G) = Z^m E'^m - N^m G up to sign.  A zero root of S *)
(* (N(x0) = 0) is a zero residue and is dropped.                              *)
(*                                                                            *)
(* The logarithmic part needs the field K generated by the residues ([T]      *)
(* p.55) and a Q-basis beta_1..beta_k of their Q-span with integer            *)
(* coordinates ([T] pp.58-59): alpha_i = Sum_j b_ij beta_j, b_ij in Z.        *)
(* ========================================================================== *)

branchFreeDenominator::usage = "branchFreeDenominator[E, G, x] is Bp = E / gcd(E, G): the part of the squarefree denominator E whose roots are not branch points of Y^m = G.";
branchFreeDenominator[E_, G_, x_Symbol] := Module[{g = PolynomialGCD[E, G]},
  Expand[Together[E/g]]];

residuePolynomial::usage = "residuePolynomial[N, E, m, G, x, Z] is the monic squarefree polynomial over Q whose roots are the distinct NONZERO residues of the remainder (N/E) Y dx on Y^m = G (E squarefree): the squarefree part of S(Z^m) with S(W) = Res_x(W E'^m - N^m G, Bp), its zero roots removed. It is 1 when there are no nonzero residues.";
residuePolynomial[N_, E_, m_Integer, G_, x_Symbol, Z_Symbol] := Module[{Bp, W, S, k, R, sf},
  Bp = branchFreeDenominator[E, G, x];
  If[Exponent[Bp, x] <= 0, Return[1]];
  W = Unique["W"];
  S = Expand[Resultant[W D[E, x]^m - N^m G, Bp, x]];
  If[S === 0, throwInternal["ResidueResultantZero"]];
  k = Exponent[S, W, Min];
  S = Expand[Together[S/W^k]];
  If[Exponent[S, W] <= 0, Return[1]];
  R = Expand[S /. W -> Z^m];
  sf = Times @@ (First /@ Select[FactorList[R], !FreeQ[#[[1]], Z] &]);
  Expand[sf/Coefficient[sf, Z, Exponent[sf, Z]]]];

residueField::usage = "residueField[R, Z, t] constructs the field K generated by the roots of the squarefree polynomial R(Z) over Q and the roots as elements of K. It returns <|\"F\" -> field, \"roots\" -> {alpha_1, ...}|>: field fieldQ[] when every root is rational (roots are then rational numbers), else fieldNF[t, mu, theta] from ToNumberField (roots are polynomials in t). Throws a Decline when [K:Q] exceeds tragerOption[\"MaxFieldDegree\"].";
residueField[R_, Z_Symbol, t_Symbol] := Module[{fac, lin, nonlin, rts, nf, gen, mu, dim, crude},
  fac = First /@ Select[FactorList[R], !FreeQ[#[[1]], Z] &];
  lin = Select[fac, Exponent[#, Z] === 1 &];
  nonlin = Select[fac, Exponent[#, Z] > 1 &];
  If[nonlin === {},
    Return[<|"F" -> fieldQ[], "roots" -> (Z /. Solve[# == 0, Z][[1]] & /@ lin)|>]];
  (* Crude a-priori bound on the splitting field degree (product of the       *)
  (* factorials of the factor degrees) before asking ToNumberField.           *)
  crude = Times @@ (Factorial[Exponent[#, Z]] & /@ nonlin);
  If[crude > 50000, throwDecline["residue field too large", <|"Bound" -> crude|>]];
  rts = Join[
    Z /. Solve[# == 0, Z][[1]] & /@ lin,
    Flatten[rootObjects[#, Z] & /@ nonlin]];
  nf = ToNumberField[rts];
  If[!ListQ[nf] || Length[nf] =!= Length[rts], throwDecline["ToNumberField failed on the residues"]];
  gen = SelectFirst[nf, Head[#] === AlgebraicNumber &, None];
  If[gen === None, throwInternal["ResidueFieldNoGenerator"]];
  gen = gen[[1]];
  mu = minimalPolynomialIn[gen, t];
  dim = Exponent[mu, t];
  If[dim > tragerOption["MaxFieldDegree"], throwDecline["residue field too large", <|"Degree" -> dim|>]];
  <|"F" -> fieldNF[t, mu, gen],
    "roots" -> (algebraicToPoly[#, gen, t] & /@ nf)|>];

rootObjects::usage = "rootObjects[q, Z] is the list of the Root objects Root[q(#)&, k], k = 1..deg q, of the polynomial q in Z.";
rootObjects[q_, Z_Symbol] := With[{body = q /. Z -> Slot[1]},
  Function[{k}, Root[Function[body], k]] /@ Range[Exponent[q, Z]]];

minimalPolynomialIn::usage = "minimalPolynomialIn[theta, t] is the monic minimal polynomial of the algebraic number theta in the variable t.";
minimalPolynomialIn[theta_, t_Symbol] := Module[{mp = MinimalPolynomial[theta, t]},
  Expand[mp/Coefficient[mp, t, Exponent[mp, t]]]];

algebraicToPoly::usage = "algebraicToPoly[a, gen, t] converts a (an AlgebraicNumber over gen, or a rational number) to the polynomial Sum c_k t^k in the symbol t.";
algebraicToPoly[AlgebraicNumber[g_, c_List], gen_, t_Symbol] := Expand[c . (t^Range[0, Length[c] - 1])];
algebraicToPoly[r_?rationalNumberQ, gen_, t_Symbol] := r;
algebraicToPoly[other_, gen_, t_Symbol] := throwInternal["AlgebraicToPolyUnexpected", <|"a" -> other|>];

qBasis::usage = "qBasis[F, alphas] computes a Q-basis of the Q-span of the residues alphas (elements of F) with integer coordinates. It returns <|\"basis\" -> {beta_1, ..., beta_k}, \"coeffs\" -> b|> with alpha_i = Sum_j b[[i, j]] beta_j and every b[[i, j]] an integer; the beta_j are rational multiples of residues.";
qBasis[F_Association, alphas_List] := Module[{dim = fieldDegree[F], vec, vecs, idx = {}, sel = {}, coords, L, beta, b},
  vec[a_] := If[F["Type"] === "NF",
    PadRight[CoefficientList[kc[F, a], F["t"]], dim], {a}];
  vecs = vec /@ alphas;
  Do[
    If[MatrixRank[Append[sel, vecs[[i]]]] > Length[sel],
      AppendTo[idx, i]; AppendTo[sel, vecs[[i]]]],
    {i, Length[vecs]}];
  If[sel === {}, Return[<|"basis" -> {}, "coeffs" -> Table[{}, {Length[alphas]}]|>]];
  (* coordinates of every residue on the selected residues *)
  coords = Table[LinearSolve[Transpose[sel], vecs[[i]]], {i, Length[vecs]}];
  L = Table[LCM @@ (Denominator /@ coords[[All, j]]), {j, Length[idx]}];
  beta = Table[kc[F, alphas[[idx[[j]]]]/L[[j]]], {j, Length[idx]}];
  b = Table[coords[[i, j]] L[[j]], {i, Length[alphas]}, {j, Length[idx]}];
  If[!AllTrue[Flatten[b], IntegerQ], throwInternal["QBasisNonInteger"]];
  <|"basis" -> beta, "coeffs" -> b|>];

componentResiduePolynomial::usage = "componentResiduePolynomial[N, E, m, G, x] is the cheap part of componentResidues: <|\"R\" -> R(Z), \"Bp\" -> Bp, \"Z\" -> Z, \"t\" -> t|> without the residue field (which the per-orbit construction and Kauers' heuristic do not need).";
componentResiduePolynomial[N_, E_, m_Integer, G_, x_Symbol] := Module[{Z = Unique["Z"]},
  <|"R" -> residuePolynomial[N, E, m, G, x, Z], "Bp" -> branchFreeDenominator[E, G, x], "Z" -> Z, "t" -> Unique["t"]|>];

componentResidues::usage = "componentResidues[N, E, m, G, x] gathers everything the logarithmic part needs for the remainder (N/E) Y dx: <|\"R\" -> R(Z), \"Bp\" -> Bp, \"F\" -> K, \"residues\" -> {alpha_i in K}, \"basis\" -> {beta_j}, \"coeffs\" -> b, \"Z\" -> Z, \"t\" -> t|>. \"residues\" is {} when the remainder has no nonzero residue.";
componentResidues[N_, E_, m_Integer, G_, x_Symbol] := Module[{Z = Unique["Z"], t = Unique["t"], R, Bp, rf, qb},
  R = residuePolynomial[N, E, m, G, x, Z];
  Bp = branchFreeDenominator[E, G, x];
  If[R === 1,
    Return[<|"R" -> 1, "Bp" -> Bp, "F" -> fieldQ[], "residues" -> {}, "basis" -> {}, "coeffs" -> {}, "Z" -> Z, "t" -> t|>]];
  rf = residueField[R, Z, t];
  qb = qBasis[rf["F"], rf["roots"]];
  <|"R" -> R, "Bp" -> Bp, "F" -> rf["F"], "residues" -> rf["roots"],
    "basis" -> qb["basis"], "coeffs" -> qb["coeffs"], "Z" -> Z, "t" -> t|>];
