gfMod::usage = "gfMod[e, p] reduces the polynomial expression e (rational coefficients allowed, denominators prime to p) to its canonical form over GF(p): every coefficient in {0, ..., p-1}.";
gfSqrtMinusOne::usage = "gfSqrtMinusOne[p] is the least r in {1, ..., p - 1} with r^2 = -1 mod p, for a prime p = 1 mod 4: the image of I under the reduction Z[i] -> GF(p) at the prime (p, I - r) of degree 1 (constant field Q(i), Phase 4.1b). Every reduction at p uses this r, so the reductions of all data agree (one ring homomorphism).";
gfSqrtMinusOne[p_Integer] := gfSqrtMinusOne[p] = SelectFirst[Range[1, p - 1], Mod[#^2 + 1, p] === 0 &];

gfConstField::usage = "gfConstField[gens] is the constant field Q(gens) of the radical constants in use (and I under Q(i)), Phase 4.3b: <|\"g\" -> g, \"mu\" -> mu(g), \"theta\" -> gamma, \"reps\" -> {c -> P_c(g), ...}|> with gamma a primitive element (ToNumberField), mu its monic minimal polynomial and every generator c = P_c(gamma). Memoised on gens.";
gfConstField[gens_List] := gfConstField[gens] = Module[{nf, gen, g = Unique["Trager`Private`gfG"], own},
  (* a generator that IS one of the constants when the others lie in its field
     (2^(2/3) in Q(2^(1/3))): mapped back it is a radical, not a Root object
     such as Root[-6 - 6 #1 + #1^3, 1] = 2^(1/3) + 2^(2/3), which flooded the
     arithmetic with Root objects (Phase 4.3b C6) *)
  own = SelectFirst[SortBy[gens, LeafCount],
    Function[c, AllTrue[gens, Head[Quiet[ToNumberField[#, c]]] === AlgebraicNumber || rationalNumberQ[#] &]], None];
  nf = If[own =!= None && own =!= I, Quiet[ToNumberField[#, own]] & /@ gens, ToNumberField[gens]];
  (* radicals of rationals always have a primitive element: a failure is a bug *)
  If[!ListQ[nf] || Length[nf] =!= Length[gens], throwInternal["ConstantFieldToNumberField", <|"gens" -> gens|>]];
  gen = SelectFirst[nf, Head[#] === AlgebraicNumber &, None];
  If[gen === None, throwInternal["ConstantFieldNoGenerator"]];
  gen = gen[[1]];
  (* the generator written as the constant itself (ToNumberField returns
     Root[-2 + #1^3 &, 1] for 2^(1/3)) once it is checked to be that number *)
  If[own =!= None && own =!= I && RootReduce[gen - own] === 0, gen = own];
  <|"g" -> g, "mu" -> minimalPolynomialIn[gen, g], "theta" -> gen,
    "reps" -> MapThread[#1 -> algebraicToPoly[#2, gen, g] &, {gens, nf}]|>];

gfConstRoot::usage = "gfConstRoot[p] is the image r in GF(p) of the primitive element gamma of the constant field (gfConstField[tragerExtension[]]) under the reduction at a prime of degree 1 above p: the least simple root of mu mod p, or None when p is not usable (it divides a denominator of mu or of a representation, divides the discriminant of mu, or mu has no root mod p). Every reduction at p uses this r (gfMod), so all data are reduced by ONE ring homomorphism, as gfSqrtMinusOne does for Q(i).";
gfConstRoot[p_Integer] := gfConstRoot[p, tragerExtension[]];
gfConstRoot[p_Integer, gens_List] := gfConstRoot[p, gens] = Module[{cf = gfConstField[gens], mu, g, lin},
  mu = cf["mu"]; g = cf["g"];
  If[!denominatorsPrimeToQ[{mu, Last /@ cf["reps"]}, p], Return[None]];
  If[gfModQ[Discriminant[mu, g], p] === 0, Return[None]];
  lin = Select[FactorList[gfModQ[mu, p], Modulus -> p], Exponent[#[[1]], g] === 1 &];
  If[lin === {}, Return[None]];
  Min[gfModQ[-Coefficient[#[[1]], g, 0] PowerMod[Coefficient[#[[1]], g, 1], -1, p], p] & /@ lin]];

gfConstImage::usage = "gfConstImage[c, p] is the image in GF(p) of the algebraic constant c (a generator of the constant field, a radical of a rational formed from them such as Sqrt[6] = Sqrt[2] Sqrt[3], or I) at the degree-1 prime chosen by gfConstRoot[p].";
gfConstImage[c_, p_Integer] := Module[{gens = tragerExtension[], cf, r, rep, nf},
  cf = gfConstField[gens]; r = gfConstRoot[p, gens];
  If[r === None, throwUnimplemented["TorsionModP:algebraic-constant", "reduction mod a prime with no degree-1 prime of the constant field"]];
  rep = c /. cf["reps"];
  If[rep === c,
    nf = Quiet[ToNumberField[c, cf["theta"]]];
    If[Head[nf] =!= AlgebraicNumber, throwUnimplemented["Trager:constant-outside-field", "a radical constant outside the constant field"]];
    rep = algebraicToPoly[nf, cf["theta"], cf["g"]]];
  gfModQ[rep /. cf["g"] -> r, p]];

gfImageI::usage = "gfImageI[p] is the image of I at p: gfSqrtMinusOne[p] over Q(i) alone, the image under the constant field's degree-1 prime (gfConstImage) when radical constants are in use too, so that I and the radicals are reduced by the same homomorphism.";
gfImageI[p_Integer] := If[tragerAlgConstants =!= {} && TrueQ[tragerConstantI], gfConstImage[I, p], gfSqrtMinusOne[p]];

gfModQ::usage = "gfModQ[e, p] is gfMod for an expression with rational coefficients only (no algebraic constants).";
gfModQ[e_, p_Integer] := PolynomialMod[Expand[e /. r_Rational :> Mod[Numerator[r] PowerMod[Denominator[r], -1, p], p]], p];

gfMod[e_, p_Integer] := Module[{e1 = e},
  (* every reduction mod p goes through here.  A Gaussian rational a + b I maps
     to a + b r, r = gfSqrtMinusOne[p], when p = 1 mod 4 (a homomorphism
     Z[i] -> GF(p)); for p = 2 or 3 mod 4 there is no such map and the data is
     refused (goodPrime skips those primes first) *)
  (* radical constants (Phase 4.3b): reduced at the degree-1 prime of the
     constant field chosen by gfConstRoot[p] (one homomorphism for all data) *)
  If[!FreeQ[e1, Power[b_, q_Rational] /; rationalNumberQ[b]],
    If[tragerAlgConstants === {},
      throwUnimplemented["TorsionModP:algebraic-constant", "reduction mod p of a radical constant outside the declared constant field"]];
    e1 = e1 /. c : Power[b_, q_Rational] /; rationalNumberQ[b] :> gfConstImage[c, p]];
  If[!FreeQ[e1, _Complex],
    If[Mod[p, 4] =!= 1,
      throwUnimplemented["TorsionModP:complex", "reduction of complex constants modulo a prime p != 1 mod 4"]];
    e1 = e1 /. Complex[a_, b_] :> a + b gfImageI[p]];
  gfModQ[e1, p]];

kc::usage = "kc[F, e] is the canonical form of the polynomial expression e over the field F: Expand over Q; the remainder modulo mu(t) over Q(theta); gfMod over GF(p). e may be a polynomial in x as well; only coefficients are reduced.";
fieldSubI::usage = "fieldSubI[F, e] writes the Gaussian rationals of e in the generator of F when F is an absolute number field containing i (key \"I\" -> rep(t), set by residueField over Q(i)): a + b I -> a + b rep. Otherwise e.";
fieldSubI[F_Association, e_] := Module[{r = e},
  If[KeyExistsQ[F, "I"], r = r /. Complex[a_, b_] :> a + b F["I"]];
  (* radical constants (Phase 4.3): every radical of a rational, including the
     products the arithmetic forms (Sqrt[2] Sqrt[3] -> Sqrt[6]), written in the
     field's generator (fieldConstRep) *)
  If[KeyExistsQ[F, "consts"],
    r = r /. c : Power[b_, q_Rational] /; rationalNumberQ[b] :> fieldConstRep[F, c]];
  r];

fieldConstRep::usage = "fieldConstRep[F, c] is the radical constant c (a power of a rational with a rational exponent) as a polynomial in the generator t of the absolute number field F (\"consts\" key: rules recorded by residueField, else computed by ToNumberField against the field's theta). A constant not in F is an Unimplemented decline, never a wrong reduction.";
fieldConstRep[F_Association, c_] := Module[{hit = c /. F["consts"], nf},
  If[hit =!= c || FreeQ[hit, Power], Return[hit]];
  nf = Quiet[ToNumberField[c, F["theta"]]];
  If[Head[nf] =!= AlgebraicNumber,
    throwUnimplemented["Trager:constant-outside-field", "a radical constant outside the residue field"]];
  algebraicToPoly[nf, F["theta"], F["t"]]];

kc[F_Association, e_] := Switch[F["Type"],
  "Q", If[tragerAlgConstants === {} || FreeQ[e, Power[b_, _Rational] /; rationalNumberQ[b]], Expand[e], kcConstQ[e]],
  "NF", Expand[PolynomialRemainder[Expand[fieldSubI[F, e]], F["mu"], F["t"]]],
  "GF", gfMod[e, F["p"]],
  "Fn", kcFn[F, e]];

constNF::usage = "constNF[] is the constant field Q(constants) of the radical constants in use (and I under Q(i)) as a number field fieldNF[g, mu, gamma] carrying the constants' representations (\"consts\", \"I\"): gfConstField[tragerExtension[]] in the form the field layer takes (Phase 4.3b).";
constNF[] := Module[{cf = gfConstField[tragerExtension[]], F},
  F = fieldNF[cf["g"], cf["mu"], cf["theta"]];
  F = Append[F, "consts" -> Select[cf["reps"], #[[1]] =!= I &]];
  If[MemberQ[First /@ cf["reps"], I], F = Append[F, "I" -> (I /. cf["reps"])]];
  F];

kcConstQ::usage = "kcConstQ[e] is the canonical form over Q of an expression e whose coefficients carry radical constants, the base field being really Q(constants) (Phase 4.3b): the constants written in the primitive element g of constNF[], the normal form over Q[g]/(mu) (rc: a denominator in g is rationalised by its norm), and g mapped back to gamma. Zero, and only zero, maps to 0; Expand alone left 1 + 1/(3 Sqrt[2] d) - 2 Sqrt[2]/(27 d) (= 0) unreduced, and Normalize.m saw no progress.";
kcConstQ[e_] := Module[{F = constNF[]},
  Expand[rc[F, e] /. F["t"] -> F["theta"]]];

fnInvertT::usage = "fnInvertT[F, num, den] is {num', den'} with num'/den' = num/den over the extension field F (fieldFn with t, or fieldNF) and den' free of t: the t-part of den is inverted modulo mu(t) by the extended Euclidean algorithm over the rational functions in the other symbols. A den that is a zero divisor modulo mu (not possible over a field: mu is irreducible) is an internal error.";
fnInvertT[F_Association, num_, den_] := Module[{t = F["t"], eg, tt},
  If[FreeQ[den, t], Return[{num, den}]];
  eg = PolynomialExtendedGCD[den, F["mu"], t];
  If[!FreeQ[eg[[1]], t] || eg[[1]] === 0, throwInternal["fnInvertTNotUnit", <|"den" -> den|>]];
  tt = Together[num eg[[2, 1]]/eg[[1]]];
  If[!FreeQ[Denominator[tt], t], throwInternal["fnInvertTResidualT", <|"den" -> den|>]];
  {Numerator[tt], Denominator[tt]}];

fnCollect::usage = "fnCollect[F, num, den] is the canonical form over fieldFn F of the polynomial num/den (den free of the curve variables): num reduced modulo mu(t) when F has an extension, then collected in the non-scalar symbols with each coefficient put through Together. The zero polynomial maps to 0.";
fnCollect[F_Association, num0_, den_] := Module[{num = Expand[num0], pv, rules},
  If[fieldExtQ[F], num = Expand[PolynomialRemainder[num, F["mu"], F["t"]]]];
  If[num === 0, Return[0]];
  pv = Complement[Variables[num], fieldScalarSymbols[F]];
  If[pv === {}, Return[Together[num/den]]];
  rules = CoefficientRules[num, pv];
  Total[(Together[#[[2]]/den] Times @@ (pv^#[[1]])) & /@ rules]];

kcFn::usage = "kcFn[F, e] is kc over a rational function field fieldFn: e must be a polynomial in the curve variable(s) with coefficients in F (a denominator involving a non-scalar symbol is an internal error).";
kcFn[F_Association, e_] := Module[{tt = Together[fieldSubI[F, e]], num, den},
  {num, den} = {Numerator[tt], Denominator[tt]};
  If[fieldExtQ[F], {num, den} = fnInvertT[F, num, den]];
  If[!fieldScalarQ[F, den], throwInternal["kcFnNotPolynomial", <|"e" -> e|>]];
  fnCollect[F, num, den]];

kZeroQ::usage = "kZeroQ[F, e] is True when the polynomial e is zero over F (exact).";
kZeroQ[F_Association, e_] := kc[F, e] === 0;

kInv::usage = "kInv[F, c] is the inverse of the nonzero scalar c of F. Over Q(theta) it is the Bezout cofactor of c against mu; a zero c is an internal error.";
kInv[F_Association, c_] := Switch[F["Type"],
  "Q", If[c === 0, throwInternal["kInvZero"], 1/c],
  "GF", Module[{cc = gfMod[c, F["p"]]},
    If[cc === 0, throwInternal["kInvZero"], PowerMod[cc, -1, F["p"]]]],
  "NF", Module[{cc = kc[F, c], eg},
    If[cc === 0, throwInternal["kInvZero"]];
    If[FreeQ[cc, F["t"]], 1/cc,
      eg = PolynomialExtendedGCD[cc, F["mu"], F["t"]];
      If[!FreeQ[eg[[1]], F["t"]], throwInternal["kInvNotUnit", <|"c" -> cc|>]];
      kc[F, eg[[2, 1]]/eg[[1]]]]],
  "Fn", Module[{cc = kc[F, c]},
    If[cc === 0, throwInternal["kInvZero"]];
    If[!fieldScalarQ[F, cc], throwInternal["kInvNotScalar", <|"c" -> cc|>]];
    kc[F, 1/cc]]];

kDeg::usage = "kDeg[F, p, x] is the degree in x of the polynomial p over F (-Infinity for zero).";
kDeg[F_Association, p_, x_Symbol] := Module[{q = kc[F, p]}, If[q === 0, -Infinity, Exponent[q, x]]];

kLC::usage = "kLC[F, p, x] is the leading coefficient in x of p over F (an element of F); 0 for p = 0.";
kLC[F_Association, p_, x_Symbol] := Module[{q = kc[F, p]},
  If[q === 0, 0, kc[F, Coefficient[q, x, Exponent[q, x]]]]];

kMonic::usage = "kMonic[F, p, x] is p divided by its leading coefficient (p = 0 is returned unchanged).";
kMonic[F_Association, p_, x_Symbol] := Module[{q = kc[F, p]},
  If[q === 0, 0, kc[F, q kInv[F, kLC[F, q, x]]]]];

