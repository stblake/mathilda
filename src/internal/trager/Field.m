kRowEchelon::usage = "kRowEchelon[F, A] is {R, pivots, T}: R the reduced row echelon form of the scalar matrix A over F, pivots the pivot columns, and T the invertible transform with T.A = R.";
kRowEchelon[F_Association, A0_List] := Module[
  {A = Map[kc[F, #] &, A0, {2}], m, n, T, row = 1, pivots = {}, piv, inv, f},
  m = Length[A]; n = If[m === 0, 0, Length[First[A]]];
  If[m === 0, Return[{{}, {}, {}}]];
  T = IdentityMatrix[m];
  Do[
    If[row > m, Break[]];
    piv = SelectFirst[Range[row, m], A[[#, col]] =!= 0 &, 0];
    If[piv =!= 0,
      If[piv =!= row,
        A[[{row, piv}]] = A[[{piv, row}]];
        T[[{row, piv}]] = T[[{piv, row}]]];
      inv = kInv[F, A[[row, col]]];
      A[[row]] = kc[F, # inv] & /@ A[[row]];
      T[[row]] = kc[F, # inv] & /@ T[[row]];
      Do[
        If[i =!= row && A[[i, col]] =!= 0,
          f = A[[i, col]];
          A[[i]] = MapThread[kc[F, #1 - f #2] &, {A[[i]], A[[row]]}];
          T[[i]] = MapThread[kc[F, #1 - f #2] &, {T[[i]], T[[row]]}]],
        {i, m}];
      AppendTo[pivots, col];
      row++],
    {col, n}];
  {A, pivots, T}];

kRank::usage = "kRank[F, A] is the rank of the scalar matrix A over F.";
kRank[F_Association, A_List] := If[A === {}, 0, Length[kRowEchelon[F, A][[2]]]];

kLeftNullVector::usage = "kLeftNullVector[F, A] is a nonzero row vector c over F with c.A = 0, or None when the rows of A are independent.";
kLeftNullVector[F_Association, A_List] := Module[{ech = kRowEchelon[F, A], r},
  r = Length[ech[[2]]];
  If[r === Length[A], None, ech[[3, r + 1]]]];

kSolveVector::usage = "kSolveVector[F, A, b] is a vector c over F with c.A = b (A a list of row vectors), or None when b is not in the row span of A.";
kSolveVector[F_Association, A_List, b_List] := Module[{ech, cands, k},
  (* The rows of T beyond the rank span the left null space of {A..., b};    *)
  (* one with a nonzero last entry expresses b in terms of the rows of A.    *)
  ech = kRowEchelon[F, Append[A, b]];
  cands = ech[[3]][[Length[ech[[2]]] + 1 ;;]];
  k = SelectFirst[cands, kc[F, Last[#]] =!= 0 &, None];
  If[k === None, None, kc[F, -# kInv[F, Last[k]]] & /@ Most[k]]];
