(* ::Package:: *)

(* ========================================================================== *)
(* Field.m -- coefficient fields and univariate polynomial arithmetic over    *)
(*            them.                                                           *)
(*                                                                            *)
(* Three coefficient fields K occur:                                          *)
(*   Q          -- the base field;                                            *)
(*   Q(theta)   -- the residue field of the logarithmic part ([T] p.55: the   *)
(*                 field generated by the residues suffices).  An element is   *)
(*                 a polynomial in a SYMBOL t of degree < deg mu, where mu(t)  *)
(*                 is the monic minimal polynomial of theta; "theta" records   *)
(*                 the embedding (a Root object) used when the answer is       *)
(*                 printed;                                                   *)
(*   GF(p)      -- the reductions modulo p used to bound torsion orders       *)
(*                 ([T] Ch 6 Sec 2-3).                                        *)
(*                                                                            *)
(* A field is an Association with key "Type" -> "Q" | "NF" | "GF".  All       *)
(* polynomial routines take the field first and the variable x explicitly;    *)
(* polynomials are ordinary expanded expressions in x whose coefficients are  *)
(* canonical elements of K (kc).  For Q and GF(p) the built-in polynomial      *)
(* routines are used (Modulus -> p for GF); Q(theta) uses the hand-written     *)
(* Euclidean routines below, which reduce every coefficient modulo mu.        *)
(*                                                                            *)
(* Rational functions over K (rc) keep their DENOMINATOR in the base field    *)
(* (Q[x] or GF(p)[x]); a denominator containing t is rationalised by its norm. *)
(* This keeps every zero test exact: an element is zero iff its reduced        *)
(* numerator is the zero polynomial.                                          *)
(* ========================================================================== *)

fieldQ::usage = "fieldQ[] is the base field Q.";
fieldQ[] := <|"Type" -> "Q"|>;

fieldNF::usage = "fieldNF[t, mu, theta] is the number field Q(theta) = Q[t]/(mu(t)): t a symbol, mu the monic minimal polynomial of theta in t, theta an explicit algebraic number (Root object or radical) used only to print answers. Elements are polynomials in t of degree < deg mu.";
fieldNF[t_Symbol, mu_, theta_] := <|"Type" -> "NF", "t" -> t, "mu" -> Expand[mu], "theta" -> theta|>;

fieldGF::usage = "fieldGF[p] is the prime field GF(p).";
fieldGF[p_Integer] := <|"Type" -> "GF", "p" -> p|>;

fieldDegree::usage = "fieldDegree[F] is [F : prime field]: 1 for Q and GF(p), deg mu for Q(theta).";
fieldDegree[F_Association] := If[F["Type"] === "NF", Exponent[F["mu"], F["t"]], 1];

nativeOpts::usage = "nativeOpts[F] is the option list naming the field F to the FLINT` polynomial kernels (flint_polymat.c): {} for Q, {Modulus -> p} for GF(p), {Extension -> {t, mu}} for Q(theta).";
nativeOpts[F_Association] := Switch[F["Type"],
  "Q", {},
  "GF", {Modulus -> F["p"]},
  "NF", {Extension -> {F["t"], F["mu"]}}];

nativeQ::usage = "nativeQ[] is True when the FLINT` polynomial kernels are to be tried first (tragerOption[\"NativeKernels\"]).";
nativeQ[] := TrueQ[tragerOption["NativeKernels"]];

(* -------------------------------------------------------------------------- *)
(* Scalars and polynomials: canonical forms.                                  *)
(* -------------------------------------------------------------------------- *)

gfMod::usage = "gfMod[e, p] reduces the polynomial expression e (rational coefficients allowed, denominators prime to p) to its canonical form over GF(p): every coefficient in {0, ..., p-1}.";
gfMod[e_, p_Integer] :=
  PolynomialMod[Expand[e /. r_Rational :> Mod[Numerator[r] PowerMod[Denominator[r], -1, p], p]], p];

kc::usage = "kc[F, e] is the canonical form of the polynomial expression e over the field F: Expand over Q; the remainder modulo mu(t) over Q(theta); gfMod over GF(p). e may be a polynomial in x as well; only coefficients are reduced.";
kc[F_Association, e_] := Switch[F["Type"],
  "Q", Expand[e],
  "NF", Expand[PolynomialRemainder[Expand[e], F["mu"], F["t"]]],
  "GF", gfMod[e, F["p"]]];

kZeroQ::usage = "kZeroQ[F, e] is True when the polynomial e is zero over F (exact).";
kZeroQ[F_Association, e_] := kc[F, e] === 0;

kInv::usage = "kInv[F, c] is the inverse of the nonzero scalar c of F. Over Q(theta) it is the Bezout cofactor of c against mu; a zero c is an internal error.";
kInv[F_Association, c_] := Switch[F["Type"],
  "Q", If[c === 0, throwInternal["kInvZero"], 1/c],
  "GF", Module[{cc = gfMod[c, F["p"]]},
    If[cc === 0, throwInternal["kInvZero"], PowerMod[cc, -1, F["p"]]]],
  "NF", Module[{cc = kc[F, c], eg},
    If[cc === 0, throwInternal["kInvZero"]];
    If[FreeQ[cc, F["t"]], 1/cc,
      eg = PolynomialExtendedGCD[cc, F["mu"], F["t"]];
      If[!FreeQ[eg[[1]], F["t"]], throwInternal["kInvNotUnit", <|"c" -> cc|>]];
      kc[F, eg[[2, 1]]/eg[[1]]]]]];

kDeg::usage = "kDeg[F, p, x] is the degree in x of the polynomial p over F (-Infinity for zero).";
kDeg[F_Association, p_, x_Symbol] := Module[{q = kc[F, p]}, If[q === 0, -Infinity, Exponent[q, x]]];

kLC::usage = "kLC[F, p, x] is the leading coefficient in x of p over F (an element of F); 0 for p = 0.";
kLC[F_Association, p_, x_Symbol] := Module[{q = kc[F, p]},
  If[q === 0, 0, kc[F, Coefficient[q, x, Exponent[q, x]]]]];

kMonic::usage = "kMonic[F, p, x] is p divided by its leading coefficient (p = 0 is returned unchanged).";
kMonic[F_Association, p_, x_Symbol] := Module[{q = kc[F, p]},
  If[q === 0, 0, kc[F, q kInv[F, kLC[F, q, x]]]]];

(* -------------------------------------------------------------------------- *)
(* Division with remainder and the extended Euclidean algorithm over K[x].    *)
(* -------------------------------------------------------------------------- *)

kDivRem::usage = "kDivRem[F, a, b, x] is {q, r} with a = q b + r and deg r < deg b, over F. b must be nonzero.";
kDivRem[F_Association, a_, b_, x_Symbol] := Switch[F["Type"],
  "Q", {Expand[PolynomialQuotient[a, b, x]], Expand[PolynomialRemainder[a, b, x]]},
  "GF", {gfMod[PolynomialQuotient[gfMod[a, F["p"]], gfMod[b, F["p"]], x, Modulus -> F["p"]], F["p"]],
         gfMod[PolynomialRemainder[gfMod[a, F["p"]], gfMod[b, F["p"]], x, Modulus -> F["p"]], F["p"]]},
  "NF", kDivRemNF[F, a, b, x]];

kDivRemNF::usage = "kDivRemNF[F, a, b, x] is division with remainder over Q(theta): the FLINT` kernel when nativeQ[], else schoolbook long division; kDivRem dispatches to it.";
kDivRemNF[F_Association, a_, b_, x_Symbol] := Module[
  {r = kc[F, a], bb = kc[F, b], db, inv, q = 0, dr, term, nat},
  If[bb === 0, throwInternal["kDivRemByZero"]];
  If[nativeQ[],
    nat = FLINT`PolynomialQuotientRemainder[r, bb, x, Sequence @@ nativeOpts[F]];
    If[ListQ[nat], Return[nat]]];
  db = Exponent[bb, x];
  inv = kInv[F, Coefficient[bb, x, db]];
  While[r =!= 0 && (dr = Exponent[r, x]) >= db,
    term = kc[F, Coefficient[r, x, dr] inv] x^(dr - db);
    q = q + term;
    r = kc[F, r - term bb]];
  {kc[F, q], r}];

kQuo::usage = "kQuo[F, a, b, x] is the quotient of a by b over F.";
kQuo[F_Association, a_, b_, x_Symbol] := First[kDivRem[F, a, b, x]];

kRem::usage = "kRem[F, a, b, x] is the remainder of a modulo b over F.";
kRem[F_Association, a_, b_, x_Symbol] := Last[kDivRem[F, a, b, x]];

kExactQuo::usage = "kExactQuo[F, a, b, x] is a/b over F when b divides a; a nonzero remainder is an internal error.";
kExactQuo[F_Association, a_, b_, x_Symbol] := Module[{qr = kDivRem[F, a, b, x]},
  If[qr[[2]] =!= 0, throwInternal["kExactQuoRemainder", <|"a" -> a, "b" -> b|>]];
  qr[[1]]];

kExtGCD::usage = "kExtGCD[F, a, b, x] is {g, s, t} with s a + t b = g, g the monic gcd of a and b over F (g = 0 when both are zero).";
kExtGCD[F_Association, a0_, b0_, x_Symbol] := Module[{a = kc[F, a0], b = kc[F, b0], eg, g, lc},
  Which[
    a === 0 && b === 0, {0, 0, 0},
    b === 0, lc = kInv[F, kLC[F, a, x]]; {kc[F, a lc], lc, 0},
    a === 0, lc = kInv[F, kLC[F, b, x]]; {kc[F, b lc], 0, lc},
    F["Type"] === "Q",
      eg = PolynomialExtendedGCD[a, b, x];
      g = eg[[1]]; lc = 1/kLC[F, g, x];
      {Expand[g lc], Expand[eg[[2, 1]] lc], Expand[eg[[2, 2]] lc]},
    F["Type"] === "GF",
      eg = PolynomialExtendedGCD[a, b, x, Modulus -> F["p"]];
      g = gfMod[eg[[1]], F["p"]]; lc = kInv[F, kLC[F, g, x]];
      {kc[F, g lc], kc[F, eg[[2, 1]] lc], kc[F, eg[[2, 2]] lc]},
    True, kExtGCDEuclid[F, a, b, x]]];

kExtGCDEuclid::usage = "kExtGCDEuclid[F, a, b, x] is the extended Euclidean algorithm over any field F (used for Q(theta)): the FLINT` kernel when nativeQ[], else the package loop.";
kExtGCDEuclid[F_Association, a_, b_, x_Symbol] := Module[
  {r0 = kc[F, a], r1 = kc[F, b], s0 = 1, s1 = 0, t0 = 0, t1 = 1, q, r2, inv, nat},
  If[nativeQ[],
    nat = FLINT`PolynomialExtendedGCD[r0, r1, x, Sequence @@ nativeOpts[F]];
    If[ListQ[nat], Return[{nat[[1]], nat[[2, 1]], nat[[2, 2]]}]]];
  While[r1 =!= 0,
    {q, r2} = kDivRem[F, r0, r1, x];
    {r0, r1} = {r1, r2};
    {s0, s1} = {s1, kc[F, s0 - q s1]};
    {t0, t1} = {t1, kc[F, t0 - q t1]}];
  inv = kInv[F, kLC[F, r0, x]];
  {kc[F, r0 inv], kc[F, s0 inv], kc[F, t0 inv]}];

kGCD::usage = "kGCD[F, a, b, x] is the monic gcd of a and b over F. Over Q(theta), with the native kernels, the certified modular gcd (FLINT`PolynomialFieldGCD): the Euclidean remainders and Bezout cofactors over a field of high degree grow far larger than the gcd.";
kGCD[F_Association, a_, b_, x_Symbol] := Module[{nat, p = kc[F, a], q = kc[F, b]},
  If[F["Type"] === "NF" && nativeQ[],
    (* one division first when the degrees differ: the modular gcd then works *)
    (* on two polynomials of the smaller degree (2.4x on residue-field towers) *)
    If[p =!= 0 && q =!= 0 && Exponent[p, x] < Exponent[q, x], {p, q} = {q, p}];
    If[q =!= 0 && Exponent[p, x] > Exponent[q, x], {p, q} = {q, kRem[F, p, q, x]}];
    nat = FLINT`PolynomialFieldGCD[p, q, x, Sequence @@ nativeOpts[F]];
    If[Head[nat] =!= FLINT`PolynomialFieldGCD, Return[nat]]];
  First[kExtGCD[F, a, b, x]]];

kNorm::usage = "kNorm[F, p] is the norm of p from K[x] down to the prime-field polynomial ring: Resultant over t against mu for Q(theta), p itself for Q and GF(p).";
kNorm[F_Association, p_] := If[F["Type"] === "NF",
  Expand[Resultant[kc[F, p], F["mu"], F["t"]]], kc[F, p]];

(* -------------------------------------------------------------------------- *)
(* Rational functions over K with base-field denominators.                    *)
(* -------------------------------------------------------------------------- *)

rc::usage = "rc[F, e] is the normal form of the rational function e over F: numerator reduced over F, denominator a polynomial over the prime field (Q or GF(p)) -- a denominator involving t is replaced by its norm. Zero, and only zero, maps to 0, so zero tests (rcZeroQ) are exact. Over Q(theta) and GF(p) the form is unique; over Q it is Together's output, unique only up to the factored/expanded shape, so compare two values with rcZeroQ of their difference, never with ===.";
rc[F_Association, e_] := Switch[F["Type"],
  "Q", Together[e],
  "GF", Module[{t = Together[e, Modulus -> F["p"]], num, den},
    num = gfMod[Numerator[t], F["p"]]; den = gfMod[Denominator[t], F["p"]];
    If[num === 0, 0, rcGFMonic[num, den, F["p"]]]],
  "NF", rcNF[F, e]];

rcGFMonic::usage = "rcGFMonic[num, den, p] scales num/den over GF(p) so that the denominator is monic in its variable.";
rcGFMonic[num_, den_, p_Integer] := Module[{v = Variables[den], lc, inv},
  If[v === {}, Return[gfMod[num PowerMod[den, -1, p], p]]];
  lc = Coefficient[den, First[v], Exponent[den, First[v]]];
  inv = PowerMod[lc, -1, p];
  gfMod[num inv, p]/gfMod[den inv, p]];

rcNF::usage = "rcNF[F, e] is rc over Q(theta): Together, rationalise a t-dependent denominator by its norm, reduce the numerator modulo mu.";
rcNF[F_Association, e_] := Module[{tt = Together[e], num, den, t = F["t"], nrm, x, cof},
  num = Numerator[tt]; den = Denominator[tt];
  If[!FreeQ[den, t],
    nrm = Expand[Resultant[den, F["mu"], t]];
    x = First[Join[Complement[Variables[{den, num}], {t}], {Unique["x"]}]];
    cof = kExactQuo[F, nrm, den, x];
    num = num cof; den = nrm];
  num = kc[F, num];
  If[num === 0, 0, Together[num/den]]];

rcZeroQ::usage = "rcZeroQ[F, e] is True when the rational function e is zero over F (exact).";
rcZeroQ[F_Association, e_] := rc[F, e] === 0;

rcNumDen::usage = "rcNumDen[F, e] is {num, den} of the canonical rational function rc[F, e].";
rcNumDen[F_Association, e_] := Module[{r = rc[F, e]}, {kc[F, Numerator[r]], Denominator[r]}];

rcDeg::usage = "rcDeg[F, e, x] is the degree in x of the rational function e over F (-Infinity for zero).";
rcDeg[F_Association, e_, x_Symbol] := Module[{nd = rcNumDen[F, e]},
  If[nd[[1]] === 0, -Infinity, Exponent[nd[[1]], x] - Exponent[nd[[2]], x]]];

rcLeading::usage = "rcLeading[F, e, x] is the leading coefficient at x = Infinity of the rational function e over F: lc(num)/lc(den), an element of F (0 for e = 0).";
rcLeading[F_Association, e_, x_Symbol] := Module[{nd = rcNumDen[F, e]},
  If[nd[[1]] === 0, 0,
    kc[F, Coefficient[nd[[1]], x, Exponent[nd[[1]], x]] *
          kInv[F, Coefficient[nd[[2]], x, Exponent[nd[[2]], x]]]]]];

(* -------------------------------------------------------------------------- *)
(* Linear algebra over K (small dense matrices of scalars).                   *)
(* -------------------------------------------------------------------------- *)

kRowEchelon::usage = "kRowEchelon[F, A] is {R, pivots, T}: R the reduced row echelon form of the scalar matrix A over F, pivots the pivot columns, and T the invertible transform with T.A = R.";
kRowEchelon[F_Association, A0_List] := Module[
  {A = Map[kc[F, #] &, A0, {2}], m, n, T, row = 1, pivots = {}, piv, inv, f},
  m = Length[A]; n = If[m === 0, 0, Length[First[A]]];
  If[m === 0, Return[{{}, {}, {}}]];
  T = IdentityMatrix[m];
  Do[
    If[row > m, Break[]];
    piv = SelectFirst[Range[row, m], A[[#, col]] =!= 0 &, 0];
    If[piv =!= 0,
      If[piv =!= row,
        A[[{row, piv}]] = A[[{piv, row}]];
        T[[{row, piv}]] = T[[{piv, row}]]];
      inv = kInv[F, A[[row, col]]];
      A[[row]] = kc[F, # inv] & /@ A[[row]];
      T[[row]] = kc[F, # inv] & /@ T[[row]];
      Do[
        If[i =!= row && A[[i, col]] =!= 0,
          f = A[[i, col]];
          A[[i]] = MapThread[kc[F, #1 - f #2] &, {A[[i]], A[[row]]}];
          T[[i]] = MapThread[kc[F, #1 - f #2] &, {T[[i]], T[[row]]}]],
        {i, m}];
      AppendTo[pivots, col];
      row++],
    {col, n}];
  {A, pivots, T}];

kRank::usage = "kRank[F, A] is the rank of the scalar matrix A over F.";
kRank[F_Association, A_List] := If[A === {}, 0, Length[kRowEchelon[F, A][[2]]]];

kLeftNullVector::usage = "kLeftNullVector[F, A] is a nonzero row vector c over F with c.A = 0, or None when the rows of A are independent.";
kLeftNullVector[F_Association, A_List] := Module[{ech = kRowEchelon[F, A], r},
  r = Length[ech[[2]]];
  If[r === Length[A], None, ech[[3, r + 1]]]];

kSolveVector::usage = "kSolveVector[F, A, b] is a vector c over F with c.A = b (A a list of row vectors), or None when b is not in the row span of A.";
kSolveVector[F_Association, A_List, b_List] := Module[{ech, cands, k},
  (* The rows of T beyond the rank span the left null space of {A..., b};    *)
  (* one with a nonzero last entry expresses b in terms of the rows of A.    *)
  ech = kRowEchelon[F, Append[A, b]];
  cands = ech[[3]][[Length[ech[[2]]] + 1 ;;]];
  k = SelectFirst[cands, kc[F, Last[#]] =!= 0 &, None];
  If[k === None, None, kc[F, -# kInv[F, Last[k]]] & /@ Most[k]]];
