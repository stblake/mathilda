(* GRTable.m -- the Gradshteyn & Ryzhik integral table.

   Loaded lazily by the Integrate stages "GRTable" (src/calculus/integrate.c):
     GRTable`RunIndefinite[f, x]                  antiderivative, or $Failed
     GRTable`RunDefinite[f, x, lo, hi, assum]     definite value, or $Failed

   The formulas themselves live in src/internal/GRTables/*.m.  These files are
   generated by tools/gr/build_table.py from the verified G&R corpus
   (tools/gr/corpus/), and each one is loaded the first time a query needs it:

     Indefinite.m     indefinite integrals (chapters 2 and 5)
     DefHalfLine.m    definite over {0, Infinity}
     DefWholeLine.m   definite over {-Infinity, Infinity}
     DefUnit.m        definite over {0, 1}
     DefTrig.m        definite over an interval whose ends are multiples of Pi
     DefOther.m       every other definite interval, including symbolic ends

   Each record is GRTable`Private`add[key, id, f, x, {lo, hi} | None,
   Hold[value], {params}, Hold[{conds}]].  The parameter symbols live in GRTable`Private`, so
   a user's value for `a` or `nu` can never leak into a formula.

   MATCHING IS UNIFICATION, NOT LITERAL PATTERN MATCHING.  At load time the
   integrand of every record is turned into a pattern.  Each maximal x-free
   subexpression becomes a slot variable; in Times, Plus and a Power exponent
   the slot is Optional, so the defaults 1, 0 and 1 apply when the query has
   no factor, summand or exponent there.  A query that matches binds each slot
   to a value, and the record's parameters are then solved from
   slot(params) == value.  This one record therefore serves:
     - the symbolic form in any spelling of the parameter names;
     - every numeric instance (x^(2 nu - 1) against x^(3/2) gives nu = 5/4);
     - a parameter that only enters squared (u^2 against 4 gives u = 2 or -2;
       the book's conditions pick the branch).
   A query's overall x-free factor is split off on both sides, and the answer is
   multiplied by the ratio of the two factors.

   CONDITIONS.  The book's side conditions are checked after the parameters
   are substituted:
     - one that evaluates to False rejects that solution;
     - one that Refine cannot decide under the call's Assumptions (and
       $Assumptions) is kept.  The definite answer is then
       ConditionalExpression[value, conds].
   For an indefinite integral, conditions on the integration variable are not
   used, because they describe where the book's antiderivative is real.

   SELF-CHECK.  Every answer is tested numerically before it is returned:
     - definite with no free symbol: against a quiet NIntegrate, capped by
       TimeConstrained.  A converged quadrature that disagrees is a decline.
     - indefinite: D[value, x] - f at two points, with the remaining symbols
       set to generic rationals.

   DISPATCH.  Records are bucketed by a key: the sorted set of heads of the
   integrand's x-dependent subterms (other than Times, Plus and Power; a base
   E counts as "Exp"), plus the interval ends.  An end that involves a
   parameter is keyed as "p".  A query therefore tries only the few records
   that share its key, which keeps a decline cheap. *)

GRTable`savedContextPath = $ContextPath;
$ContextPath = {"System`"};
Begin["GRTable`Private`"];

(* rec[id] = {f, x, lim, Hold[value], params, Hold[conds]} as loaded;
   comp[id] = {g, cr, pattern, slots}, built on the record's first use;
   bucket[key] = the ids under one dispatch key.  DownValues, not an
   Association: an Association assignment copies, and the table has
   thousands of records. *)
bucket[_] := {};
nrec = 0;
slotSyms = {};       (* slot pattern symbols, created on demand *)

(* ------------------------------------------------------------------ keys *)

hk[e_] := If[Head[e] === Power && e[[1]] === E, "Exp", ToString[Head[e]]];

depHeads[e_, x_] := Which[
  AtomQ[e] || FreeQ[e, x], {},
  True, Join[{hk[e]}, Flatten[depHeads[#, x] & /@ (List @@ e)]]];

headKey[g_, x_] := StringJoin[Riffle[
  Sort[DeleteDuplicates[Complement[depHeads[g, x], {"Times", "Plus", "Power"}]]], ","]];

endKey[l_] := If[l === Infinity || l === -Infinity || NumericQ[l], ToString[InputForm[l]], "p"];

keyOf[g_, x_, None] := "I|" <> headKey[g, x];
keyOf[g_, x_, {lo_, hi_}] := "D|" <> headKey[g, x] <> "|" <> endKey[lo] <> "|" <> endKey[hi];

(* ------------------------------------------------------------- patterns *)

(* The k-th slot pattern symbol; the slots of one record are 1..n. *)
slotSym[k_] := Module[{s},
  While[Length[slotSyms] < k,
    AppendTo[slotSyms, Symbol["GRTable`Private`slot" <> ToString[Length[slotSyms] + 1]]]];
  slotSyms[[k]]];

(* mk[e, x, opt] -> pattern; Sow[] records each slot's expression in order
   and nslot counts them (reset by add). *)
nslot = 0;
mk[e_, x_, opt_] := Which[
  FreeQ[e, x], newSlot[e, opt],
  e === x, x,
  Head[e] === Plus || Head[e] === Times,
    Module[{fr = Select[List @@ e, FreeQ[#, x] &], dep = Select[List @@ e, !FreeQ[#, x] &]},
      Apply[Head[e], Join[If[fr === {}, {}, {newSlot[Apply[Head[e], fr], True]}],
                         mk[#, x, False] & /@ dep]]],
  Head[e] === Power, Power[mk[e[[1]], x, False], mk[e[[2]], x, True]],
  True, Apply[Head[e], mk[#, x, False] & /@ (List @@ e)]];

(* Pattern holds its first argument, so the slot symbol goes in by Apply *)
newSlot[e_, opt_] := Module[{p},
  nslot++;
  p = Pattern @@ {slotSym[nslot], Blank[]};
  Sow[e];
  If[opt, Optional[p], p]];

(* split off the overall x-free factor: {c, g} with f == c g *)
splitConst[f_, x_] := Which[
  FreeQ[f, x], {f, 1},
  Head[f] === Times, {Select[f, FreeQ[#, x] &], Select[f, !FreeQ[#, x] &]},
  True, {1, f}];

(* ----------------------------------------------------------------- load *)

(* One record.  The key is computed by tools/gr/build_table.py with keyOf
   below (running this file), so loading is a parse plus two stores. *)
add[key_String, id_String, f_, x_Symbol, lim_, v_Hold, params_List, conds_Hold] := (
  rec[id] = {f, x, lim, v, params, conds};
  bucket[key] = Append[bucket[key], id];
  nrec++;);

compile[id_] := compile[id] = Module[{f, x, lim, v, ps, conds, cr, g, pat, slots},
  {f, x, lim, v, ps, conds} = rec[id];
  {cr, g} = splitConst[f, x];
  nslot = 0;
  {pat, slots} = Reap[mk[g, x, False]];
  slots = If[slots === {}, {}, First[slots]];
  pat = With[{p = pat, l = Table[slotSym[i], {i, nslot}], xx = x}, Condition[p, FreeQ[l, xx]]];
  {g, cr, pat, slots}];

loaded = <||>;
need[file_String] := If[!TrueQ[loaded[file]],
  loaded[file] = True;
  Mathilda`LoadModule["GRTables/" <> file]];

defFiles[lo_, hi_] := Which[
  lo === 0 && hi === Infinity, {"DefHalfLine.m", "DefOther.m"},
  lo === -Infinity && hi === Infinity, {"DefWholeLine.m", "DefOther.m"},
  lo === 0 && hi === 1, {"DefUnit.m", "DefOther.m"},
  trigEnd[lo] && trigEnd[hi], {"DefTrig.m", "DefOther.m"},
  True, {"DefOther.m"}];
trigEnd[l_] := l === 0 || IntegerQ[l/Pi] || Head[l/Pi] === Rational;

(* ---------------------------------------------------------------- solve *)

isParam[e_, ps_] := MemberQ[ps, e];

(* the parameter solutions of eqs (a list of {lhs, rhs} pairs, lhs in the
   record's parameters), as a list of rule lists; {} when none *)
solveParams[eqs0_List, ps_List] := Module[{eqs = eqs0, sol = {}, again = True, e, un, rest, ss},
  While[again,
    again = False;
    Do[If[isParam[eqs[[i, 1]], ps] && FreeQ[sol, eqs[[i, 1]] -> _],
         sol = Append[sol /. (eqs[[i, 1]] -> eqs[[i, 2]]), eqs[[i, 1]] -> eqs[[i, 2]]];
         eqs = Delete[eqs, i] /. sol;
         again = True; Break[]],
       {i, Length[eqs]}]];
  un = Select[ps, !FreeQ[eqs[[All, 1]], #] &];
  rest = eqs;
  If[un === {},
    If[And @@ (zeroQ[#[[1]] - #[[2]]] & /@ rest), {sol}, {}],
    ss = Quiet[Solve[Equal @@@ rest, un]];
    If[Head[ss] =!= List, Return[{}]];
    principalFirst[Select[Join[sol /. #, #] & /@ ss,
      Function[s, And @@ (zeroQ[(#[[1]] - #[[2]]) /. s] & /@ eqs0)]]]]];

(* A slot that is a power has several roots: the query's a^4 against the
   record's a^4 solves to a -> a, -a, I a, -I a.  The book's conditions often
   cannot tell them apart (a^2 > b^2 holds for all four) while its value is
   not even in a, so the principal root goes first: the solutions are ordered
   by how many parameters come out real and positive when the query's own
   symbols are generic positive numbers (stable among ties). *)
principalFirst[sols_List] := Module[{sc},
  If[Length[sols] < 2, Return[sols]];
  sc = MapIndexed[{-principalScore[#1], #2[[1]]} &, sols];
  sols[[Ordering[sc]]]];
principalScore[s_List] := Module[{vals = s[[All, 2]], syms, rep, nv},
  syms = DeleteDuplicates[Cases[vals, z_Symbol /; Context[z] =!= "System`", {0, Infinity}]];
  rep = Thread[syms -> Take[PadRight[generic, Length[syms], generic], Length[syms]]];
  nv = Quiet[N[vals /. rep]];
  nv = Count[nv, v_ /; NumberQ[v] && Im[v] == 0 && v > 0];
  If[IntegerQ[nv], nv, 0]];

zeroQ[d_] := TrueQ[Quiet[PossibleZeroQ[d]]];

(* conditions: True when all hold, False when one fails, else the residue *)
condState[conds_List, s_, assum_, x_, kind_] := Module[{c, res = {}, r, bad = False},
  Do[c = Quiet[cond /. s];
     If[kind === "I" && !FreeQ[c, x], Continue[]];
     r = c;
     If[r =!= True && r =!= False, r = Quiet[Refine[c, assum]]];
     If[r =!= True && r =!= False, r = implied[r, assum]];
     If[r === False, bad = True; Break[]];
     If[r =!= True, AppendTo[res, r]],
     {cond, conds}];
  If[bad, False, res]];

(* A condition Refine leaves open is still settled when it is literally an
   assumption (or a conjunct of one), or when Simplify proves it in a
   bounded time. *)
conjuncts[a_] := If[Head[a] === And, List @@ a, {a}];
implied[r_, assum_] := Module[{q},
  If[MemberQ[conjuncts[assum], r] || And @@ (MemberQ[conjuncts[assum], #] & /@ conjuncts[r]), Return[True]];
  If[assum === True, Return[r]];
  q = Quiet[TimeConstrained[Simplify[r, assum], 1, r]];
  If[q === True || q === False, q, r]];

(* ------------------------------------------------------------ self-check *)

numVal[e_] := Quiet[N[e]];
finiteQ[z_] := NumberQ[z] && Abs[z] < 10^300;

defCheck[fq_, x_, lo_, hi_, v_] := Module[{nv, ni},
  If[!FreeQ[{fq, lo, hi, v} /. x -> 0, s_Symbol /; Context[s] =!= "System`"], Return[True]];
  nv = numVal[v];
  If[!finiteQ[nv], Return[False]];
  ni = Quiet[TimeConstrained[Check[NIntegrate[fq, {x, lo, hi}], $Failed], 3, $Failed]];
  If[!finiteQ[ni], Return[True]];
  Abs[ni - nv] <= 10^-5 Max[1, Abs[nv]]];

generic = {31/97, 47/89, 53/71, 61/83, 67/101, 73/109, 79/113, 37/59};

indefCheck[fq_, x_, v_] := Module[{syms, rep, d, ok = 0, bad = 0, z},
  syms = DeleteDuplicates[Cases[{fq, v}, s_Symbol /; Context[s] =!= "System`" && s =!= x, Infinity]];
  rep = Thread[syms -> Take[PadRight[generic, Length[syms], generic], Length[syms]]];
  (* Abs' has no numeric value, so G&R's Log[Abs[..]] antiderivatives are
     differentiated in the real-line form Abs[u] = Sqrt[u^2] (the answer
     itself keeps Abs; the sample points are real) *)
  d = Quiet[D[v /. Abs[u_] :> Sqrt[u^2], x] - fq];
  Do[z = Quiet[N[(d /. rep) /. x -> p, 20]];
     If[!finiteQ[z], Continue[]];
     If[Abs[z] <= 10^-6 Max[1, Abs[numVal[(fq /. rep) /. x -> p]]], ok++, bad++],
     {p, {31/100, 77/100, 143/100}}];
  ok > 0 && bad == 0];

(* ------------------------------------------------------------------ run *)

(* A record value that binds an iterator (3.486: Sum[n^-n, {n, 1, Infinity}])
   names it in the record context, which would print as GRTable`R`n.  Each
   Sum/Product iterator is renamed to the plain symbol of the same name, unless
   that symbol has a value (the record symbol is then kept: never captured). *)
cleanBound[val_] := Module[{js, rules},
  js = Union[Cases[val, (Sum | Product)[_, {j_Symbol, ___}] :> j, {0, Infinity}]];
  rules = Select[(# -> Symbol[SymbolName[#]]) & /@ js,
                 (#[[1]] =!= #[[2]] && Length[OwnValues @@ {#[[2]]}] == 0) &];
  val /. rules];

tryRecord[id_, cq_, gq_, qx_, qlim_, assum_, kind_] :=
  Module[{g, x, lim, v, ps, conds, pat, slots, cr, gx, m, eqs, sols, st, val, out = $Failed, f},
    {f, x, lim, v, ps, conds} = rec[id];
    {g, cr, pat, slots} = compile[id];
    gx = gq /. qx -> x;
    If[!MatchQ[gx, pat], Return[$Failed]];
    m = Replace[gx, RuleDelayed @@ {pat, Table[slotSym[i], {i, Length[slots]}]}];
    (* {slot expression, bound value} pairs, plus a symbolic interval end *)
    eqs = If[slots === {}, {}, Transpose[{slots, m}]];
    If[lim =!= None,
      eqs = Join[eqs, Select[{{lim[[1]], qlim[[1]]}, {lim[[2]], qlim[[2]]}},
                             !FreeQ[#[[1]], Alternatives @@ ps] &]]];
    eqs = Select[eqs, #[[1]] =!= #[[2]] &];
    (* a pair free of the parameters must hold as it stands *)
    If[!And @@ (zeroQ[#[[1]] - #[[2]]] & /@ Select[eqs, FreeQ[#[[1]], Alternatives @@ ps] &]),
      Return[$Failed]];
    eqs = Select[eqs, !FreeQ[#[[1]], Alternatives @@ ps] &];
    sols = solveParams[eqs, ps];
    Do[
      If[!FreeQ[{ReleaseHold[v] /. s, cr /. s}, Alternatives @@ ps], Continue[]];
      st = condState[ReleaseHold[conds], s, assum, x, kind];
      If[st === False, Continue[]];
      val = Quiet[(cq / (cr /. s)) (ReleaseHold[v] /. s)] /. x -> qx;
      val = cleanBound[val];
      If[kind === "D",
        If[!defCheck[cq gq, qx, qlim[[1]], qlim[[2]], val], Continue[]];
        If[st =!= {}, val = ConditionalExpression[val, And @@ st]],
        If[!indefCheck[cq gq, qx, val], Continue[]]];
      out = val; lastScore = principalScore[s]; Break[],
      {s, sols}];
    out];

lookup[k_] := bucket[k];

GRTable`RunIndefinite[f_, x_Symbol] := Quiet[runIndef[f, x]];
GRTable`RunDefinite[f_, x_Symbol, lo_, hi_, assum_] := Quiet[runDef[f, x, lo, hi, assum]];

(* The table never speaks: a candidate record that does not apply can still
   raise Power::infy and the like while it is tried, so both entry points
   run under Quiet, and an unusable answer is just a decline. *)
runIndef[f_, x_Symbol] := Module[{cq, gq, ids, r = $Failed},
  need["Indefinite.m"];
  {cq, gq} = splitConst[f, x];
  If[gq === 1, Return[$Failed]];
  ids = lookup[keyOf[gq, x, None]];
  Do[r = tryRecord[id, cq, gq, x, None, True, "I"]; If[r =!= $Failed, Break[]], {id, ids}];
  r];

runDef[f_, x_Symbol, lo_, hi_, assum0_] :=
  Module[{cq, gq, ids, r, condAns, done, best, assum, hkq, ks},
    r = $Failed; condAns = $Failed; done = $Failed; best = -1;
    Scan[need, defFiles[lo, hi]];
    assum = If[assum0 === True, $Assumptions, assum0 && $Assumptions];
    {cq, gq} = splitConst[f, x];
    If[gq === 1, Return[$Failed]];
    hkq = "D|" <> headKey[gq, x] <> "|";
    ks = DeleteDuplicates[{hkq <> endKey[lo] <> "|" <> endKey[hi], hkq <> "p|" <> endKey[hi],
                           hkq <> endKey[lo] <> "|p", hkq <> "p|p"}];
    ids = DeleteDuplicates[Flatten[lookup /@ ks]];
    (* an unconditional answer from any record beats a ConditionalExpression:
       a record whose open condition is a case split (a parity, p^2 <= 1
       under p^2 >= 1) is usually the wrong sibling of the one that applies *)
    (* Among unconditional answers the most principal parameter solution
       wins (first record on a tie): G&R 3.915.4a, the e^(+beta Cos[x])
       sibling, matches the e^(-beta Cos[x]) query with beta -> -beta and
       its (2/beta)^nu BesselI[nu, beta] is then on the wrong branch, while
       3.915.4b matches with beta -> beta. *)
    Do[lastScore = 0; r = tryRecord[id, cq, gq, x, {lo, hi}, assum, "D"];
       If[r === $Failed, Continue[]];
       If[Head[r] =!= ConditionalExpression,
         If[done === $Failed || lastScore > best, done = r; best = lastScore];
         Continue[]];
       If[condAns === $Failed, condAns = r],
       {id, ids}];
    If[done =!= $Failed, done, condAns]];

(* the number of records loaded so far, and the ids under one query's keys *)
GRTable`Count[] := nrec;

End[];
$ContextPath = GRTable`savedContextPath;
