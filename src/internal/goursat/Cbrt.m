(* ========================================================================== *)
(* goursat/Cbrt.m -- p = 1/3, 2/3: y^3 = R, deg R in {2, 3}.  The group is     *)
(* generated by the order-3 Mobius map fixing the roots of the Hessian H and   *)
(* the transpositions; everything is expressed through the covariants H and    *)
(* G of R, so the only irrationalities are the two roots of H.                 *)
(* goursat.py: cubic_covariants, cbrt_reduce, cbrt_second_level.               *)
(* ========================================================================== *)

(* Hessian H and Jacobian covariant G of R as a binary cubic (a quadratic R is  *)
(* the cubic form with vanishing leading coefficient).                         *)
cubicCovariants[R_, t_] := Module[{c = allCoeffs[R, t], a, b, cc, d, H, G},
  c = Join[ConstantArray[0, 4 - Length[c]], c];
  {a, b, cc, d} = c;
  H = Expand[(b^2 - 3 a cc) t^2 + (b cc - 9 a d) t + (cc^2 - 3 b d)];
  G = Expand[3 D[H, t] R - 2 H D[R, t]];
  {H, G}];

(* Symmetry reduction of F dt/y^k on y^3 = R.                                  *)
(* Q(t) = E (+) O over Q(x0), x0 = G/R.  E is integrated through the two         *)
(* uniformisers y/(t - gamma), gamma the roots of the Hessian; the part of O      *)
(* that is odd in x0 is integrated through w = H/y^2; the even part of O is the   *)
(* residual.  Returns {antiderivative, residual, log}.                           *)
cbrtReduce[F_, R_, t_, y_, k_] := Module[
  {x, u, w, H, G, x0, gam, g1, g2, lcH, hc, total = 0, log = {}, A, B, Cc, comps, pairs,
   ofac, q1, q2, s, p, gc, gu, a, X, M0, dX, g, rho, ut, Codd, Ceven, xs, psi, a3, a0,
   sol, wt, Fres},
  {H, G} = cubicCovariants[R, t];
  x0 = gK[G/R];
  gam = stage["cbrt: Hessian roots", rootsOf[H, t]];
  If[Length[gam] == 1, AppendTo[gam, Infinity]];
  If[Length[gam] != 2, ggDecline["cbrt: degenerate Hessian"]];
  {g1, g2} = gam;
  lcH = Coefficient[H, t, Exponent[H, t]];
  If[k == 1,
    {A, B, Cc} = stage["cbrt: coords", coords[F, {1/H, t/H, H/R}, x0, t, x]];
    comps = If[g2 === Infinity,
      {gK[(A + B g1)/lcH], gK[B/lcH]},
      {gK[(A + B g1)/(lcH (g1 - g2))], gK[(A + B g2)/(lcH (g2 - g1))]}];
    pairs = {{g1, g2}, {g2, g1}};             (* (component, uniformiser) *)
    ofac = w,                                  (* x0 (H/R) dt/y = 3 w dw *)
    (* k == 2 *)
    If[g2 === Infinity,
      q1 = (t - g1)^2; q2 = 1,
      hc = allCoeffs[H, t];
      s = -hc[[2]]/lcH; p = hc[[3]]/lcH;
      q1 = t^2 - p; q2 = 2 t - s];
    {Cc, A, B} = stage["cbrt: coords", coords[F, {1, q1/H, q2/H}, x0, t, x]];
    comps = If[g2 === Infinity,
      {A, B},
      {gK[(-B - g2 A)/(g1 - g2)], gK[(B + g1 A)/(g1 - g2)]}];
    pairs = {{g1, g1}, {g2, g2}};
    ofac = 1];                                 (* x0 dt/y^2 = 3 dw *)

  Do[{gc, gu} = pairs[[i]];
     a = comps[[i]];
     If[a =!= 0,
       X = gK[R/lin[gu, t]^3];
       M0 = stage["cbrt: descend x0", descend[x0, X, t, x]];
       dX = D[X, t];
       rho = If[k == 1,
         g = 1/(lin[gc, t] lin[gu, t] dX);
         3 u (a /. x -> M0) descend[g, X, t, x],
         3 (a /. x -> M0) descend[1/(H dX), X, t, x]];
       rho = gK[rho /. x -> u^3];
       ut = y/lin[gu, t];
       total += ratInt[rho, u] /. u -> ut;
       AppendTo[log, <|"uniformiser" -> ut, "rho" -> rho|>]],
     {i, 2}];

  (* the obstruction space, split by the transposition x0 -> -x0 *)
  Codd = gK[(Cc - (Cc /. x -> -x))/2];
  Ceven = gK[(Cc + (Cc /. x -> -x))/2];
  If[Codd =!= 0,
    psi = gK[(Codd/x) /. x -> Sqrt[xs]];
    (* syzygy  G^2 = a3 H^3 + a0 R^2   =>   x0^2 = a3 w^3 + a0 *)
    sol = solveIdentity[G^2 - a3 H^3 - a0 R^2, {a3, a0}, t];
    rho = gK[3 (psi /. xs -> ((a3 /. sol) w^3 + (a0 /. sol))) ofac];
    wt = H y/R;
    total += ratInt[rho, w] /. w -> wt;
    AppendTo[log, <|"uniformiser" -> wt, "rho" -> rho|>]];
  Fres = gK[(Ceven /. x -> x0) If[k == 1, H/R, 1]];
  {total, Fres, log}];

(* The residual of the cube-root reduction as a Goursat integral.               *)
(* The residual is chi(x0^2) (H/R) dt/y (k = 1) or chi(x0^2) dt/y^2 (k = 2).      *)
(* With w = H/y^2: dw = x0 dt/(3 y^2), x0^2 = 4 w^3 - 27 disc(R), so              *)
(*   residual = Phi(w) dw/Y,   Y^2 = 4 w^3 - 27 disc(R),   Y = x0 = G/R,          *)
(* a square-root integral on a j = 0 cubic.  Returns {sub, back-rules}.          *)
cbrtSecondLevel[Fres_, R_, t_, y_, k_] := Module[{x, w, Y, H, G, x0, chi, R2, Phi, sub},
  {H, G} = cubicCovariants[R, t];
  x0 = gK[G/R];
  chi = descend[Fres If[k == 1, R/H, 1], x0^2, t, x];
  R2 = Expand[4 w^3 - 27 Discriminant[R, t]];
  Phi = gK[3 If[k == 1, w, 1] (chi /. x -> R2)];
  sub = goursatIntegrate[Phi, R2, w, 1/2, Y, 0];
  {sub, {w -> H y/R, Y -> x0}}];
