static int in_table(uint32_t cp, const CpRange* t, size_t n) {
    if (cp < t[0].lo || cp > t[n - 1].hi) return 0;
    size_t lo = 0, hi = n;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (cp < t[mid].lo) hi = mid;
        else if (cp > t[mid].hi) lo = mid + 1;
        else return 1;
    }
    return 0;
}

int term_cp_width(uint32_t cp) {
    if (cp < 0x20 || cp == 0x7F || (cp >= 0x80 && cp < 0xA0)) return -1;
    if (cp < 0x300) return 1;                         /* Latin fast path */
    if (in_table(cp, ZERO_WIDTH, sizeof(ZERO_WIDTH) / sizeof(ZERO_WIDTH[0]))) return 0;
    if (in_table(cp, WIDE, sizeof(WIDE) / sizeof(WIDE[0]))) return 2;
    return 1;
}

size_t term_utf8_next(const char* s, size_t n, size_t i, uint32_t* cp) {
    const unsigned char* u = (const unsigned char*)s;
    unsigned char c = u[i];
    if (c < 0x80) { *cp = c; return i + 1; }
    size_t len; uint32_t v, min;
    if (c >= 0xC2 && c <= 0xDF)      { len = 2; v = c & 0x1F; min = 0x80; }
    else if (c >= 0xE0 && c <= 0xEF) { len = 3; v = c & 0x0F; min = 0x800; }
    else if (c >= 0xF0 && c <= 0xF4) { len = 4; v = c & 0x07; min = 0x10000; }
    else { *cp = c; return i + 1; }
    if (i + len > n) { *cp = c; return i + 1; }
    for (size_t k = 1; k < len; k++) {
        if ((u[i + k] & 0xC0) != 0x80) { *cp = c; return i + 1; }
        v = (v << 6) | (u[i + k] & 0x3F);
    }
    if (v < min || v > 0x10FFFF || (v >= 0xD800 && v <= 0xDFFF)) { *cp = c; return i + 1; }
    *cp = v;
    return i + len;
}

size_t term_utf8_prev(const char* s, size_t i) {
    const unsigned char* u = (const unsigned char*)s;
    size_t j = i - 1, steps = 0;
    while (j > 0 && steps < 3 && (u[j] & 0xC0) == 0x80) { j--; steps++; }
    /* Only a real lead byte owns the continuation bytes; otherwise each
     * stray byte is a character of its own (term_utf8_next's rule). */
    uint32_t cp;
    if (term_utf8_next(s, i, j, &cp) != i) return i - 1;
    return j;
}

size_t term_text_width(const char* s, size_t n) {
    size_t w = 0, i = 0;
    while (i < n) {
        uint32_t cp;
        i = term_utf8_next(s, n, i, &cp);
        int cw = term_cp_width(cp);
        w += cw < 0 ? 2 : (size_t)cw;
    }
    return w;
}
