typedef struct { int* a; long n, cap; } IVec;
typedef struct { u64* a; long n, cap; } UVec;

static int ivec_grow(IVec* v, long need) {
    long nc;
    int* na;
    if (need <= v->cap) return 1;
    nc = v->cap > 0 ? v->cap : 256;
    while (nc < need) nc *= 2;
    na = (int*)realloc(v->a, (size_t)nc * sizeof(int));
    if (!na) return 0;
    v->a = na;
    v->cap = nc;
    return 1;
}

static int uvec_grow(UVec* v, long need) {
    long nc;
    u64* na;
    if (need <= v->cap) return 1;
    nc = v->cap > 0 ? v->cap : 256;
    while (nc < need) nc *= 2;
    na = (u64*)realloc(v->a, (size_t)nc * sizeof(u64));
    if (!na) return 0;
    v->a = na;
    v->cap = nc;
    return 1;
}

static int push1(IVec* v, int a) {
    if (v->n + 1 > v->cap && !ivec_grow(v, v->n + 1)) return 0;
    v->a[v->n++] = a;
    return 1;
}

static int push2(IVec* v, int a, int b) {
    if (v->n + 2 > v->cap && !ivec_grow(v, v->n + 2)) return 0;
    v->a[v->n++] = a;
    v->a[v->n++] = b;
    return 1;
}

static u64 mix64(u64 h, u64 x) {
    h ^= x + 0x9E3779B97F4A7C15ULL + (h << 6) + (h >> 2);
    h *= 0xBF58476D1CE4E5B9ULL;
    h ^= h >> 29;
    return h;
}

static int cmp_int(const void* a, const void* b) {
    int x = *(const int*)a, y = *(const int*)b;
    return (x > y) - (x < y);
}

static int cmp_u64(const void* a, const void* b) {
    u64 x = *(const u64*)a, y = *(const u64*)b;
    return (x > y) - (x < y);
}

static void sort_ints(int* a, long n) {
    long i, j;
    if (n > 24) {
        qsort(a, (size_t)n, sizeof(int), cmp_int);
        return;
    }
    for (i = 1; i < n; i++) {
        int x = a[i];
        for (j = i; j > 0 && a[j - 1] > x; j--) a[j] = a[j - 1];
        a[j] = x;
    }
}

/* Search control shared by everything one API call does. */
typedef struct {
    long budget, nodes;
    long work; /* edge visits since the last galg_poll() */
    int err;   /* budget exhausted or allocation failure */
} Ctl;

static void ctl_work(Ctl* c, long w) {
    c->work += w;
    if (c->work > ISO_POLL_WORK) {
        c->work = 0;
        galg_poll();
    }
}

static int ctl_node(Ctl* c) {
    c->nodes++;
    if (c->nodes % ISO_POLL_NODES == 0) galg_poll();
    if (c->budget > 0 && c->nodes > c->budget) {
        c->err = 1;
        return 0;
    }
    return 1;
}

/* ========================================================================
 * Internal graph: normalized relations and colour classes
 * ======================================================================== */

typedef struct {
    int n;
    const int *uo, *ua; /* undirected; NULL when empty           */
    const int *oo, *oa; /* out; NULL when there are no arcs       */
    const int *io, *ia; /* in (transpose of out)                  */
    int* own[4];        /* transposes built here                  */
    const int* vcol;
    int* cls;           /* colour class (rank of vcol value)      */
    int ncls;
    int *clsval, *clssz;
    long mu, md;        /* entries of uadj, number of arcs        */
} IG;

static void ig_free(IG* G) {
    int i;
    for (i = 0; i < 4; i++) free(G->own[i]);
    free(G->cls);
    free(G->clsval);
    free(G->clssz);
    memset(G, 0, sizeof *G);
}

static int rel_ok(int n, const int* off, const int* adj) {
    int v;
    long j;
    for (v = 0; v < n; v++)
        if (off[v + 1] < off[v]) return 0;
    if (off[n] > off[0] && !adj) return 0;
    for (j = off[0]; j < off[n]; j++)
        if (adj[j] < 0 || adj[j] >= n) return 0;
    return 1;
}

static int transpose(int n, const int* off, const int* adj, int** toff, int** tadj) {
    long m = (long)off[n] - off[0], j;
    int v;
    int* to = (int*)calloc((size_t)n + 1, sizeof(int));
    int* ta = (int*)malloc((size_t)(m > 0 ? m : 1) * sizeof(int));
    int* cur = (int*)malloc((size_t)n * sizeof(int));
    if (!to || !ta || !cur) {
        free(to);
        free(ta);
        free(cur);
        return 0;
    }
    for (j = off[0]; j < off[n]; j++) to[adj[j] + 1]++;
    for (v = 0; v < n; v++) to[v + 1] += to[v];
    memcpy(cur, to, (size_t)n * sizeof(int));
    for (v = 0; v < n; v++)
        for (j = off[v]; j < off[v + 1]; j++) ta[cur[adj[j]]++] = v;
    free(cur);
    *toff = to;
    *tadj = ta;
    return 1;
}

typedef struct { int val, v; } VPair;

static int cmp_vpair(const void* a, const void* b) {
    const VPair* x = (const VPair*)a;
    const VPair* y = (const VPair*)b;
    if (x->val != y->val) return x->val < y->val ? -1 : 1;
    return (x->v > y->v) - (x->v < y->v);
}

/* 1 ok, 0 allocation failure or malformed input. Requires n >= 1. */
static int ig_build(IG* G, const GalgIsoGraph* g) {
    int n = g->n, i;
    memset(G, 0, sizeof *G);
    G->n = n;
    G->vcol = g->vcol;
    if (g->uoff) {
        if (!rel_ok(n, g->uoff, g->uadj)) return 0;
        G->mu = (long)g->uoff[n] - g->uoff[0];
        if (G->mu > 0) {
            G->uo = g->uoff;
            G->ua = g->uadj;
        }
    }
    if (g->ooff) {
        if (!rel_ok(n, g->ooff, g->oadj)) return 0;
        G->md = (long)g->ooff[n] - g->ooff[0];
        if (G->md > 0) {
            G->oo = g->ooff;
            G->oa = g->oadj;
            if (g->ioff) {
                if (!rel_ok(n, g->ioff, g->iadj)) return 0;
                if ((long)g->ioff[n] - g->ioff[0] != G->md) return 0;
                G->io = g->ioff;
                G->ia = g->iadj;
            } else {
                if (!transpose(n, g->ooff, g->oadj, &G->own[0], &G->own[1])) return 0;
                G->io = G->own[0];
                G->ia = G->own[1];
            }
        }
    } else if (g->ioff) {
        if (!rel_ok(n, g->ioff, g->iadj)) return 0;
        G->md = (long)g->ioff[n] - g->ioff[0];
        if (G->md > 0) {
            G->io = g->ioff;
            G->ia = g->iadj;
            if (!transpose(n, g->ioff, g->iadj, &G->own[2], &G->own[3])) return 0;
            G->oo = G->own[2];
            G->oa = G->own[3];
        }
    }
    G->cls = (int*)malloc((size_t)n * sizeof(int));
    if (!G->cls) return 0;
    if (!g->vcol) {
        G->ncls = 1;
        G->clsval = (int*)malloc(sizeof(int));
        G->clssz = (int*)malloc(sizeof(int));
        if (!G->clsval || !G->clssz) return 0;
        G->clsval[0] = 0;
        G->clssz[0] = n;
        for (i = 0; i < n; i++) G->cls[i] = 0;
    } else {
        VPair* pr = (VPair*)malloc((size_t)n * sizeof(VPair));
        int c = 0;
        if (!pr) return 0;
        for (i = 0; i < n; i++) {
            pr[i].val = g->vcol[i];
            pr[i].v = i;
        }
        qsort(pr, (size_t)n, sizeof(VPair), cmp_vpair);
        for (i = 0; i < n; i++)
            if (i == 0 || pr[i].val != pr[i - 1].val) c++;
        G->ncls = c;
        G->clsval = (int*)malloc((size_t)c * sizeof(int));
        G->clssz = (int*)calloc((size_t)c, sizeof(int));
        if (!G->clsval || !G->clssz) {
            free(pr);
            return 0;
        }
        c = -1;
        for (i = 0; i < n; i++) {
            if (i == 0 || pr[i].val != pr[i - 1].val) {
                c++;
                G->clsval[c] = pr[i].val;
            }
            G->cls[pr[i].v] = c;
            G->clssz[c]++;
        }
        free(pr);
    }
    return 1;
}

/* Cheap necessary conditions. 1 = may be isomorphic, 0 = not, -1 = alloc. */
static int quick_same(const IG* G, const IG* H) {
    int n = G->n, i, v, r;
    int* hist;
    if (G->mu != H->mu || G->md != H->md || G->ncls != H->ncls) return 0;
    for (i = 0; i < G->ncls; i++)
        if (G->clsval[i] != H->clsval[i] || G->clssz[i] != H->clssz[i]) return 0;
    hist = (int*)calloc((size_t)n + 1, sizeof(int));
    if (!hist) return -1;
    for (r = 0; r < 3; r++) {
        const int* go = r == 0 ? G->uo : r == 1 ? G->oo : G->io;
        const int* ho = r == 0 ? H->uo : r == 1 ? H->oo : H->io;
        if (!go) continue;
        for (v = 0; v < n; v++) {
            int dg = go[v + 1] - go[v], dh = ho[v + 1] - ho[v];
            if (dg > n) dg = n;
            if (dh > n) dh = n;
            hist[dg]++;
            hist[dh]--;
        }
        for (i = 0; i <= n; i++)
            if (hist[i]) {
                free(hist);
                return 0;
            }
    }
    free(hist);
    return 1;
}

/* ========================================================================
 * Ordered partition with refinement and exact undo
 * ======================================================================== */

typedef struct { long lab, split, sing, ev; } Mark;

typedef struct {
    const IG* g;
    Ctl* ctl;
    int n;
    int *lab, *inv;   /* lab[pos] = vertex, inv[vertex] = pos              */
    int *cst, *csz;   /* cst[v] = start of v's cell, csz[start] = size     */
    int ncells;
    unsigned char* inq;
    int* q;           /* circular FIFO of splitter cell starts             */
    int qh, qn;
    int *cnt, *tc, *tcl;
    int ntc;
    int *wbuf, *frs, *frc, *tmpv, *bkt;
    u64* tmpk;
    u64* st;          /* min segment tree over positions: key (size, start)
                       * of every non-singleton cell, ~0 elsewhere         */
    int stsz;
    IVec lablog;      /* (pos, old vertex)                                 */
    IVec splitlog;    /* (parent start, fragment start)                    */
    IVec singlog;     /* positions that became singleton cells             */
    UVec ev;          /* trace events of the current path                  */
    /* trace comparison for the refinement in progress */
    int cmpmode;
    const u64* refA;  /* must match exactly (first path / other graph)     */
    long lenA;
    int eqA;
    const u64* refB;  /* lexicographic comparison with the best path       */
    long lenB;
    int stB;          /* -1 worse, 0 equal so far, +1 better               */
    long evbase;
    u64 h;
    int abrt;
} Part;

static void part_free(Part* P) {
    free(P->lab);
    free(P->inv);
    free(P->cst);
    free(P->csz);
    free(P->inq);
    free(P->q);
    free(P->cnt);
    free(P->tc);
    free(P->tcl);
    free(P->wbuf);
    free(P->frs);
    free(P->frc);
    free(P->tmpv);
    free(P->bkt);
    free(P->tmpk);
    free(P->st);
    free(P->lablog.a);
    free(P->splitlog.a);
    free(P->singlog.a);
    free(P->ev.a);
    memset(P, 0, sizeof *P);
}

static void enq(Part* P, int s) {
    int t = P->qh + P->qn;
    if (t >= P->n) t -= P->n;
    P->q[t] = s;
    P->qn++;
    P->inq[s] = 1;
}

/* Refresh the target-cell tree at position pos (start = pos is a cell start). */
static void st_upd(Part* P, int pos, int start) {
    int i = pos + P->stsz;
    u64* t = P->st;
    t[i] = (start && P->csz[pos] >= 2) ? (((u64)(unsigned)P->csz[pos] << 32) | (u64)(unsigned)pos)
                                        : ~(u64)0;
    for (i >>= 1; i > 0; i >>= 1) {
        u64 m = t[2 * i] < t[2 * i + 1] ? t[2 * i] : t[2 * i + 1];
        if (t[i] == m) break;
        t[i] = m;
    }
}

/* Initial partition = colour classes in increasing colour value, all queued. */
static int part_init(Part* P, const IG* G, Ctl* ctl) {
    int n = G->n, i, c, pos;
    size_t N = (size_t)n;
    memset(P, 0, sizeof *P);
    P->g = G;
    P->ctl = ctl;
    P->n = n;
    P->lab = (int*)malloc(N * sizeof(int));
    P->inv = (int*)malloc(N * sizeof(int));
    P->cst = (int*)malloc(N * sizeof(int));
    P->csz = (int*)malloc(N * sizeof(int));
    P->inq = (unsigned char*)calloc(N, 1);
    P->q = (int*)malloc(N * sizeof(int));
    P->cnt = (int*)calloc(N, sizeof(int));
    P->tc = (int*)calloc(N, sizeof(int));
    P->tcl = (int*)malloc(N * sizeof(int));
    P->wbuf = (int*)malloc(N * sizeof(int));
    P->frs = (int*)malloc((N + 2) * sizeof(int));
    P->frc = (int*)malloc((N + 2) * sizeof(int));
    P->tmpv = (int*)malloc(N * sizeof(int));
    P->bkt = (int*)malloc((2 * N + 18) * sizeof(int));
    P->tmpk = (u64*)malloc(N * sizeof(u64));
    P->stsz = 1;
    while (P->stsz < n) P->stsz *= 2;
    P->st = (u64*)malloc(2 * (size_t)P->stsz * sizeof(u64));
    if (!P->lab || !P->inv || !P->cst || !P->csz || !P->inq || !P->q || !P->cnt || !P->tc ||
        !P->tcl || !P->wbuf || !P->frs || !P->frc || !P->tmpv || !P->bkt || !P->tmpk ||
        !P->st)
        return 0;
    /* counting sort of the vertices by colour class */
    {
        int* start = (int*)malloc(((size_t)G->ncls + 1) * sizeof(int));
        if (!start) return 0;
        start[0] = 0;
        for (c = 0; c < G->ncls; c++) start[c + 1] = start[c] + G->clssz[c];
        for (i = 0; i < n; i++) {
            c = G->cls[i];
            pos = start[c]++;
            P->lab[pos] = i;
            P->inv[i] = pos;
        }
        free(start);
    }
    for (i = 0; i < 2 * P->stsz; i++) P->st[i] = ~(u64)0;
    pos = 0;
    for (c = 0; c < G->ncls; c++) {
        int sz = G->clssz[c];
        for (i = pos; i < pos + sz; i++) P->cst[P->lab[i]] = pos;
        P->csz[pos] = sz;
        st_upd(P, pos, 1);
        enq(P, pos);
        pos += sz;
    }
    P->ncells = G->ncls;
    return 1;
}

static void perr(Part* P) {
    P->ctl->err = 1;
    P->abrt = 1;
}

/* Append the current hash as a trace event and compare with the references. */
static void emit(Part* P) {
    long idx;
    u64 x = P->h;
    if (P->ev.n + 1 > P->ev.cap && !uvec_grow(&P->ev, P->ev.n + 1)) {
        perr(P);
        return;
    }
    P->ev.a[P->ev.n++] = x;
    if (!P->cmpmode) return;
    idx = P->ev.n - 1 - P->evbase;
    if (P->eqA && (idx >= P->lenA || P->refA[idx] != x)) P->eqA = 0;
    if (P->stB == 0) {
        if (idx >= P->lenB)
            P->stB = 1;
        else if (x != P->refB[idx])
            P->stB = x > P->refB[idx] ? 1 : -1;
    }
    if (!P->eqA && P->stB < 0) P->abrt = 1;
}

/* Sort lab[b .. b+t) by count (counting sort when the range is small). */
static int sort_region(Part* P, int b, int t, int mn, int mx) {
    int *lab = P->lab, *inv = P->inv, *cnt = P->cnt, *out = P->tmpv;
    long range = (long)mx - mn + 1;
    int i;
    if (range <= 2L * t + 16) {
        int* bk = P->bkt;
        for (i = 0; i <= range; i++) bk[i] = 0;
        for (i = 0; i < t; i++) bk[cnt[lab[b + i]] - mn + 1]++;
        for (i = 0; i < range; i++) bk[i + 1] += bk[i];
        for (i = 0; i < t; i++) {
            int v = lab[b + i];
            out[bk[cnt[v] - mn]++] = v;
        }
    } else {
        u64* k = P->tmpk;
        for (i = 0; i < t; i++) {
            int v = lab[b + i];
            k[i] = ((u64)(unsigned)(cnt[v] - mn) << 32) | (u64)(unsigned)v;
        }
        qsort(k, (size_t)t, sizeof(u64), cmp_u64);
        for (i = 0; i < t; i++) out[i] = (int)(k[i] & 0xffffffffu);
    }
    if (P->lablog.n + 2L * t > P->lablog.cap && !ivec_grow(&P->lablog, P->lablog.n + 2L * t))
        return 0;
    for (i = 0; i < t; i++) {
        int v = out[i], q = b + i;
        if (lab[q] != v) {
            P->lablog.a[P->lablog.n++] = q;
            P->lablog.a[P->lablog.n++] = lab[q];
            lab[q] = v;
            inv[v] = q;
        }
    }
    return 1;
}

/* Split cell s (size sz) whose t touched vertices occupy its tail. */
static void do_split(Part* P, int r, int s, int sz, int t) {
    int e = s + sz, b = e - t, mn = INT_MAX, mx = INT_MIN, q, i, nf = 0, L = 0, inqp;
    int *lab = P->lab, *cnt = P->cnt, *frs = P->frs, *frc = P->frc;
    u64 h;
    for (q = b; q < e; q++) {
        int c = cnt[lab[q]];
        if (c < mn) mn = c;
        if (c > mx) mx = c;
    }
    if (t == sz && mn == mx) { /* no split; still an invariant fact */
        P->h = mix64(P->h, ((u64)(unsigned)s << 20) ^ ((u64)(unsigned)mn << 42) ^
                               (u64)(unsigned)(r + 1));
        return;
    }
    if (mn != mx && !sort_region(P, b, t, mn, mx)) {
        perr(P);
        return;
    }
    if (b > s) {
        frs[nf] = s;
        frc[nf] = 0;
        nf++;
    }
    for (q = b; q < e;) {
        int c = cnt[lab[q]];
        frs[nf] = q;
        frc[nf] = c;
        nf++;
        q++;
        while (q < e && cnt[lab[q]] == c) q++;
    }
    frs[nf] = e;
    h = mix64(P->h, ((u64)(unsigned)s << 8) ^ (u64)(unsigned)(r + 1) ^ ((u64)(unsigned)nf << 40));
    for (i = 0; i < nf; i++) {
        int fz = frs[i + 1] - frs[i];
        h = mix64(h, ((u64)(unsigned)frc[i] << 32) | (u64)(unsigned)fz);
        if (fz > frs[L + 1] - frs[L]) L = i;
    }
    P->h = h;
    inqp = P->inq[s];
    for (i = 1; i < nf; i++) {
        int f = frs[i], fz = frs[i + 1] - f;
        P->csz[f] = fz;
        for (q = f; q < f + fz; q++) P->cst[lab[q]] = f;
        if (!push2(&P->splitlog, s, f)) {
            perr(P);
            return;
        }
        P->ncells++;
    }
    P->csz[s] = frs[1] - s;
    st_upd(P, s, 1);
    if (frs[1] - s == 1 && !push1(&P->singlog, s)) {
        perr(P);
        return;
    }
    for (i = 1; i < nf; i++) {
        int f = frs[i];
        if (frs[i + 1] - f >= 2) {
            st_upd(P, f, 1);
        } else if (!push1(&P->singlog, f)) {
            perr(P);
            return;
        }
    }
    for (i = 0; i < nf; i++)
        if (inqp ? i > 0 : i != L) enq(P, frs[i]);
    emit(P);
}

static void split_cells(Part* P, int r) {
    int ci, q;
    sort_ints(P->tcl, P->ntc); /* invariant order: by cell position */
    for (ci = 0; ci < P->ntc; ci++) {
        int s = P->tcl[ci], sz = P->csz[s], t = P->tc[s], e = s + sz;
        if (!P->abrt) do_split(P, r, s, sz, t);
        for (q = e - t; q < e; q++) P->cnt[P->lab[q]] = 0;
        P->tc[s] = 0;
    }
    P->ntc = 0;
}

/* Count, for every vertex x, |{w in W : w in adj(x) direction r}| by visiting
 * the reverse adjacency (off, adj) of W's members. */
static void pass(Part* P, int r, int wn, const int* off, const int* adj) {
    const int* W = P->wbuf;
    int *cst = P->cst, *csz = P->csz, *cnt = P->cnt, *tc = P->tc, *lab = P->lab, *inv = P->inv;
    long work = 0;
    int i;
    for (i = 0; i < wn; i++) {
        int w = W[i], j, j1 = off[w + 1];
        for (j = off[w]; j < j1; j++) {
            int x = adj[j], s = cst[x];
            if (csz[s] == 1) continue;
            if (cnt[x]++ == 0) {
                int pos = s + csz[s] - 1 - tc[s], px = inv[x];
                if (tc[s]++ == 0) P->tcl[P->ntc++] = s;
                if (px != pos) { /* move x into the touched tail */
                    int y = lab[pos];
                    IVec* L = &P->lablog;
                    if (L->n + 4 > L->cap && !ivec_grow(L, L->n + 4)) {
                        perr(P);
                        return;
                    }
                    L->a[L->n++] = px;
                    L->a[L->n++] = x;
                    L->a[L->n++] = pos;
                    L->a[L->n++] = y;
                    lab[pos] = x;
                    inv[x] = pos;
                    lab[px] = y;
                    inv[y] = px;
                }
            }
        }
        work += j1 - off[w] + 1;
        if (work > 4096) {
            ctl_work(P->ctl, work);
            work = 0;
        }
    }
    ctl_work(P->ctl, work);
    if (P->ntc) split_cells(P, r);
}

/* Refine to the coarsest equitable partition.
 * Returns 0 done, 1 aborted (trace cannot match/beat the references),
 * -1 error. */
static int refine(Part* P) {
    const IG* g = P->g;
    P->h = 0x243F6A8885A308D3ULL;
    P->abrt = 0;
    P->evbase = P->ev.n;
    while (P->qn > 0 && P->ncells < P->n && !P->abrt) {
        int s = P->q[P->qh], sz;
        if (++P->qh == P->n) P->qh = 0;
        P->qn--;
        P->inq[s] = 0;
        sz = P->csz[s];
        memcpy(P->wbuf, P->lab + s, (size_t)sz * sizeof(int));
        P->h = mix64(P->h, ((u64)(unsigned)s << 32) | (u64)(unsigned)sz);
        if (g->uo) pass(P, 0, sz, g->uo, g->ua);
        if (g->oo) {
            if (!P->abrt) pass(P, 1, sz, g->io, g->ia); /* out-neighbours in W */
            if (!P->abrt) pass(P, 2, sz, g->oo, g->oa); /* in-neighbours in W  */
        }
    }
    while (P->qn > 0) {
        P->inq[P->q[P->qh]] = 0;
        if (++P->qh == P->n) P->qh = 0;
        P->qn--;
    }
    if (P->ctl->err) return -1;
    if (P->abrt) return 1;
    P->h = mix64(P->h, (u64)(unsigned)P->ncells);
    emit(P);
    if (P->ctl->err) return -1;
    if (P->cmpmode) {
        long ne = P->ev.n - P->evbase;
        if (P->eqA && ne != P->lenA) P->eqA = 0;
        if (P->stB == 0 && ne < P->lenB) P->stB = -1;
        if (!P->eqA && P->stB < 0) return 1;
    }
    return 0;
}

/* Individualize v: it becomes a singleton at the END of its cell. */
static int individualize(Part* P, int v) {
    int s = P->cst[v], sz = P->csz[s], e = s + sz - 1, pv = P->inv[v];
    if (pv != e) {
        int y = P->lab[e];
        if (!push2(&P->lablog, pv, v) || !push2(&P->lablog, e, y)) return 0;
        P->lab[e] = v;
        P->inv[v] = e;
        P->lab[pv] = y;
        P->inv[y] = pv;
    }
    P->csz[s] = sz - 1;
    P->csz[e] = 1;
    P->cst[v] = e;
    if (!push2(&P->splitlog, s, e)) return 0;
    P->ncells++;
    if (!push1(&P->singlog, e)) return 0;
    st_upd(P, s, 1);
    if (sz - 1 == 1 && !push1(&P->singlog, s)) return 0;
    enq(P, e);
    return 1;
}

/* Target cell: first smallest non-singleton cell (by size, then position). */
static int pick_target(const Part* P) {
    return P->st[1] == ~(u64)0 ? -1 : (int)(P->st[1] & 0xffffffffu);
}

static void get_mark(const Part* P, Mark* m) {
    m->lab = P->lablog.n;
    m->split = P->splitlog.n;
    m->sing = P->singlog.n;
    m->ev = P->ev.n;
}

static void reset_logs(Part* P) {
    P->lablog.n = P->splitlog.n = P->singlog.n = 0;
}

/* Restore the exact state recorded in m (partition, lab order, sets). */
static void undo_to(Part* P, const Mark* m) {
    int* a = P->splitlog.a;
    while (P->splitlog.n > m->split) {
        int f = a[--P->splitlog.n], s = a[--P->splitlog.n], fz = P->csz[f], q;
        /* lab[f .. f+fz) still holds exactly fragment f's vertices: later
         * writes only permute within cells, later splits are undone first */
        for (q = f; q < f + fz; q++) P->cst[P->lab[q]] = s;
        P->csz[s] += fz;
        P->ncells--;
        st_upd(P, f, 0);
        st_upd(P, s, 1);
    }
    a = P->lablog.a;
    while (P->lablog.n > m->lab) {
        int old = a[--P->lablog.n], p = a[--P->lablog.n];
        P->lab[p] = old;
        P->inv[old] = p;
    }
    P->singlog.n = m->sing;
    P->ev.n = m->ev;
}

/* ========================================================================
 * Map verification (edge by edge)
 * ======================================================================== */

static int rel_map_ok(int n, const int* go, const int* ga, const int* ho, const int* ha,
                      const int* map, int* mark, int* stamp) {
    int v;
    long j;
    for (v = 0; v < n; v++) {
        int w = map[v], d = go[v + 1] - go[v];
        if (ho[w + 1] - ho[w] != d) return 0;
        if (d == 0) continue;
        ++*stamp;
        for (j = ho[w]; j < ho[w + 1]; j++) mark[ha[j]] = *stamp;
        for (j = go[v]; j < go[v + 1]; j++)
            if (mark[map[ga[j]]] != *stamp) return 0;
    }
    return 1;
}

/* 1 if map is an isomorphism G -> H (colours and every relation). */
static int verify_map(const IG* G, const IG* H, const int* map, int* mark) {
    int n = G->n, v, stamp = 0;
    for (v = 0; v < n; v++) mark[v] = 0;
    for (v = 0; v < n; v++) {
        int gv = G->vcol ? G->vcol[v] : 0, hv;
        if (map[v] < 0 || map[v] >= n) return 0;
        hv = H->vcol ? H->vcol[map[v]] : 0;
        if (gv != hv) return 0;
    }
    if ((G->uo == NULL) != (H->uo == NULL) || (G->oo == NULL) != (H->oo == NULL)) return 0;
    if (G->uo && !rel_map_ok(n, G->uo, G->ua, H->uo, H->ua, map, mark, &stamp)) return 0;
    if (G->oo && !rel_map_ok(n, G->oo, G->oa, H->oo, H->oa, map, mark, &stamp)) return 0;
    return 1;
}

