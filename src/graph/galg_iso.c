typedef uint64_t u64;

#define ISO_POLL_NODES 256L
#define ISO_POLL_WORK (1L << 15)

/* Node limit of the direct G -> H search before falling back to comparing
 * canonical forms (overridable for testing). */
#ifndef GALG_ISO_DIRECT_LIMIT
#define GALG_ISO_DIRECT_LIMIT(n) (4L * (n) + 1000)
#endif

