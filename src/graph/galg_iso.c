/* galg_iso.c - graph isomorphism and canonical labeling by
 * individualization-refinement (the nauty / bliss / Traces family).
 *
 * No Expr dependency: the engine works on GalgIsoGraph (CSR relations) and
 * calls nothing outside the C library except galg_poll().
 *
 * ---------------------------------------------------------------------------
 * 1. Relations and colours
 *    A graph carries up to three relations over 0..n-1: undirected (U),
 *    directed out (O) and its transpose in (I). Missing transposes are built
 *    here, empty relations are dropped, so two graphs with the same edge
 *    counts always run exactly the same refinement passes. vcol values are
 *    ranked; the initial ordered partition lists the colour classes by
 *    increasing colour value (an isomorphism-invariant order).
 *
 * 2. Refinement (1-dimensional Weisfeiler-Leman, Hopcroft / Paige-Tarjan)
 *    The ordered partition is kept nauty-style in lab[] (cells are contiguous
 *    position ranges, a cell is named by its start position). A FIFO queue of
 *    splitter cells drives the refinement. For a splitter W and each relation
 *    R separately, only the R-neighbours of W are visited; every visited
 *    vertex gets a count |R(x) cap W| and is swapped to the tail of its cell,
 *    so the untouched part (count 0) stays at the front and needs no work.
 *    Touched cells are processed in increasing start position, the touched
 *    tail is sorted by count, and the cell becomes the fragments
 *    [count 0][count c1][count c2]... (c1 < c2 < ...). If the parent cell was
 *    queued, all new fragments are queued, otherwise all but the first
 *    largest (Hopcroft's "skip the largest half"), which gives
 *    O((n + m) log n) per full refinement. Singleton cells are never touched.
 *    The result is the coarsest equitable refinement.
 *
 *    Invariance: every decision (splitter order, touched-cell order, fragment
 *    order, queueing) depends only on cell start positions, cell sizes and
 *    counts, never on vertex ids, so for an isomorphism phi the refinement of
 *    phi(G) is exactly phi applied to the refinement of G, split for split.
 *    Vertex order inside a cell is arbitrary (it may depend on ids); nothing
 *    reads it except the non-invariant choice of the first-path child.
 *
 * 3. Traces
 *    Each refinement produces a trace: a running 64-bit hash over
 *    (splitter position/size, relation, touched cell, fragment counts and
 *    sizes), emitted as one event per actual split plus a final event (with
 *    the cell count). Events are compared on the fly against a reference
 *    trace (first path, best path, or the other graph); the refinement is
 *    abandoned as soon as it can no longer match or beat the reference
 *    ("early abort"). This is what makes the search cheap: a wrong branch in
 *    a random regular graph dies after O(sqrt n) work instead of O(n log n).
 *    Events per node <= new cells + 1, so traces along a path are O(n).
 *
 * 4. Search tree
 *    Node = equitable ordered partition; child = individualize a vertex of
 *    the target cell (first smallest non-singleton cell, by (size, start) --
 *    invariant) and refine. Individualized vertices go to the END of their
 *    cell so the big remainder keeps its start (O(1) individualization).
 *    The tree is walked iteratively with per-level undo marks: every split,
 *    lab write and set operation is logged and undone exactly, so memory is
 *    O(n + m + work on the current path) and the depth may be n (no
 *    recursion anywhere).
 *
 * 5. Canonical form (galg_iso_canon / galg_iso_automorphisms)
 *    Leaf key = (trace of level 1, trace of level 2, ..., relabeled graph),
 *    compared lexicographically; the canonical labeling is the leaf of
 *    maximal key. The key is isomorphism-invariant, hence relabeling G and
 *    phi(G) by their best leaves gives identical graphs. Pruning (nauty):
 *    - trace pruning: a node whose trace prefix is below the best leaf's and
 *      differs from the first leaf's is cut (mid-refinement);
 *    - automorphisms: a leaf equal (as relabeled graph) to the first leaf or
 *      the best leaf yields an automorphism; an internal node whose trace
 *      equals the first path's is also tested directly: the singletons
 *      created on the first path since the divergence level are mapped
 *      positionally to the current node's singletons, the partial map is
 *      closed into a permutation that fixes everything else, and it is
 *      verified on the moved vertices only (this finds twins, swapped
 *      components, ... without descending). After an automorphism we jump
 *      back to the divergence level (first leaf) or to the common ancestor
 *      (best leaf);
 *    - orbit pruning on the first path: at first-path level k only one child
 *      per orbit of the group generated by the automorphisms found so far
 *      (all of which fix the first-path prefix) is explored; a level is
 *      finished as soon as the explored orbits cover the target cell.
 *    The automorphisms found this way generate Aut(G) (standard
 *    individualization-refinement argument, as in nauty).
 *
 * 6. Isomorphism (galg_iso_find / galg_iso_enumerate)
 *    Quick rejections (n, edge counts, colour classes, degree histograms),
 *    then G and H are refined in lockstep. find: follow one path in G and
 *    search H for a path with identical traces (early abort on the first
 *    deviating event), verifying the map edge by edge at a leaf. If that
 *    direct search exceeds ~4n nodes, fall back to comparing the two
 *    canonical forms (robust with automorphism pruning). enumerate: the
 *    direct search without pruning visits every H-leaf trace-consistent with
 *    G's path exactly once; every isomorphism corresponds to exactly one
 *    such leaf, so each verified leaf is reported once.
 *
 * Complexity: one refinement O((n + m) log n); the number of tree nodes is
 * small for random and most structured graphs and bounded by `budget`
 * (refinement calls) in the worst case (e.g. CFI-type constructions).
 * galg_poll() is called every 256 nodes and every ~32k edge visits.
 */

