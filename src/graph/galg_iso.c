static int uf_find(int* uf, int x) {
    while (uf[x] != x) {
        uf[x] = uf[uf[x]];
        x = uf[x];
    }
    return x;
}

/* Merge orbits; keep `covered` (processed part of the current first-path
 * target cell) up to date. */
static void uf_union(Canon* C, int a, int b) {
    int ra = uf_find(C->uf, a), rb = uf_find(C->uf, b), pa, pb;
    if (ra == rb) return;
    pa = C->pmark[ra] == C->stamp;
    pb = C->pmark[rb] == C->stamp;
    if (pa && !pb) C->covered += C->ufs[rb];
    if (pb && !pa) C->covered += C->ufs[ra];
    if (C->ufs[ra] < C->ufs[rb]) {
        int t = ra;
        ra = rb;
        rb = t;
    }
    C->uf[rb] = ra;
    C->ufs[ra] += C->ufs[rb];
    C->pmark[ra] = (pa || pb) ? C->stamp : 0;
}

static int img(const int* gam, int v) { return gam[v] >= 0 ? gam[v] : v; }

/* gamma(R(v)) == R(gamma(v)) for one relation. */
static int check_rel(Canon* C, const int* off, const int* adj, int v, int w) {
    int d = off[v + 1] - off[v];
    long j;
    if (off[w + 1] - off[w] != d) return 0;
    if (d == 0) return 1;
    if (C->vstamp == INT_MAX) {
        memset(C->vmark, 0, (size_t)C->n * sizeof(int));
        C->vstamp = 0;
    }
    C->vstamp++;
    for (j = off[w]; j < off[w + 1]; j++) C->vmark[adj[j]] = C->vstamp;
    for (j = off[v]; j < off[v + 1]; j++)
        if (C->vmark[img(C->gam, adj[j])] != C->vstamp) return 0;
    return 1;
}

/* gamma (gam[], identity where -1) is an automorphism iff every moved vertex
 * keeps its colour and its U, O and I neighbourhoods map onto those of its
 * image: an edge between two fixed vertices is trivially preserved, every
 * other edge is seen from a moved endpoint. */
static int verify_moved(Canon* C, int nm) {
    const IG* g = C->g;
    int i;
    for (i = 0; i < nm; i++) {
        int v = C->mv[i], w = img(C->gam, v);
        if (g->cls[v] != g->cls[w]) return 0;
        if (g->uo && !check_rel(C, g->uo, g->ua, v, w)) return 0;
        if (g->oo && (!check_rel(C, g->oo, g->oa, v, w) || !check_rel(C, g->io, g->ia, v, w)))
            return 0;
    }
    return 1;
}

static int add_gen(Canon* C, int nm) {
    IVec* G = &C->gens;
    int i;
    if (!ivec_grow(G, G->n + 1 + 2L * nm)) return 0;
    G->a[G->n++] = nm;
    for (i = 0; i < nm; i++) {
        G->a[G->n++] = C->mv[i];
        G->a[G->n++] = img(C->gam, C->mv[i]);
    }
    C->ngens++;
    for (i = 0; i < nm; i++) uf_union(C, C->mv[i], img(C->gam, C->mv[i]));
    return 1;
}

/* Current node at level t has the first path's trace and diverged from the
 * first path at level ell. Map the singletons the first path created below
 * ell onto the current singletons at the same positions, close the partial
 * map into a permutation fixing everything else, and verify it.
 * 1 = automorphism found (and recorded), 0 = no, -1 = allocation failure. */
static int try_aut_fp(Canon* C, int ell, int t) {
    Part* P = &C->P;
    long i, a0 = C->fpsingoff[ell], a1 = C->fpsingoff[t];
    int nm = 0, nr = 0, ok = 1, j, res = 0;
    for (i = a0; i < a1; i++) {
        int p = C->fpsing[i], a = C->fplab[p], b = P->lab[p];
        if (P->cst[b] != p || P->csz[p] != 1) {
            ok = 0;
            break;
        }
        if (a != b) {
            C->gam[a] = b;
            C->mv[nm++] = a;
            C->inR[b] = 1;
            C->rl[nr++] = b;
        }
    }
    if (ok) {
        int nd = nm;
        for (j = 0; j < nd; j++) { /* close each path a -> ... -> x into a cycle */
            int a = C->mv[j];
            if (!C->inR[a]) {
                int x = C->gam[a];
                while (C->gam[x] >= 0) x = C->gam[x];
                C->gam[x] = a;
                C->mv[nm++] = x;
            }
        }
        for (j = ell; j < t && ok; j++)
            if (img(C->gam, C->fpv[j]) != C->cv[j]) ok = 0;
        if (ok && nm > 0 && verify_moved(C, nm)) res = add_gen(C, nm) ? 1 : -1;
    }
    for (j = 0; j < nm; j++) C->gam[C->mv[j]] = -1;
    for (j = 0; j < nr; j++) C->inR[C->rl[j]] = 0;
    return res;
}

/* Current leaf has the same relabeled graph as the best leaf. */
static int try_aut_bp(Canon* C) {
    Part* P = &C->P;
    int p, nm = 0, res = 0, j;
    for (p = 0; p < C->n; p++) {
        int a = C->bplab[p], b = P->lab[p];
        if (a != b) {
            C->gam[a] = b;
            C->mv[nm++] = a;
        }
    }
    if (nm > 0 && verify_moved(C, nm)) res = add_gen(C, nm) ? 1 : -1;
    for (j = 0; j < nm; j++) C->gam[C->mv[j]] = -1;
    return res;
}

/* Sorted canonical labels of the R-neighbours of v. */
static int row_sorted(const int* off, const int* adj, const int* inv, int v, int* out) {
    int d = off[v + 1] - off[v], i, j;
    for (i = 0; i < d; i++) out[i] = inv[adj[off[v] + i]];
    if (d > 16) {
        qsort(out, (size_t)d, sizeof(int), cmp_int);
    } else {
        for (i = 1; i < d; i++) {
            int x = out[i];
            for (j = i; j > 0 && out[j - 1] > x; j--) out[j] = out[j - 1];
            out[j] = x;
        }
    }
    return d;
}

/* Compare the graph relabeled by the current leaf with the best one. */
static int compare_leaf(Canon* C) {
    const IG* g = C->g;
    const int *lab = C->P.lab, *inv = C->P.inv;
    int r, p, i;
    for (r = 0; r < 2; r++) {
        const int* off = r == 0 ? g->uo : g->oo;
        const int* adj = r == 0 ? g->ua : g->oa;
        const int* co = r == 0 ? C->cuo : C->coo;
        const int* ca = r == 0 ? C->cua : C->coa;
        if (!off) continue;
        for (p = 0; p < C->n; p++) {
            int d = row_sorted(off, adj, inv, lab[p], C->rowbuf), bd = co[p + 1] - co[p];
            const int* brow = ca + co[p];
            if (d != bd) return d > bd ? 1 : -1;
            for (i = 0; i < d; i++)
                if (C->rowbuf[i] != brow[i]) return C->rowbuf[i] > brow[i] ? 1 : -1;
        }
    }
    return 0;
}

static void store_rows(Canon* C) {
    const IG* g = C->g;
    const int *lab = C->P.lab, *inv = C->P.inv;
    int r, p;
    for (r = 0; r < 2; r++) {
        const int* off = r == 0 ? g->uo : g->oo;
        const int* adj = r == 0 ? g->ua : g->oa;
        int* co = r == 0 ? C->cuo : C->coo;
        int* ca = r == 0 ? C->cua : C->coa;
        co[0] = 0;
        for (p = 0; p < C->n; p++)
            co[p + 1] = co[p] + (off ? row_sorted(off, adj, inv, lab[p], ca + co[p]) : 0);
    }
}

/* The current leaf (level k1) becomes the best leaf. */
static int new_best(Canon* C, int k1) {
    Part* P = &C->P;
    int j;
    C->BL = k1;
    memcpy(C->bpv, C->cv, (size_t)k1 * sizeof(int));
    memcpy(C->bplab, P->lab, (size_t)C->n * sizeof(int));
    if (!uvec_grow(&C->bpev, P->ev.n + 1)) return 0;
    memcpy(C->bpev.a, P->ev.a, (size_t)P->ev.n * sizeof(u64));
    C->bpev.n = P->ev.n;
    for (j = 0; j <= k1; j++) {
        C->bpevoff[j] = C->mk[j].ev;
        C->onb[j] = 1;
        C->cmpb[j] = 0;
    }
    store_rows(C);
    return 1;
}

static void begin_level(Canon* C, int k) {
    int r = uf_find(C->uf, C->fpv[k]);
    C->stamp++;
    C->pmark[r] = C->stamp;
    C->covered = C->ufs[r];
    C->k0 = k;
}

/* Full canonical search. 1 ok, -1 budget/allocation. */
static int canon_run(Canon* C) {
    Part* P = &C->P;
    Ctl* ctl = C->ctl;
    int n = C->n, k, j;
    P->cmpmode = 0;
    if (!ctl_node(ctl) || refine(P) < 0) return -1;
    reset_logs(P);
    P->ev.n = 0;
    get_mark(P, &C->mk[0]);
    if (P->ncells == n) {
        C->L = 0;
        return new_best(C, 0) ? 1 : -1;
    }
    /* first path */
    k = 0;
    for (;;) {
        int s = pick_target(P);
        C->ls[k] = s;
        C->lsz[k] = P->csz[s];
        C->li[k] = 1;
        C->cv[k] = P->lab[s];
        if (!individualize(P, C->cv[k])) return -1;
        if (!ctl_node(ctl) || refine(P) < 0) return -1;
        k++;
        get_mark(P, &C->mk[k]);
        if (P->ncells == n) break;
    }
    C->L = k;
    C->fpev = (u64*)malloc((size_t)(P->ev.n + 1) * sizeof(u64));
    C->fpsing = (int*)malloc((size_t)(P->singlog.n + 1) * sizeof(int));
    if (!C->fpev || !C->fpsing) return -1;
    memcpy(C->fpev, P->ev.a, (size_t)P->ev.n * sizeof(u64));
    memcpy(C->fpsing, P->singlog.a, (size_t)P->singlog.n * sizeof(int));
    for (j = 0; j <= k; j++) {
        C->fpevoff[j] = C->mk[j].ev;
        C->fpsingoff[j] = C->mk[j].sing;
        C->eqf[j] = 1;
        C->onf[j] = 1;
    }
    memcpy(C->fpv, C->cv, (size_t)k * sizeof(int));
    memcpy(C->fplab, P->lab, (size_t)n * sizeof(int));
    if (!new_best(C, k)) return -1;

    /* backtracking over the rest of the tree */
    k = C->L - 1;
    undo_to(P, &C->mk[k]);
    begin_level(C, k);
    P->cmpmode = 1;
    for (;;) {
        int s = C->ls[k], sz = C->lsz[k], c = -1, rt = -1, k1, a, jump, rr;
        if (!C->onf[k] || C->covered < sz) {
            while (C->li[k] < sz) {
                int x = P->lab[s + C->li[k]++];
                if (C->onf[k]) { /* one child per orbit on the first path */
                    rt = uf_find(C->uf, x);
                    if (C->pmark[rt] == C->stamp) {
                        ctl_work(ctl, 1);
                        continue;
                    }
                }
                c = x;
                break;
            }
        }
        if (c < 0) { /* level exhausted */
            int wasfirst = C->onf[k];
            if (k == 0) break;
            k--;
            undo_to(P, &C->mk[k]);
            if (wasfirst) begin_level(C, k);
            continue;
        }
        if (C->onf[k]) {
            C->pmark[rt] = C->stamp;
            C->covered += C->ufs[rt];
        }
        C->cv[k] = c;
        if (!individualize(P, c) || !ctl_node(ctl)) return -1;
        if (C->eqf[k] && k + 1 <= C->L) {
            P->refA = C->fpev + C->fpevoff[k];
            P->lenA = C->fpevoff[k + 1] - C->fpevoff[k];
            P->eqA = 1;
        } else {
            P->eqA = 0;
        }
        if (C->cmpb[k] != 0) {
            P->stB = C->cmpb[k];
        } else if (k + 1 <= C->BL) {
            P->refB = C->bpev.a + C->bpevoff[k];
            P->lenB = C->bpevoff[k + 1] - C->bpevoff[k];
            P->stB = 0;
        } else {
            P->stB = 1;
        }
        rr = refine(P);
        if (rr < 0) return -1;
        if (rr > 0) {
            undo_to(P, &C->mk[k]);
            continue;
        }
        k1 = k + 1;
        get_mark(P, &C->mk[k1]);
        C->eqf[k1] = (unsigned char)P->eqA;
        C->cmpb[k1] = (signed char)P->stB;
        C->onf[k1] = 0;
        C->onb[k1] = (unsigned char)(C->onb[k] && k < C->BL && c == C->bpv[k]);
        jump = -1;
        if (C->eqf[k1]) {
            a = try_aut_fp(C, C->k0, k1);
            if (a < 0) return -1;
            if (a) jump = C->k0;
        }
        if (P->ncells == n) { /* leaf */
            if (jump < 0 && C->cmpb[k1] >= 0) {
                int cmp = C->cmpb[k1] > 0 ? 1 : compare_leaf(C);
                if (cmp > 0) {
                    if (!new_best(C, k1)) return -1;
                } else if (cmp == 0) {
                    a = try_aut_bp(C);
                    if (a < 0) return -1;
                    if (a) {
                        j = k;
                        while (j > 0 && !C->onb[j]) j--;
                        jump = j;
                    }
                }
            }
            undo_to(P, &C->mk[k]);
            if (jump >= 0 && jump < k) {
                k = jump;
                undo_to(P, &C->mk[k]);
            }
            continue;
        }
        if (jump >= 0) {
            k = jump;
            undo_to(P, &C->mk[k]);
            continue;
        }
        k = k1; /* descend */
        s = pick_target(P);
        C->ls[k] = s;
        C->lsz[k] = P->csz[s];
        C->li[k] = 0;
    }
    return 1;
}

/* ========================================================================
 * Direct isomorphism search G -> H
 * ======================================================================== */

typedef struct {
    long maxc;
    int (*cb)(const int* map, void* ctx);
    void* ctx;
    long count;
} EnumCtx;

/* Follow one path in G; search H for paths with identical traces.
 * find mode (en == NULL): 1 found (map filled), 0 not isomorphic,
 * 2 node limit reached, -1 error. enumerate mode: 1 complete/stopped,
 * -1 error (en->count holds the number reported). */
static int direct_search(const IG* G, const IG* H, Ctl* ctl, int* map, long limit,
                         EnumCtx* en) {
    int n = G->n, k, L = 0, res = -1, rr;
    Part Pg, Ph;
    int *gls = NULL, *glsz = NULL, *li = NULL, *mark = NULL;
    long *gevoff = NULL, start;
    Mark* mk = NULL;
    memset(&Pg, 0, sizeof Pg);
    memset(&Ph, 0, sizeof Ph);
    if (!part_init(&Pg, G, ctl) || !part_init(&Ph, H, ctl)) goto done;
    gls = (int*)malloc(((size_t)n + 1) * sizeof(int));
    glsz = (int*)malloc(((size_t)n + 1) * sizeof(int));
    li = (int*)malloc(((size_t)n + 1) * sizeof(int));
    mark = (int*)malloc((size_t)n * sizeof(int));
    gevoff = (long*)malloc(((size_t)n + 2) * sizeof(long));
    mk = (Mark*)malloc(((size_t)n + 1) * sizeof(Mark));
    if (!gls || !glsz || !li || !mark || !gevoff || !mk) goto done;

    /* roots in lockstep */
    Pg.cmpmode = 0;
    if (!ctl_node(ctl) || refine(&Pg) < 0) goto done;
    gevoff[0] = Pg.ev.n;
    Ph.cmpmode = 1;
    Ph.refA = Pg.ev.a;
    Ph.lenA = Pg.ev.n;
    Ph.eqA = 1;
    Ph.stB = -1;
    if (!ctl_node(ctl)) goto done;
    rr = refine(&Ph);
    if (rr < 0) goto done;
    if (rr > 0) {
        res = en ? 1 : 0;
        goto done;
    }
    reset_logs(&Pg);
    reset_logs(&Ph);
    Ph.ev.n = 0;

    /* G's path */
    k = 0;
    while (Pg.ncells < n) {
        int s = pick_target(&Pg);
        gls[k] = s;
        glsz[k] = Pg.csz[s];
        if (!individualize(&Pg, Pg.lab[s]) || !ctl_node(ctl) || refine(&Pg) < 0) goto done;
        k++;
        gevoff[k] = Pg.ev.n;
    }
    L = k;

    /* H's tree */
    start = ctl->nodes;
    get_mark(&Ph, &mk[0]);
    li[0] = 0;
    k = 0;
    for (;;) {
        int s, sz, c;
        if (k == L) { /* leaf (only reached directly when L == 0) */
            c = 0;
        } else {
            s = gls[k];
            sz = glsz[k];
            if (li[k] == 0 && (Ph.cst[Ph.lab[s]] != s || Ph.csz[s] != sz)) li[k] = sz;
            if (li[k] >= sz) {
                if (k == 0) break;
                k--;
                undo_to(&Ph, &mk[k]);
                continue;
            }
            c = Ph.lab[s + li[k]++];
            if (!individualize(&Ph, c) || !ctl_node(ctl)) goto done;
            if (limit > 0 && ctl->nodes - start > limit) {
                res = 2;
                goto done;
            }
            Ph.refA = Pg.ev.a + gevoff[k];
            Ph.lenA = gevoff[k + 1] - gevoff[k];
            Ph.eqA = 1;
            Ph.stB = -1;
            rr = refine(&Ph);
            if (rr < 0) goto done;
            if (rr > 0) {
                undo_to(&Ph, &mk[k]);
                continue;
            }
        }
        if (k == L || k + 1 == L) {
            int p, found = 0;
            if (Ph.ncells == n) {
                for (p = 0; p < n; p++) map[Pg.lab[p]] = Ph.lab[p];
                found = verify_map(G, H, map, mark);
            }
            if (found) {
                if (!en) {
                    res = 1;
                    goto done;
                }
                en->count++;
                if ((en->cb && !en->cb(map, en->ctx)) || (en->maxc > 0 && en->count >= en->maxc)) {
                    res = 1;
                    goto done;
                }
            }
            if (k == L) break; /* L == 0: single leaf */
            undo_to(&Ph, &mk[k]);
            continue;
        }
        k++;
        get_mark(&Ph, &mk[k]);
        li[k] = 0;
    }
    res = en ? 1 : 0;
done:
    part_free(&Pg);
    part_free(&Ph);
    free(gls);
    free(glsz);
    free(li);
    free(mark);
    free(gevoff);
    free(mk);
    return res;
}

/* Compare canonical forms of G and H. 1 (map filled) / 0 / -1. */
static int canon_compare(const IG* G, const IG* H, Ctl* ctl, int* map) {
    Canon A, B;
    int res = -1, n = G->n, p;
    int* mark = NULL;
    memset(&A, 0, sizeof A);
    memset(&B, 0, sizeof B);
    if (!canon_init(&A, G, ctl) || !canon_init(&B, H, ctl)) goto done;
    if (canon_run(&A) < 0 || canon_run(&B) < 0) goto done;
    res = 0;
    for (p = 0; p < n; p++) {
        int ca = G->vcol ? G->vcol[A.bplab[p]] : 0, cb = H->vcol ? H->vcol[B.bplab[p]] : 0;
        if (ca != cb) goto done;
    }
    if (memcmp(A.cuo, B.cuo, ((size_t)n + 1) * sizeof(int)) ||
        memcmp(A.coo, B.coo, ((size_t)n + 1) * sizeof(int)) ||
        (G->mu > 0 && memcmp(A.cua, B.cua, (size_t)G->mu * sizeof(int))) ||
        (G->md > 0 && memcmp(A.coa, B.coa, (size_t)G->md * sizeof(int))))
        goto done;
    mark = (int*)malloc((size_t)n * sizeof(int));
    if (!mark) {
        res = -1;
        goto done;
    }
    for (p = 0; p < n; p++) map[A.bplab[p]] = B.bplab[p];
    res = verify_map(G, H, map, mark); /* always 1 when the forms agree */
done:
    free(mark);
    canon_free(&A);
    canon_free(&B);
    return res;
}

static int find_core(const IG* G, const IG* H, Ctl* ctl, int* map) {
    int r = direct_search(G, H, ctl, map, GALG_ISO_DIRECT_LIMIT(G->n), NULL);
    if (r == 2) r = canon_compare(G, H, ctl, map);
    return r;
}

/* Build both graphs and run the quick tests. 1 go on, 0 not iso, -1 error. */
static int prepare_pair(const GalgIsoGraph* g, const GalgIsoGraph* h, IG* G, IG* H) {
    int r;
    memset(G, 0, sizeof *G);
    memset(H, 0, sizeof *H);
    if (!ig_build(G, g) || !ig_build(H, h)) return -1;
    r = quick_same(G, H);
    return r;
}

/* ========================================================================
 * Public interface
 * ======================================================================== */

int galg_iso_find(const GalgIsoGraph* g, const GalgIsoGraph* h, int* map, long budget) {
    IG G, H;
    Ctl ctl;
    int r;
    if (!g || !h || g->n < 0 || h->n < 0) return -1;
    if (g->n != h->n) return 0;
    if (g->n == 0) return 1;
    if (!map) return -1;
    r = prepare_pair(g, h, &G, &H);
    if (r > 0) {
        memset(&ctl, 0, sizeof ctl);
        ctl.budget = budget;
        r = find_core(&G, &H, &ctl, map);
    }
    ig_free(&G);
    ig_free(&H);
    return r;
}

long galg_iso_enumerate(const GalgIsoGraph* g, const GalgIsoGraph* h, long max_count,
                        int (*cb)(const int* map, void* ctx), void* ctx, long budget) {
    IG G, H;
    Ctl ctl;
    EnumCtx en;
    int r;
    int* map;
    long res;
    if (!g || !h || g->n < 0 || h->n < 0) return -1;
    if (g->n != h->n) return 0;
    if (g->n == 0) {
        int dummy = 0;
        if (cb) cb(&dummy, ctx);
        return 1;
    }
    map = (int*)malloc((size_t)g->n * sizeof(int));
    if (!map) return -1;
    r = prepare_pair(g, h, &G, &H);
    res = r;
    if (r > 0) {
        memset(&ctl, 0, sizeof ctl);
        ctl.budget = budget;
        r = find_core(&G, &H, &ctl, map); /* settles non-isomorphic pairs robustly */
        res = r;
        if (r > 0) {
            en.maxc = max_count;
            en.cb = cb;
            en.ctx = ctx;
            en.count = 0;
            r = direct_search(&G, &H, &ctl, map, 0, &en);
            res = r < 0 ? -1 : en.count;
        }
    }
    free(map);
    ig_free(&G);
    ig_free(&H);
    return res;
}

int galg_iso_canon(const GalgIsoGraph* g, int* lab, long budget) {
    IG G;
    Ctl ctl;
    Canon C;
    int r;
    if (!g || g->n < 0) return -1;
    if (g->n == 0) return 1;
    if (!lab) return -1;
    memset(&C, 0, sizeof C);
    if (!ig_build(&G, g)) {
        ig_free(&G);
        return -1;
    }
    memset(&ctl, 0, sizeof ctl);
    ctl.budget = budget;
    r = canon_init(&C, &G, &ctl) ? canon_run(&C) : -1;
    if (r > 0) memcpy(lab, C.bplab, (size_t)g->n * sizeof(int));
    canon_free(&C);
    ig_free(&G);
    return r > 0 ? 1 : -1;
}

long galg_iso_automorphisms(const GalgIsoGraph* g, int** gens, long budget) {
    IG G;
    Ctl ctl;
    Canon C;
    long res = -1, i, pos;
    int n, v;
    if (!gens) return -1;
    *gens = NULL;
    if (!g || g->n < 0) return -1;
    if (g->n == 0) return 0;
    n = g->n;
    memset(&C, 0, sizeof C);
    if (!ig_build(&G, g)) {
        ig_free(&G);
        return -1;
    }
    memset(&ctl, 0, sizeof ctl);
    ctl.budget = budget;
    if (canon_init(&C, &G, &ctl) && canon_run(&C) > 0) {
        if (C.ngens == 0) {
            res = 0;
        } else if ((size_t)C.ngens <= ((size_t)-1) / sizeof(int) / (size_t)n) {
            int* out = (int*)malloc((size_t)C.ngens * (size_t)n * sizeof(int));
            if (out) {
                pos = 0;
                for (i = 0; i < C.ngens; i++) {
                    int* p = out + (size_t)i * (size_t)n;
                    int nm = C.gens.a[pos++], j;
                    for (v = 0; v < n; v++) p[v] = v;
                    for (j = 0; j < nm; j++) {
                        int a = C.gens.a[pos++], b = C.gens.a[pos++];
                        p[a] = b;
                    }
                }
                *gens = out;
                res = C.ngens;
            }
        }
    }
    canon_free(&C);
    ig_free(&G);
    return res;
}
