/* test_bronstein_completeness.c -- the failure taxonomy and the
 * "implementation incomplete" surface of the Bronstein completion campaign
 * (BRONSTEIN_PLAN.md, "2026-11-14 -- Completion campaign", Phases 0-1).
 *
 *  - the five failure classes of the Trager/Bronstein protocol (trager/Common.m):
 *    throwIncomplete / throwUnimplemented, failToList, tragerRetryableQ;
 *  - the Kummer cyclicity decision that separates one simple radical in
 *    disguise from a genuine compositum (brKummerCyclicQ);
 *  - BronsteinScope, the classifier the Automatic cascade asks;
 *  - the growing-height specialization search (brSpecializationPoint);
 *  - Integrate::incomplete: Method -> "Bronstein" / "Trager", the Automatic
 *    cascade, Quiet / Check, and the cases that must stay silent (an answer, a
 *    certificate, a non-elementary input, a definite integral);
 *  - Phase 0 soundness: a CAS failure is never a certificate
 *    (Risch`ElementaryIntegralQ through the base-field route, Cos[E^x]).
 */
#include "bronstein_test_utils.h"

static void test_failure_classes(void) {
    BR_EQ("failToList[Catch[throwIncomplete[\"r\"], \"TragerFail\"]]", "{\"implementation incomplete\", \"r\"}");
    BR_EQ("failToList[Catch[throwUnimplemented[\"S:t\", \"r\"], \"TragerFail\"]]", "{\"implementation incomplete\", \"r\"}");
    BR_EQ("Catch[throwUnimplemented[\"S:t\", \"r\"], \"TragerFail\"][[3]][\"site\"]", "\"S:t\"");
    BR_EQ("Catch[throwUnimplemented[\"S:t\", \"r\", <|\"a\" -> 1|>], \"TragerFail\"][[3]][\"a\"]", "1");
    BR_EQ("failToList[Catch[throwDecline[\"r\"], \"TragerFail\"]]", "{\"failed\", \"r\"}");
    BR_EQ("failToList[Catch[throwInternal[\"inv\"], \"TragerFail\"]]", "{\"failed\", \"internal: inv\"}");
    BR_EQ("failToList[Catch[throwNonElementary[\"c\"], \"TragerFail\"]]", "{\"not elementary\", \"c\"}");
    /* retryable: proves nothing, so another construction may be tried */
    BR_TRUE("tragerRetryableQ[tragerFail[\"Decline\", \"r\", <||>]]");
    BR_TRUE("tragerRetryableQ[tragerFail[\"Unimplemented\", \"r\", <||>]]");
    BR_TRUE("tragerRetryableQ[tragerFail[\"Incomplete\", \"r\", <||>]]");
    BR_FALSE("tragerRetryableQ[tragerFail[\"NonElementary\", \"r\", <||>]]");
    BR_FALSE("tragerRetryableQ[tragerFail[\"Internal\", \"r\", <||>]]");
    BR_FALSE("tragerRetryableQ[x^2]");
    BR_FALSE("tragerRetryableQ[{\"failed\", \"r\"}]");
}

static void test_head_classes(void) {
    /* the three head classes of the front end partition brUnsupportedHeads */
    BR_TRUE("MatchQ[Sin[x], brElementaryUnimplementedHeads[][___]] && MatchQ[ArcSinh[x], brElementaryUnimplementedHeads[][___]]");
    BR_FALSE("MatchQ[Erf[x], brElementaryUnimplementedHeads[][___]]");
    BR_TRUE("MatchQ[Erf[x], brNonElementaryInputHeads[][___]] && MatchQ[Abs[x], brNonElementaryInputHeads[][___]]");
    BR_FALSE("MatchQ[Log[x], brNonElementaryInputHeads[][___]]");
    BR_TRUE("MatchQ[RootSum[#^3 - x &, Log], brAlgebraicGeneralHeads[][___]]");
    BR_FALSE("MatchQ[Sqrt[x], brAlgebraicGeneralHeads[][___]]");
    BR_TRUE("MatchQ[Cos[x], brUnsupportedHeads[][___]] && MatchQ[Gamma[x], brUnsupportedHeads[][___]] && MatchQ[Root[#^3 - x &, 1], brUnsupportedHeads[][___]]");
    BR_FALSE("MatchQ[Power[E, x], brUnsupportedHeads[][___]]");
}

static void test_kummer_cyclic(void) {
    /* one simple radical in disguise */
    BR_TRUE("brKummerCyclicQ[{{x^3, 1/2}, {x, 1/2}}, {x}]");
    BR_TRUE("brKummerCyclicQ[{{x, 1/2}, {x, 1/3}}, {x}]");                     /* Z/6 */
    BR_TRUE("brKummerCyclicQ[{{x, 1/2}, {x + 1, 1/3}}, {x}]");                 /* Z/2 x Z/3 = Z/6 */
    BR_TRUE("brKummerCyclicQ[{{x^2 (x + 1), 1/2}, {x + 1, 1/2}}, {x}]");
    BR_TRUE("brKummerCyclicQ[{{x (x + 1), 1/2}, {x^2 (x + 1)^2, 1/4}}, {x}]");
    BR_TRUE("brKummerCyclicQ[{{2 x, 1/2}, {x, 1/2}}, {x}]");                   /* constants: the constant field */
    BR_TRUE("brKummerCyclicQ[{{1/x, 1/2}, {x, 1/2}}, {x}]");                   /* a reciprocal radicand */
    BR_TRUE("brKummerCyclicQ[{{-x, 1/2}, {x, 1/2}}, {x}]");                    /* associates */
    /* genuine composita: Z/2 x Z/2, Z/2 x Z/4, Z/3 x Z/3 */
    BR_FALSE("brKummerCyclicQ[{{x, 1/2}, {x + 1, 1/2}}, {x}]");
    BR_FALSE("brKummerCyclicQ[{{x, 1/2}, {x + 1, 1/4}}, {x}]");
    BR_FALSE("brKummerCyclicQ[{{x, 1/3}, {x + 1, 1/3}}, {x}]");
    BR_FALSE("brKummerCyclicQ[{{t, 1/2}, {x, 1/2}}, {x, t}]");
    BR_FALSE("brKummerCyclicQ[{{x (x + 1), 1/2}, {x, 1/2}}, {x}]");
    /* property: the order of the group generated by x^(1/a), (x+1)^(1/b) is a b,
       its exponent lcm(a, b) -- cyclic exactly when gcd(a, b) = 1 */
    BR_TRUE("And @@ Flatten[Table[brKummerCyclicQ[{{x, 1/a}, {x + 1, 1/b}}, {x}] === (GCD[a, b] == 1),"
            " {a, 2, 6}, {b, 2, 6}]]");
}

static void test_scope(void) {
    BR_EQ("BronsteinScope[Sqrt[x + Log[x]], x]", "\"InScope\"");
    BR_EQ("BronsteinScope[Sqrt[Log[x]] E^x, x]", "\"InScope\"");
    BR_EQ("BronsteinScope[Log[x] E^x, x]", "\"NotApplicable\"");               /* no radical */
    BR_EQ("BronsteinScope[Erf[x] Sqrt[x], x]", "\"NotApplicable\"");           /* non-elementary input */
    BR_EQ("BronsteinScope[1.5 Sqrt[x], x]", "\"NotApplicable\"");
    BR_EQ("BronsteinScope[Sqrt[Log[x] + Sqrt[Log[x]]], x]", "{\"implementation incomplete\", \"nested radicals\"}");
    BR_EQ("BronsteinScope[Sqrt[x] + Sqrt[x + 1], x]",
          "{\"implementation incomplete\", \"several radicals generating a non-cyclic Kummer extension (not one simple radical)\"}");
    BR_EQ("BronsteinScope[Root[#^5 - # - x &, 1], x]",
          "{\"implementation incomplete\", \"a general algebraic function (Root/RootSum) in the integrand\"}");
    BR_EQ("BronsteinScope[Sin[x] Sqrt[x], x]", "\"InScope\"");                     /* trig front end (v0.6554) */
    BR_EQ("First[BronsteinScope[Sqrt[2] Sqrt[x] Log[x], x]]", "\"implementation incomplete\"");   /* number-field constant (4.3) */
}

static void test_specialization_growth(void) {
    /* round 0 keeps the historical points; later rounds grow, and never cycle */
    BR_EQ("brSpecializationPoint[{x}, 1]", "{x -> 64/5}");
    BR_TRUE("Max[Abs[Numerator[Last /@ Flatten[Table[brSpecializationPoint[{x, t}, k], {k, 1, 12}]]]]] < 100");
    BR_TRUE("Max[Abs[Numerator[Last /@ Flatten[Table[brSpecializationPoint[{x, t}, k], {k, 85, 96}]]]]] > 100");
    BR_TRUE("Length[DeleteDuplicates[Table[brSpecializationPoint[{x}, k], {k, 1, 96}]]] > 60");
    BR_EQ("brOption[\"SpecializationRounds\"]", "8");
}

static void test_incomplete_message(void) {
    /* Method -> "Bronstein": out of scope, and in scope but unimplemented */
    BR_EQ("Check[Integrate[Sqrt[Log[x] + Sqrt[Log[x]]], x, Method -> \"Bronstein\"]; \"ok\", \"msg\"]", "\"msg\"");
    BR_EQ("Check[Integrate[Sqrt[Log[x] + Sqrt[Log[x]]], x, Method -> \"Bronstein\"]; \"ok\", \"msg\", Integrate::incomplete]", "\"msg\"");
    BR_EQ("Check[Integrate[Sqrt[2] Sqrt[Log[x]] Log[x + 1], x, Method -> \"Bronstein\"]; \"ok\", \"msg\", Integrate::incomplete]", "\"msg\"");
    BR_EQ("Check[Quiet[Integrate[Sqrt[Log[x] + Sqrt[Log[x]]], x, Method -> \"Bronstein\"]]; \"ok\", \"msg\"]", "\"ok\"");
    /* Method -> "Trager": nested radicals are outside its class too */
    BR_EQ("Check[Integrate[Sqrt[x + Sqrt[x + 1]]/(x^2 + 3), x, Method -> \"Trager\"]; \"ok\", \"msg\", Integrate::incomplete]", "\"msg\"");
    /* the Automatic cascade reports it when nothing answered and nothing was
       proved; a certificate outranks it (Sqrt[Log[x] + Sqrt[Log[x]]] is proved
       non-elementary by ParallelMixedTower through x = E^u, so it is never silent) */
    BR_EQ("Check[Integrate[Sqrt[Log[x] + Sqrt[Log[x]]], x]; \"ok\", \"msg\"]", "\"msg\"");
    BR_EQ("Check[Integrate[Root[#^5 - # - x &, 1], x]; \"ok\", \"msg\", Integrate::incomplete]", "\"msg\"");
    BR_EQ("Head[Quiet[Integrate[Sqrt[Log[x] + Sqrt[Log[x]]], x]]]", "Integrate");
    /* silent: an answer (even through a nested radical), a certificate, a
       non-elementary input, an integrand with no radical, a definite integral */
    BR_EQ("Check[Integrate[Sqrt[x + Sqrt[x]]/x^2, x]; \"ok\", \"msg\", Integrate::incomplete]", "\"ok\"");
    BR_EQ("Check[Quiet[Integrate[Sqrt[Log[x]], x, Method -> \"Bronstein\"], Integrate::nonelem]; \"ok\", \"msg\"]", "\"ok\"");
    BR_EQ("Check[Integrate[Erf[x] Sqrt[Log[x]], x, Method -> \"Bronstein\"]; \"ok\", \"msg\"]", "\"ok\"");
    BR_EQ("Check[Integrate[(x + 1)/((x Log[x] + x^2) Sqrt[x + Log[x]]), x]; \"ok\", \"msg\"]", "\"ok\"");
    BR_EQ("Check[Integrate[Sqrt[x + Sqrt[x]], {x, 0, 1}]; \"ok\", \"msg\", Integrate::incomplete]", "\"ok\"");
}

static void test_soundness_phase0(void) {
    /* Cos[E^x]: the exponent I E^x reached the base-field Risch DE in surface
       form, which could not even form its equation; its NULL was a certificate
       by accident.  Now decided through the tower Risch DE, certified. */
    BR_EQ("Risch`ElementaryIntegralQ[Cos[E^x], x]", "False");
    BR_EQ("Risch`ElementaryIntegralQ[E^x Cos[E^x], x]", "True");
    BR_EQ("Risch`ElementaryIntegralQ[E^(x^2), x]", "False");
    BR_EQ("Risch`ElementaryIntegralQ[2 x E^(x^2), x]", "True");
    /* the structure theorems are tri-state ($Failed is not a proof) */
    BR_EQ("Risch`LogReducible[x + 1, x, {{t1, \"Foo\", 1/x}}]", "$Failed");
    BR_EQ("Risch`LogReducible[x + 1, x, {{t1, \"Log\", 1/x}}]", "False");
    /* the tower front end never reads $Failed as "a new monomial" */
    BR_EQ("Head[brCatch[brTower[Sqrt[Log[x] + Log[x + 1]], x]]]", "Association");
}

