(* tests/lean_golden/corpus.m -- the golden corpus of Certify calls.       *)
(*                                                                          *)
(* Each item is one complete call that runs no Lean process: "Verify" ->   *)
(* False, Engine -> "Mathilda", a call refused before any Lean run, a      *)
(* LeanVerify source refused unrun, or a Lean`Internal`Oracle query.  The  *)
(* items run in this order in one session (surd serial numbers depend on   *)
(* the order, deterministically).  dump.m records, per item, the messages  *)
(* issued, the result's head and every property of each ProofObject except *)
(* "Timing"; golden.txt is that record, made on the code before the        *)
(* prover-backend refactor, so a later change to any generated statement,  *)
(* proof, source, certificate, trusted step or message shows up as a diff. *)
(*                                                                          *)
(* Sources: every Certify input of examples/lean/showcase.m, the generator *)
(* lists of tests/scripts/lean_leakcheck.sh, the Certify / ProofObject     *)
(* calls of tests/test_lean_certify.c and the generation-level calls of    *)
(* test_lean_verify.c / test_lean_mathlib.c, plus one item per generator   *)
(* branch and per refusal message.  An item that needs state (a symbol     *)
(* with a value, SetOptions) sets it up and clears it itself.  Tier 1       *)
(* generation names "LeanProject" -> "/nonexistent" explicitly, and dump.m *)
(* runs the corpus with $LeanProject = None, so the record does not depend *)
(* on MATHILDA_LEAN_PROJECT.                                                *)
