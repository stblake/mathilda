/* GMP oracle for head h at x = n/d (d > 0). Round is half to even. */
static void oracle(int h, const mpz_t n, const mpz_t d, mpq_t out) {
    mpz_t q, t, d2;
    mpz_inits(q, t, d2, NULL);
    switch (h) {
        case 0: mpz_fdiv_q(q, n, d); mpq_set_z(out, q); break;
        case 1: mpz_cdiv_q(q, n, d); mpq_set_z(out, q); break;
        case 2:
            /* floor((2n + d) / 2d) is round-half-up; on an exact tie with an
             * odd result step down to the even neighbour. */
            mpz_mul_2exp(t, n, 1); mpz_add(t, t, d);
            mpz_mul_2exp(d2, d, 1);
            mpz_fdiv_q(q, t, d2);
            if (mpz_divisible_p(t, d2) && mpz_odd_p(q)) mpz_sub_ui(q, q, 1);
            mpq_set_z(out, q);
            break;
        case 3: mpz_tdiv_q(q, n, d); mpq_set_z(out, q); break;
        default:
            mpz_tdiv_r(t, n, d);
            mpq_set_num(out, t); mpq_set_den(out, d); mpq_canonicalize(out);
            break;
    }
    mpz_clears(q, t, d2, NULL);
}

/* Evaluate head[Rational[n, d]] and compare it with the oracle. */
static void check_one(int h, int64_t n, int64_t d) {
    char in[160];
    snprintf(in, sizeof in, "%s[Rational[%" PRId64 ", %" PRId64 "]]", RAT_HEADS[h], n, d);
    Expr* e = parse_expression(in);
    Expr* r = evaluate(e);
    mpz_t zn, zd; mpq_t want, got;
    mpz_init_set_si(zn, 0); mpz_init(zd);
    /* via strings: int64 -> mpz without assuming long is 64 bits */
    char buf[32];
    snprintf(buf, sizeof buf, "%" PRId64, n); mpz_set_str(zn, buf, 10);
    snprintf(buf, sizeof buf, "%" PRId64, d); mpz_set_str(zd, buf, 10);
    mpq_inits(want, got, NULL);
    oracle(h, zn, zd, want);
    bool ok = result_to_mpq(r, got);
    if (!ok || !mpq_equal(want, got)) {
        char* s = expr_to_string_fullform(r);
        char* w = mpq_get_str(NULL, 10, want);
        ASSERT_MSG(false, "%s: expected %s, got %s", in, w, s);
        free(s); free(w);
    }
    /* An integer-valued head must return an Integer, never a Rational. */
    if (h != 4) ASSERT_MSG(expr_is_integer_like(r), "%s: result is not an integer", in);
    mpq_clears(want, got, NULL);
    mpz_clears(zn, zd, NULL);
    expr_free(e);
    expr_free(r);
}

/* Seeded sweep over every magnitude band of n and d, plus exact Round ties
 * (n = (2m + 1) d / 2 for even d) and the INT64_MIN numerator. */
static void test_int64_rational_gmp_oracle(void) {
    int checked = 0;
    for (int it = 0; it < 6000; it++) {
        int nb = (int)(rng_next() % 65);          /* 0..63 bits, 64 = INT64_MIN */
        int db = 1 + (int)(rng_next() % 63);      /* 1..63 bits */
        int64_t n = rng_int64(nb);
        int64_t d = rng_int64(db);
        if (d < 0) d = d == INT64_MIN ? INT64_MAX : -d;
        if (d == 0) d = 1;
        for (int h = 0; h < 5; h++) { check_one(h, n, d); checked++; }
    }
    /* Round ties at every scale: (2m + 1)/2 * d with d even. */
    for (int it = 0; it < 2000; it++) {
        int db = 2 + (int)(rng_next() % 30);
        int64_t d = (int64_t)((rng_next() >> (64 - db)) | 2) & ~INT64_C(1);   /* even, >= 2 */
        int64_t half = d / 2;
        int64_t mmax = (INT64_MAX - half) / d;     /* keep (2m+1)*half in range */
        int64_t m = (int64_t)(rng_next() % (uint64_t)(mmax + 1));
        int64_t n = m * d + half;                  /* = (2m + 1) * d / 2 */
        if (rng_next() & 1) n = -n;
        check_one(2, n, d);
        check_one(4, n, d);
        checked += 2;
    }
    /* Exhaustive small grid, including every sign and tie. */
    for (int64_t n = -60; n <= 60; n++)
        for (int64_t d = 1; d <= 12; d++)
            for (int h = 0; h < 5; h++) { check_one(h, n, d); checked++; }
    ASSERT(checked == 6000 * 5 + 2000 * 2 + 121 * 12 * 5);
}

/* The int64 branch and the mpz branch must agree: shifting x by an integer
 * K = 2^70 forces the bignum path, and every head commutes with integer
 * shifts (FractionalPart is shift-invariant only for x and x + K of the same
 * sign, which holds for K = 2^70 > |x|... except for the sign flip, so
 * compare it on positive x only). */
static void test_int64_rational_cross_path(void) {
    eval_check_fullform(
        "SeedRandom[515]; xs = Join[Table[RandomInteger[{-2^63 + 1, 2^63 - 1}]/"
        "RandomInteger[{2, 2^63 - 1}], {400}], Table[RandomInteger[{-2^63 + 1, 2^63 - 1}]/"
        "RandomInteger[{2, 2^20}], {400}], Table[(2 RandomInteger[{-2^40, 2^40}] + 1)/2, {100}]]; "
        "k = 2^70; "
        "{And @@ Table[Floor[x] == Floor[x + k] - k, {x, xs}], "
        " And @@ Table[Ceiling[x] == Ceiling[x + k] - k, {x, xs}], "
        " And @@ Table[Round[x] == Round[x + k] - k, {x, xs}], "
        " And @@ Table[IntegerPart[x] == If[x >= 0, IntegerPart[x + k] - k, IntegerPart[x - k] + k], {x, xs}], "
        " And @@ Table[FractionalPart[x] == If[x >= 0, FractionalPart[x + k], FractionalPart[x - k]], {x, xs}]}",
        "List[True, True, True, True, True]");
    /* Identities that tie the five heads together, on the int64 path. */
    eval_check_fullform(
        "SeedRandom[516]; xs = Table[RandomInteger[{-2^63 + 1, 2^63 - 1}]/"
        "RandomInteger[{2, 2^63 - 1}], {500}]; "
        "{And @@ Table[Ceiling[x] == -Floor[-x], {x, xs}], "
        " And @@ Table[Floor[x] <= x < Floor[x] + 1, {x, xs}], "
        " And @@ Table[Ceiling[x] - 1 < x <= Ceiling[x], {x, xs}], "
        " And @@ Table[Abs[x - Round[x]] <= 1/2, {x, xs}], "
        " And @@ Table[IntegerPart[x] + FractionalPart[x] == x, {x, xs}], "
        " And @@ Table[Round[-x] == -Round[x], {x, xs}]}",
        "List[True, True, True, True, True, True]");
}

