/* The value of an Integer / BigInt / Rational result as an mpq. */
static bool result_to_mpq(const Expr* r, mpq_t out) {
    if (expr_is_integer_like(r)) {
        mpz_t z; expr_to_mpz(r, z);
        mpq_set_z(out, z); mpz_clear(z);
        return true;
    }
    if (r->type == EXPR_FUNCTION && r->data.function.head->type == EXPR_SYMBOL
        && r->data.function.head->data.symbol.name == SYM_Rational
        && r->data.function.arg_count == 2
        && expr_is_integer_like(r->data.function.args[0])
        && expr_is_integer_like(r->data.function.args[1])) {
        mpz_t a, b;
        expr_to_mpz(r->data.function.args[0], a);
        expr_to_mpz(r->data.function.args[1], b);
        mpq_set_num(out, a); mpq_set_den(out, b); mpq_canonicalize(out);
        mpz_clears(a, b, NULL);
        return true;
    }
    return false;
}

static uint64_t rng_state = UINT64_C(0x9E3779B97F4A7C15);
static uint64_t rng_next(void) {         /* xorshift64*: deterministic */
    rng_state ^= rng_state >> 12;
    rng_state ^= rng_state << 25;
    rng_state ^= rng_state >> 27;
    return rng_state * UINT64_C(2685821657736338717);
}

/* A random int64 of `bits` magnitude bits (0..63) and random sign; bits ==
 * 64 stands for INT64_MIN itself. */
static int64_t rng_int64(int bits) {
    if (bits >= 64) return INT64_MIN;
    uint64_t m = bits == 0 ? 0 : (rng_next() >> (64 - bits));
    int64_t v = (int64_t)m;
    return (rng_next() & 1) ? -v : v;
}

