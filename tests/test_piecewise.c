/* A structural Rational with a negative denominator (one a builder made and
 * nothing canonicalised) must not take the int64 path, whose remainder sign
 * logic assumes d > 0; the mpz branch normalises it. */
extern Expr* builtin_floor(Expr* res);
extern Expr* builtin_ceiling(Expr* res);
extern Expr* builtin_round(Expr* res);
extern Expr* builtin_fractionalpart(Expr* res);
static void test_int64_rational_structural_negative_den(void) {
    Expr* (*fns[4])(Expr*) = { builtin_floor, builtin_ceiling, builtin_round, builtin_fractionalpart };
    const char* want[4] = { "-4", "-3", "-4", "Rational[-1, 2]" };  /* Rational[7, -2] = -7/2 */
    for (int i = 0; i < 4; i++) {
        Expr* ra[2] = { expr_new_integer(7), expr_new_integer(-2) };
        Expr* rat = expr_new_function(expr_new_symbol(SYM_Rational), ra, 2);
        Expr* ca[1] = { rat };
        Expr* call = expr_new_function(expr_new_symbol("Floor"), ca, 1);
        Expr* r = fns[i](call);
        ASSERT(r != NULL);
        char* s = expr_to_string_fullform(r);
        ASSERT_MSG(strcmp(s, want[i]) == 0, "structural Rational[7, -2] op %d: expected %s, got %s", i, want[i], s);
        free(s);
        expr_free(r);
        expr_free(call);    /* the builtin succeeded, so the caller frees res */
    }
}

