#!/usr/bin/env python3
"""benchmarks/87-diophantine-integers/validate.py -- the held-out gate.

Runs Mathilda COLD on every case in heldout.py and cross-checks the answer
against an independent Python brute-force oracle over the same box.  The point
is NOT a leaderboard; it is a tripwire for the one class the co-designed
benchmark (cases.py) cannot catch: a *silent wrong answer* -- a `{}` (or a
finite set) the oracle contradicts.

For each case Mathilda emits its status (uneval / empty / finite / param) and,
for a concrete answer, the integer solution tuples lying inside the box (for a
parametric family it substitutes C[1] -> 0..K and filters).  The verdict:

  OK       -- the answer agrees with the oracle (for the case's `kind`)
  DECLINE  -- Mathilda left it unevaluated where a decline is acceptable
              (kind == 'decline_ok'): honest, not a failure -- reported as a gap
  WRONG    -- a disagreement the oracle proves: an empty/finite/param answer that
              misses or invents a solution.  ANY wrong -> nonzero exit.

Usage (from this folder, with the benchmark venv on PATH or plain python3):

    python3 validate.py            # writes HELDOUT_REPORT.md, exits 1 on any WRONG

The Mathilda binary is ../../Mathilda; override with MATHILDA_BIN.
"""

import ast
import os
import subprocess
import sys
from itertools import product
from time import perf_counter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from heldout import CASES                                   # noqa: E402

REPO_ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
MATHILDA_BIN = os.environ.get("MATHILDA_BIN", os.path.join(REPO_ROOT, "Mathilda"))
MATHILDA_TIMEOUT_S = float(os.environ.get("MATHILDA_TIMEOUT_S", "240"))
PARAM_KMAX = int(os.environ.get("PARAM_KMAX", "60"))
# Per-axis range for a MULTI-parameter family (e.g. the ternary-quadratic
# C[1],C[2],C[3] union); kept modest because it grids in 3 dimensions.
MPARAM_KMAX = int(os.environ.get("MPARAM_KMAX", "16"))
GRID_LIMIT = 4_000_000

# ----------------------------------------------------------------------------
#  Oracle: the ground-truth solution set inside a case's box.
# ----------------------------------------------------------------------------

def oracle_set(case):
    if "oracle" in case:
        return sorted(tuple(t) for t in case["oracle"]())
    vs = case["vars"]
    ranges = [range(case["box"][v][0], case["box"][v][1] + 1) for v in vs]
    grid = 1
    for r in ranges:
        grid *= len(r)
    if grid > GRID_LIMIT:
        raise SystemExit(
            f"case {case['label']}: box grid {grid} exceeds {GRID_LIMIT}; "
            f"give it an explicit `oracle`")
    sat = case["sat"]
    out = []
    for combo in product(*ranges):
        d = dict(zip(vs, combo))
        if sat(d):
            out.append(tuple(combo))
    return sorted(out)

# ----------------------------------------------------------------------------
#  Mathilda side: one self-contained block per case, emitting STATUS + SOLS.
# ----------------------------------------------------------------------------

def _inbox_predicate(case):
    """A Mathilda pure-function body testing a tuple pt against the box."""
    terms = []
    for i, v in enumerate(case["vars"], start=1):
        lo, hi = case["box"][v]
        terms.append(f"{lo} <= pt[[{i}]] <= {hi}")
    return " && ".join(terms)


def build_script():
    L = ["(* generated by validate.py -- do not edit; edit heldout.py *)"]
    for c in CASES:
        lab = c["label"]
        vlist = "{" + ", ".join(c["vars"]) + "}"
        inbox = _inbox_predicate(c)
        L += [
            f'Module[{{sol, status, tuples, sols, inbox}},',
            f'  inbox = Function[pt, {inbox}];',
            f'  sol = {c["math"]};',
            f'  status = Which[Head[sol] === Solve, "uneval", sol === {{}}, "empty",',
            f'    FreeQ[sol, C] && FreeQ[sol, ConditionalExpression], "finite", True, "param"];',
            f'  Print["STATUS\\t{lab}\\t", status];',
            f'  If[status === "finite",',
            f'    tuples = ({vlist} /. sol);',
            f'    sols = Select[tuples, VectorQ[#, IntegerQ] && inbox[#] &];',
            f'    Print["SOLS\\t{lab}\\t", InputForm[Sort[DeleteDuplicates[sols]]]]];',
            f'  If[status === "param",',
            f'    (* C[1] ranges over ALL integers for a linear-lattice family; a Pell'
            f' family carries ConditionalExpression[_, C[1] >= 0] so its negative-kk'
            f' substitutions become non-integer and drop out of the VectorQ filter.'
            f' A multi-parameter family (e.g. the ternary-quadratic C[1],C[2],C[3])'
            f' is enumerated over a 3-D grid with a modest per-axis range. *)',
            f'    tuples = If[FreeQ[sol, C[2]] && FreeQ[sol, C[3]],',
            f'      Flatten[Table[Simplify[({vlist} /. sol) /. C[1] -> kk],'
            f' {{kk, -{PARAM_KMAX}, {PARAM_KMAX}}}], 1],',
            f'      Flatten[Table[({vlist} /. sol) /. {{C[1] -> k1, C[2] -> k2, C[3] -> k3}},'
            f' {{k1, -{MPARAM_KMAX}, {MPARAM_KMAX}}}, {{k2, -{MPARAM_KMAX}, {MPARAM_KMAX}}},'
            f' {{k3, -{MPARAM_KMAX}, {MPARAM_KMAX}}}], 3]];',
            f'    sols = Select[tuples, VectorQ[#, IntegerQ] && inbox[#] &];',
            f'    Print["SOLS\\t{lab}\\t", InputForm[Sort[DeleteDuplicates[sols]]]]];',
            f'];',
        ]
    return "\n".join(L) + "\n"


def parse_tuples(s):
    """Parse a Mathilda InputForm list-of-lists like {{3, 1}, {5, 3}} or {}."""
    s = s.strip()
    if s in ("{}", "{ }"):
        return []
    py = s.replace("{", "[").replace("}", "]")
    try:
        val = ast.literal_eval(py)
    except (ValueError, SyntaxError):
        return None
    return sorted(tuple(t) for t in val)


def run_mathilda():
    path = os.path.join(HERE, "heldout.m")
    with open(path, "w") as f:
        f.write(build_script())
    if not os.path.exists(MATHILDA_BIN):
        raise SystemExit(f"Mathilda binary not found at {MATHILDA_BIN} (set MATHILDA_BIN)")
    t = perf_counter()
    out = subprocess.run([MATHILDA_BIN, "-file", path],
                         capture_output=True, text=True, timeout=MATHILDA_TIMEOUT_S)
    status, sols = {}, {}
    for line in out.stdout.splitlines():
        parts = line.split("\t")
        if len(parts) >= 3 and parts[0] == "STATUS":
            status[parts[1]] = parts[2].strip()
        elif len(parts) >= 3 and parts[0] == "SOLS":
            sols[parts[1]] = parse_tuples(parts[2])
    return status, sols, perf_counter() - t

# ----------------------------------------------------------------------------
#  Verdict per case.
# ----------------------------------------------------------------------------

def verdict(case, status, sols, truth):
    """Return (verdict, detail).  verdict in OK / DECLINE / WRONG."""
    kind = case["kind"]
    if status is None:
        return "WRONG", "no STATUS emitted (crash / parse failure)"

    if status == "uneval":
        if kind == "decline_ok":
            return "DECLINE", f"unevaluated; oracle has {len(truth)} in box"
        # An unbounded family or empty proof we expected to answer -> gap, not a
        # silent wrong answer.  Only flag WRONG when Mathilda asserts something.
        return "DECLINE", f"unevaluated (expected {kind})"

    if status == "empty":
        if truth:
            return "WRONG", f"returned {{}} but oracle finds {len(truth)}: {truth[:4]}"
        return "OK", "empty, oracle agrees"

    # status in finite / param -> Mathilda gave concrete tuples.
    got = sols
    if got is None:
        return "WRONG", "could not parse emitted solutions"
    got = sorted(set(got))
    if got == truth:
        return "OK", f"{len(got)} solutions match oracle"
    missing = [t for t in truth if t not in got]
    extra = [t for t in got if t not in truth]
    return "WRONG", f"missing={missing[:4]} extra={extra[:4]}"

# ----------------------------------------------------------------------------

def main():
    print("Building oracle sets ...")
    truths = {c["label"]: oracle_set(c) for c in CASES}
    print(f"Running Mathilda cold on {len(CASES)} held-out cases ...")
    status, sols, wall = run_mathilda()
    print(f"   (Mathilda wall time: {wall:.1f}s)")

    rows = []
    for c in CASES:
        lab = c["label"]
        v, detail = verdict(c, status.get(lab), sols.get(lab), truths[lab])
        rows.append((lab, c["kind"], status.get(lab, "MISSING"), v, len(truths[lab]), detail))

    n_wrong = sum(1 for r in rows if r[3] == "WRONG")
    n_decline = sum(1 for r in rows if r[3] == "DECLINE")
    n_ok = sum(1 for r in rows if r[3] == "OK")

    write_report(rows, n_ok, n_decline, n_wrong)

    print(f"\n  OK={n_ok}  DECLINE={n_decline}  WRONG={n_wrong}  (of {len(rows)})")
    for lab, kind, st, v, ntruth, detail in rows:
        mark = {"OK": "  ok ", "DECLINE": " -- ", "WRONG": "WRONG"}[v]
        print(f"  [{mark}] {lab:<28} {st:<7} {detail}")
    if n_wrong:
        print(f"\n!! {n_wrong} SILENT WRONG ANSWER(S) -- see HELDOUT_REPORT.md")
        return 1
    print("\nNo silent wrong answers.")
    return 0


def write_report(rows, n_ok, n_decline, n_wrong):
    L = ["# Held-out Diophantine validation (silent-wrong-answer gate)\n"]
    L.append("Generated by `validate.py` from `heldout.py`. Equations here are drawn")
    L.append("from standard references and are **not** in `cases.py`; Mathilda is run")
    L.append("cold and every answer is cross-checked against an independent brute-force")
    L.append("oracle over the same box.\n")
    L.append(f"**OK {n_ok} &nbsp; DECLINE {n_decline} &nbsp; WRONG {n_wrong}** of {len(rows)}.")
    L.append("")
    L.append("- **OK** — the concrete answer (or proven `{}`) matches the oracle.")
    L.append("- **DECLINE** — left unevaluated where that is acceptable (honest gap).")
    L.append("- **WRONG** — a `{}`/finite/parametric answer the oracle contradicts. Any")
    L.append("  WRONG fails the gate (nonzero exit).")
    L.append("")
    L.append("| Case | kind | status | verdict | #oracle | detail |")
    L.append("|---|---|---|:--:|--:|---|")
    for lab, kind, st, v, ntruth, detail in rows:
        L.append(f"| `{lab}` | {kind} | {st} | {v} | {ntruth} | {detail} |")
    L.append("")
    with open(os.path.join(HERE, "HELDOUT_REPORT.md"), "w") as f:
        f.write("\n".join(L))


if __name__ == "__main__":
    sys.exit(main())
