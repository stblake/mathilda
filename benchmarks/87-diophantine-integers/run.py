#!/usr/bin/env python3
"""benchmarks/87-diophantine-integers/run.py

Head-to-head: Mathilda's Solve[..., Integers] vs sympy on the well-known
Diophantine families.  Generates the Mathilda script from cases.py, runs it,
runs the sympy `diophantine` column and a same-box Python-search column, joins
everything by label, and writes REPORT.md + results.json.

Run from this folder with the benchmark venv:

    ../.venv/bin/python run.py

The venv only needs sympy (`../.venv/bin/pip install sympy`).  The Mathilda
binary is expected at the repo root (../../Mathilda); override with
MATHILDA_BIN.
"""

import json
import os
import signal
import subprocess
import sys
from time import perf_counter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from cases import CASES                                    # noqa: E402

REPO_ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
MATHILDA_BIN = os.environ.get("MATHILDA_BIN", os.path.join(REPO_ROOT, "Mathilda"))
BRUTE_BUDGET_S = float(os.environ.get("BRUTE_BUDGET_S", "25"))
MATHILDA_TIMEOUT_S = float(os.environ.get("MATHILDA_TIMEOUT_S", "180"))

# ----------------------------------------------------------------------------
#  Mathilda side: emit a script, run it once, parse BENCH/CHECK lines.
# ----------------------------------------------------------------------------

def build_m_script():
    lines = [
        "(* generated by run.py -- do not edit by hand; edit cases.py *)",
        "SetAttributes[bench, HoldAll];",
        "bench[label_, reps_, body_] := Module[{sol, n, times},",
        "  sol = body;",
        "  n = If[Head[sol] === List, Length[sol], -1];",
        "  times = Table[First[AbsoluteTiming[body]], {reps}];",
        "  Print[\"BENCH\\t\", label, \"\\t\", 1000.0*Min[times]];",
        "  Print[\"CHECK\\t\", label, \"\\t\", n];",
        "];",
    ]
    for c in CASES:
        lines.append('bench["%s", %d, %s];' % (c["label"], c["reps"], c["math"]))
    return "\n".join(lines) + "\n"

def run_mathilda():
    script = build_m_script()
    path = os.path.join(HERE, "diophantine.m")
    with open(path, "w") as f:
        f.write(script)
    if not os.path.exists(MATHILDA_BIN):
        print("!! Mathilda binary not found at %s (set MATHILDA_BIN)" % MATHILDA_BIN)
        return {}
    t = perf_counter()
    out = subprocess.run([MATHILDA_BIN, "-file", path],
                         capture_output=True, text=True, timeout=MATHILDA_TIMEOUT_S)
    print("   (Mathilda wall time: %.1fs)" % (perf_counter() - t))
    res = {}
    for line in out.stdout.splitlines():
        parts = line.split("\t")
        if len(parts) == 3 and parts[0] in ("BENCH", "CHECK"):
            tag, label, val = parts
            res.setdefault(label, {})
            res[label]["ms" if tag == "BENCH" else "count"] = float(val)
    return res

# ----------------------------------------------------------------------------
#  Python-search side with a wall-clock budget.
# ----------------------------------------------------------------------------

class _Timeout(Exception):
    pass

def _alarm(_sig, _frm):
    raise _Timeout()

def run_brute(fn, budget):
    signal.signal(signal.SIGALRM, _alarm)
    signal.setitimer(signal.ITIMER_REAL, budget)
    t = perf_counter()
    try:
        n = fn()
        secs = perf_counter() - t
        return ("ok", n, secs)
    except _Timeout:
        return ("timeout", None, budget)
    except Exception as ex:                                # noqa: BLE001
        return ("error:" + type(ex).__name__, None, perf_counter() - t)
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)

# ----------------------------------------------------------------------------
#  Orchestrate.
# ----------------------------------------------------------------------------

def main():
    import sympy
    print("Running Mathilda cases ...")
    m = run_mathilda()

    rows = []
    for c in CASES:
        label = c["label"]
        print("  sympy/search: %s" % label)
        s_status, s_count, s_secs = c["sympy"]()
        b_status, b_count, b_secs = run_brute(c["brute"], BRUTE_BUDGET_S)

        mm = m.get(label, {})
        m_ms = mm.get("ms")
        m_count = int(mm["count"]) if "count" in mm else None

        # ground truth: the known count if given, else whatever the search that
        # finished agrees on.
        truth = c["expect"]
        if truth is None and b_status == "ok":
            truth = b_count
        correct = (m_count == truth) if (truth is not None and m_count is not None) else None

        rows.append(dict(
            label=label, family=c["family"], category=c["category"], box=c["box"],
            note=c["note"], expect=c["expect"],
            mathilda_ms=m_ms, mathilda_count=m_count,
            sympy_status=s_status, sympy_count=s_count, sympy_ms=s_secs * 1000.0,
            sympy_caveat=c.get("sympy_caveat"),
            brute_status=b_status, brute_count=b_count, brute_ms=(b_secs * 1000.0 if b_secs is not None else None),
            truth=truth, correct=correct,
        ))

    with open(os.path.join(HERE, "results.json"), "w") as f:
        json.dump(dict(sympy_version=sympy.__version__, rows=rows), f, indent=2)

    write_report(rows, sympy.__version__)
    print("\nWrote REPORT.md and results.json")

# ----------------------------------------------------------------------------
#  Report.
# ----------------------------------------------------------------------------

def _ms(x):
    if x is None:
        return "--"
    if x < 1:
        return "%.3f" % x
    if x < 1000:
        return "%.1f" % x
    return "%.0f" % x

def _sympy_cell(r):
    st = r["sympy_status"]
    cav = r.get("sympy_caveat")
    if st == "finite":
        if cav:
            return "n=%d raw* (%s ms)" % (r["sympy_count"], _ms(r["sympy_ms"]))
        return "solved n=%d (%s ms)" % (r["sympy_count"], _ms(r["sympy_ms"]))
    if st == "parametric":
        return "parametric only (%s ms)" % _ms(r["sympy_ms"])
    if st == "empty":
        return "empty=0 (%s ms)" % _ms(r["sympy_ms"])
    if st == "unsupported":
        return "**NotImplemented**" + ("*" if cav else "")
    return st

def _brute_cell(r):
    st = r["brute_status"]
    if st == "ok":
        return "n=%s (%s ms)" % (r["brute_count"], _ms(r["brute_ms"]))
    if st == "timeout":
        return "TIMEOUT (>%s ms)" % _ms(r["brute_ms"])
    return st

def _correct_cell(r):
    if r["correct"] is None:
        return "--"
    return "yes" if r["correct"] else "**NO**"

def write_report(rows, sympy_version):
    from datetime import date
    L = []
    L.append("# Diophantine solving: Mathilda `Solve[..., Integers]` vs sympy\n")
    L.append("Experiment 87. Generated by `run.py` (edit `cases.py`, not this file).\n")
    L.append("- Mathilda: `Solve[eqns && constraints, vars, Integers]` (integer pre-pass, `src/solveint.c`).")
    L.append("- sympy %s: `sympy.solvers.diophantine.diophantine`, plus a same-box Python search "
             "as the fallback a sympy user writes when `diophantine` cannot answer." % sympy_version)
    L.append("- Timing: Mathilda = min of the case's reps via `AbsoluteTiming` (in-process, "
             "excludes binary start-up); sympy/Python = one `perf_counter` run. "
             "Python search budget %.0fs." % BRUTE_BUDGET_S)
    L.append("- Run date: %s\n" % date.today().isoformat())

    # headline numbers
    solved = sum(1 for r in rows if r["mathilda_count"] is not None)
    correct = sum(1 for r in rows if r["correct"])
    dio_comparable = sum(1 for r in rows if r["sympy_status"] == "finite" and not r.get("sympy_caveat"))
    dio_partial = sum(1 for r in rows if r["sympy_status"] == "finite" and r.get("sympy_caveat"))
    dio_param = sum(1 for r in rows if r["sympy_status"] == "parametric")
    dio_unsup = sum(1 for r in rows if r["sympy_status"] == "unsupported")
    dio_empty = sum(1 for r in rows if r["sympy_status"] == "empty")
    L.append("## Headline\n")
    L.append("- **Mathilda** returns the finite, constraint-satisfying set for **%d of %d** cases; "
             "**%d of %d** match the known count." % (solved, len(rows), correct, len(rows)))
    L.append("- **sympy `diophantine`**: **%d** answered directly & comparably (all sum-of-squares), "
             "%d only after manual elimination + box-filtering (*), %d ruled empty via gcd, "
             "%d parametric-only (no bounded answer), **%d NotImplementedError** "
             "(every mixed/cubic/exponential form, and every *system* -- diophantine takes one equation)."
             % (dio_comparable, dio_partial, dio_empty, dio_param, dio_unsup))
    L.append("- `*` = the finite count sympy returns is **not** the answer to the constrained "
             "problem; it still needs hand-elimination and/or filtering (see Notes).")
    L.append("")

    hdr = "| Family | Case | Box | Mathilda | sympy `diophantine` | Python search | count | matches |"
    sep = "|---|---|---|--:|---|---|--:|:--:|"
    for cat, title in (("A", "Category A -- sympy returns a finite set (direct comparison)"),
                       ("B", "Category B -- sympy solves the family but only PARAMETRICALLY"),
                       ("C", "Category C -- sympy has no solver (`NotImplementedError`)")):
        L.append("\n### %s\n" % title)
        L.append(hdr)
        L.append(sep)
        def esc(s):
            return str(s).replace("|", "\\|")
        for r in rows:
            if r["category"] != cat:
                continue
            mcell = ("%s ms" % _ms(r["mathilda_ms"])) if r["mathilda_ms"] is not None else "--"
            L.append("| %s | `%s` | %s | %s | %s | %s | %s | %s |" % (
                esc(r["family"]), r["label"], esc(r["box"]), mcell,
                _sympy_cell(r), _brute_cell(r),
                r["mathilda_count"] if r["mathilda_count"] is not None else "--",
                _correct_cell(r)))

    L.append("\n## Notes\n")
    for r in rows:
        L.append("- **%s** -- %s" % (r["label"], r["note"]))

    L.append("\n## Method\n")
    L.append("`cases.py` is the single source of truth: one row per family with the exact "
             "Mathilda expression, the sympy polynomial, and a Python search over the *same* box. "
             "`run.py` emits `diophantine.m`, runs it once, then runs the sympy and Python columns "
             "in-process and joins by label. Solution **counts** are the invariant compared "
             "(ordering and radical spelling are not); sum-of-squares cases pass `permute=True` so "
             "sympy expands its base representatives to the full signed/ordered set Mathilda enumerates.")
    with open(os.path.join(HERE, "REPORT.md"), "w") as f:
        f.write("\n".join(L) + "\n")

if __name__ == "__main__":
    main()
