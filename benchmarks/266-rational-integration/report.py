#!/usr/bin/env python3.11
"""report.py -- renders REPORT.md for benchmark 266 from results/<label>/*.tsv.

    python3.11 benchmarks/266-rational-integration/report.py --labels before,after

The last label is the current state; the first, when two are given, is the
before-picture for the per-family before/after table.  The reference column is
a timing and size comparison only: every Mathilda verdict comes from Mathilda's
own PossibleZeroQ[D[F, x] - f] (see run.py).
"""
import argparse
import os
import statistics
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
FAMS = ["classical", "bronstein", "sqfree", "nonsqfree", "multiplicity", "rootsum", "rioboo",
        "param_generic", "param_special", "alg_qi", "alg_sqrt", "alg_nested", "alg_root",
        "largecoef", "stress", "czichowski", "logtoreal"]


def load_corpus():
    out = {}
    with open(os.path.join(HERE, "corpus.tsv")) as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            p = line.rstrip("\n").split("\t")
            out[p[0]] = dict(family=p[1], wl=p[2], note=p[4] if len(p) > 4 else "")
    return out


def fnum(s):
    try:
        return float(s)
    except (TypeError, ValueError):
        return None


def load(label):
    d = os.path.join(HERE, "results", label)
    M, W, S = {}, {}, {}
    p = os.path.join(d, "mathilda.tsv")
    if os.path.exists(p):
        for line in open(p):
            r = line.rstrip("\n").split("\t")
            if len(r) < 8:
                continue
            M[(r[0], r[1])] = dict(status=r[2], t=fnum(r[3]), lc=fnum(r[4]), jump=r[5], msgs=r[6], F=r[7])
    p = os.path.join(d, "wolfram.tsv")
    if os.path.exists(p):
        for line in open(p):
            r = line.rstrip("\n").split("\t")
            if len(r) < 5:
                continue
            W[r[0]] = dict(status=r[2], t=fnum(r[3]), lc=fnum(r[4]), F=r[5] if len(r) > 5 else "")
    p = os.path.join(d, "sympy.tsv")
    if os.path.exists(p):
        for line in open(p):
            r = line.rstrip("\n").split("\t")
            if len(r) < 5:
                continue
            S[r[0]] = dict(status=r[2], t=fnum(r[3]), lc=fnum(r[4]), F=r[5] if len(r) > 5 else "")
    return M, W, S


def med(xs):
    xs = [v for v in xs if v is not None]
    return statistics.median(xs) if xs else None


def mx(xs):
    xs = [v for v in xs if v is not None]
    return max(xs) if xs else None


def ft(v):
    if v is None:
        return "-"
    if v < 0.01:
        return f"{v * 1000:.1f}ms"
    if v < 10:
        return f"{v:.3g}s"
    return f"{v:.0f}s"


def fr(v):
    return "-" if v is None else f"{v:.2f}"


def fl(v):
    return "-" if v is None else f"{v:.0f}"


def ok_w(w):
    return w and w["status"] == "OK"


def family_rows(C, M, W, S, method):
    rows = []
    for fam in FAMS:
        ids = [i for i, c in C.items() if c["family"] == fam]
        if not ids:
            continue
        st = defaultdict(int)
        jumps = 0
        tm, tw, ts, lm, lw, ls, rt, rl, rs = [], [], [], [], [], [], [], [], []
        for i in ids:
            m = M.get((i, method))
            if not m:
                st["missing"] += 1
                continue
            st[m["status"]] += 1
            if m["jump"].startswith("JUMP"):
                jumps += 1
            w, s = W.get(i), S.get(i)
            if m["status"] == "PASS":
                tm.append(m["t"]); lm.append(m["lc"])
                if ok_w(w):
                    tw.append(w["t"]); lw.append(w["lc"])
                    if w["t"] and m["t"] is not None:
                        rt.append(m["t"] / max(w["t"], 1e-4))
                    if w["lc"]:
                        rl.append(m["lc"] / w["lc"])
                if s and s["status"] == "OK":
                    ts.append(s["t"]); ls.append(s["lc"])
                    if s["lc"]:
                        rs.append(m["lc"] / s["lc"])
        nw = sum(1 for i in ids if ok_w(W.get(i)))
        ns = sum(1 for i in ids if S.get(i) and S[i]["status"] == "OK")
        rows.append(dict(fam=fam, n=len(ids), st=st, jumps=jumps, tm=tm, tw=tw, ts=ts, lm=lm, lw=lw, ls=ls,
                         rt=rt, rl=rl, rs=rs, nw=nw, ns=ns))
    return rows


def render(labels):
    C = load_corpus()
    cur = labels[-1]
    M, W, S = load(cur)
    L = []
    L.append("# 266 — rational integration: report\n")
    L.append("Generated by `report.py` from `results/" + "`, `results/".join(labels) + "`. "
             "Do not edit by hand; re-run `make bench-integrate-rational` (or `run.py` + `report.py`).\n")
    meta = os.path.join(HERE, "results", cur, "meta.txt")
    if os.path.exists(meta):
        L.append("```\n" + open(meta).read().strip() + "\n```\n")
    L.append("Columns: **M** = Mathilda `Integrate[f, x]` (Automatic); **BR** = `Method -> \"BronsteinRational\"`; "
             "**Ref** = the local reference system (`wolframscript`), timing and size only, never an oracle; "
             "**sympy** = `ratint`. A Mathilda answer counts only when Mathilda's own "
             "`PossibleZeroQ[D[F, x] - f]` is `True` (PASS). Times are the median / max over the "
             "Mathilda-PASS cases; size ratio = LeafCount(Mathilda) / LeafCount(other) on cases both answered. "
             "JUMP = a spurious discontinuity of Re F on [-4, 4] not explained by a pole of f.\n")
    for method in ("Automatic", "BronsteinRational"):
        rows = family_rows(C, M, W, S, method)
        L.append(f"\n## Per family — `{method}` (`{cur}`)\n")
        L.append("| family | n | PASS | FAIL | UNEVAL | TIMEOUT/KILL | JUMP | M median / max | Ref median / max | "
                 "sympy median / max | t ratio M/Ref median / max | size M median / max | size Ref median | "
                 "size ratio M/Ref median / max | size ratio M/sympy median | Ref solved | sympy solved |")
        L.append("|---|" + "---|" * 16)
        tot = defaultdict(int)
        for r in rows:
            st = r["st"]
            to = st["TIMEOUT"] + st["KILLED_WALL"] + st["KILLED_RSS"] + st["MEMOUT"] + st["CRASH"] + st["NOROW"]
            fail = st["FAIL"] + st["VTIMEOUT"]
            for k, v in (("n", r["n"]), ("pass", st["PASS"]), ("fail", fail), ("unev", st["UNEVAL"]), ("to", to),
                         ("jump", r["jumps"]), ("nw", r["nw"]), ("ns", r["ns"])):
                tot[k] += v
            L.append(f"| {r['fam']} | {r['n']} | {st['PASS']} | {fail} | {st['UNEVAL']} | {to} | {r['jumps']} | "
                     f"{ft(med(r['tm']))} / {ft(mx(r['tm']))} | {ft(med(r['tw']))} / {ft(mx(r['tw']))} | "
                     f"{ft(med(r['ts']))} / {ft(mx(r['ts']))} | {fr(med(r['rt']))} / {fr(mx(r['rt']))} | "
                     f"{fl(med(r['lm']))} / {fl(mx(r['lm']))} | {fl(med(r['lw']))} | "
                     f"{fr(med(r['rl']))} / {fr(mx(r['rl']))} | {fr(med(r['rs']))} | {r['nw']} | {r['ns']} |")
        L.append(f"| **total** | {tot['n']} | {tot['pass']} | {tot['fail']} | {tot['unev']} | {tot['to']} | "
                 f"{tot['jump']} | | | | | | | | | {tot['nw']} | {tot['ns']} |")

    if len(labels) > 1:
        Mb, Wb, Sb = load(labels[0])
        L.append(f"\n## Before / after — `Automatic` (`{labels[0]}` → `{cur}`)\n")
        L.append("| family | PASS before → after | non-PASS after | median t before → after | max t before → after | "
                 "median size ratio M/Ref before → after | max size ratio before → after | total LeafCount before → after |")
        L.append("|---|---|---|---|---|---|---|---|")
        rb = {r["fam"]: r for r in family_rows(C, Mb, Wb, Sb, "Automatic")}
        ra = {r["fam"]: r for r in family_rows(C, M, W, S, "Automatic")}
        for fam in FAMS:
            if fam not in ra:
                continue
            a, b = ra[fam], rb.get(fam)
            if not b:
                continue
            # total leafcount over the cases PASS in both runs
            ids = [i for i, c in C.items() if c["family"] == fam]
            both = [i for i in ids if Mb.get((i, "Automatic"), {}).get("status") == "PASS"
                    and M.get((i, "Automatic"), {}).get("status") == "PASS"]
            lb = sum(Mb[(i, "Automatic")]["lc"] for i in both)
            la = sum(M[(i, "Automatic")]["lc"] for i in both)
            L.append(f"| {fam} | {b['st']['PASS']} → {a['st']['PASS']} | {a['n'] - a['st']['PASS']} | "
                     f"{ft(med(b['tm']))} → {ft(med(a['tm']))} | {ft(mx(b['tm']))} → {ft(mx(a['tm']))} | "
                     f"{fr(med(b['rl']))} → {fr(med(a['rl']))} | {fr(mx(b['rl']))} → {fr(mx(a['rl']))} | "
                     f"{lb:.0f} → {la:.0f} |")

    # worst offenders
    L.append(f"\n## Worst offenders (`{cur}`, Automatic)\n")
    bad = [(i, M[(i, "Automatic")]) for i in C if (i, "Automatic") in M and M[(i, "Automatic")]["status"] != "PASS"]
    L.append(f"### Not verified ({len(bad)})\n")
    if bad:
        L.append("| id | status | M time | Ref | integrand | note |")
        L.append("|---|---|---|---|---|---|")
        for i, m in bad:
            w = W.get(i, {})
            L.append(f"| {i} | {m['status']}{' ' + m['jump'] if m['jump'].startswith('JUMP') else ''} | {ft(m['t'])} | "
                     f"{w.get('status', '-')} {ft(w.get('t'))} | `{C[i]['wl'][:90]}` | {C[i]['note']} |")
    jumps = [(i, M[(i, "Automatic")]) for i in C if (i, "Automatic") in M
             and M[(i, "Automatic")]["jump"].startswith("JUMP")]
    L.append(f"\n### Spurious discontinuities ({len(jumps)})\n")
    for i, m in jumps:
        L.append(f"- {i} ({m['jump']}): `{C[i]['wl'][:100]}`")

    def topk(key, title, k=15):
        xs = []
        for i in C:
            m, w = M.get((i, "Automatic")), W.get(i)
            if m and m["status"] == "PASS" and ok_w(w):
                v = key(m, w)
                if v is not None:
                    xs.append((v, i, m, w))
        xs.sort(reverse=True)
        L.append(f"\n### {title}\n")
        L.append("| id | ratio | M time | Ref time | M size | Ref size | integrand |")
        L.append("|---|---|---|---|---|---|---|")
        for v, i, m, w in xs[:k]:
            L.append(f"| {i} | {v:.1f} | {ft(m['t'])} | {ft(w['t'])} | {fl(m['lc'])} | {fl(w['lc'])} | "
                     f"`{C[i]['wl'][:80]}` |")

    topk(lambda m, w: (m["t"] / max(w["t"], 1e-3)) if m["t"] and m["t"] > 0.05 else None,
         "Slowest relative to the reference (M time > 50 ms)")
    topk(lambda m, w: (m["lc"] / w["lc"]) if w["lc"] else None, "Largest relative to the reference")
    slow = sorted(((M[k]["t"] or 0), k[0]) for k in M if k[1] == "Automatic" and M[k]["status"] == "PASS")[-10:]
    L.append("\n### Slowest absolute (Automatic, PASS)\n")
    for t, i in reversed(slow):
        L.append(f"- {i}: {ft(t)} — `{C[i]['wl'][:100]}`")
    wf = [i for i in C if W.get(i) and W[i]["status"] != "OK"]
    L.append(f"\n### Reference did not answer ({len(wf)})\n")
    for i in wf:
        L.append(f"- {i}: {W[i]['status']} — Mathilda {M.get((i, 'Automatic'), {}).get('status', '-')}")
    return "\n".join(L) + "\n"


def load_grid(label):
    p = os.path.join(HERE, "results", label, "grid.tsv")
    G = {}
    if os.path.exists(p):
        for line in open(p):
            r = line.rstrip("\n").split("\t")
            if len(r) < 6:
                continue
            G[(r[0], r[1])] = dict(status=r[2], t=fnum(r[3]), lc=fnum(r[4]), jump=r[5])
    return G


def render_grid(label):
    C = load_corpus()
    G = load_grid(label)
    if not G:
        return ""
    cfgs = sorted({k[1] for k in G})
    L = [f"\n## Algorithm grid (`results/{label}/grid.tsv`)\n",
         "Every combination of `Method -> {\"BronsteinRational\", \"Hermite\" -> h, \"LogPart\" -> l, "
         "\"RealForm\" -> r}` on every case, one Mathilda process per case (15 s per integral). "
         "**ok** = PASS (`PossibleZeroQ[D[F, x] - f]`) and no spurious jump; RealForm -> None is a complex "
         "form, so its jumps are expected and reported, not counted against it. Times are summed over the "
         "cases every configuration in the row's comparison answered.\n"]

    def ok(r):
        return r and r["status"] == "PASS" and not r["jump"].startswith("JUMP")

    # overall
    L.append("### All configurations, whole corpus\n")
    L.append("| configuration | ok | FAIL | TIMEOUT/other | JUMP | total time | median time | total LeafCount (ok) |")
    L.append("|---|---|---|---|---|---|---|---|")
    common = [i for i in C if all(G.get((i, c), {}).get("status") == "PASS" for c in cfgs)]
    for c in cfgs:
        rs = [G.get((i, c)) for i in C]
        nok = sum(1 for r in rs if ok(r))
        nf = sum(1 for r in rs if r and r["status"] == "FAIL")
        nto = sum(1 for r in rs if r and r["status"] not in ("PASS", "FAIL"))
        nj = sum(1 for r in rs if r and r["jump"].startswith("JUMP"))
        tt = sum(G[(i, c)]["t"] or 0 for i in common)
        mt = med([G[(i, c)]["t"] for i in common])
        lc = sum(G[(i, c)]["lc"] or 0 for i in common)
        L.append(f"| {c} | {nok} | {nf} | {nto} | {nj} | {tt:.2f}s | {ft(mt)} | {lc:.0f} |")
    L.append(f"\n({len(common)} cases answered by all {len(cfgs)} configurations enter the time and size columns.)\n")

    def dim_table(title, fixed, varying, values):
        L.append(f"### {title}\n")
        hdr = "| family | " + " | ".join(f"{v} ok / time / size" for v in values) + " |"
        L.append(hdr)
        L.append("|---|" + "---|" * len(values))
        for fam in FAMS:
            ids = [i for i, cc in C.items() if cc["family"] == fam]
            if not ids:
                continue
            names = [fixed(v) for v in values]
            both = [i for i in ids if all(G.get((i, n), {}).get("status") == "PASS" for n in names)]
            cells = []
            for n in names:
                nok = sum(1 for i in ids if ok(G.get((i, n))))
                tt = sum(G[(i, n)]["t"] or 0 for i in both)
                lc = sum(G[(i, n)]["lc"] or 0 for i in both)
                cells.append(f"{nok}/{len(ids)} · {tt:.2f}s · {lc:.0f}")
            L.append(f"| {fam} | " + " | ".join(cells) + " |")
        L.append("")

    L.append("Within one process the configurations run in a fixed order (Hermite, then LogPart, then "
             "RealForm, as in the table above), so the first one, Linear|LazardRiobooTrager|Automatic, also pays "
             "the process's warm-up. The comparisons below therefore hold the other two choices at settings "
             "that never run first.\n")
    dim_table("Hermite reduction (LogPart RothsteinTrager, RealForm Rioboo)",
              lambda v: f"{v}|RothsteinTrager|Rioboo", "Hermite",
              ["Linear", "Quadratic", "HorowitzOstrogradsky"])
    dim_table("Log part (Hermite Quadratic, RealForm Rioboo)",
              lambda v: f"Quadratic|{v}|Rioboo", "LogPart",
              ["LazardRiobooTrager", "RothsteinTrager", "Czichowski"])
    dim_table("Real form (Hermite Quadratic, LogPart RothsteinTrager)",
              lambda v: f"Quadratic|RothsteinTrager|{v}", "RealForm",
              ["Automatic", "Rioboo", "LogToReal", "None"])
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels", default="before,after")
    ap.add_argument("--out", default=os.path.join(HERE, "REPORT.md"))
    ap.add_argument("--grid", default="grid", help="label of the algorithm-grid run")
    a = ap.parse_args()
    labels = [l for l in a.labels.split(",") if os.path.isdir(os.path.join(HERE, "results", l))]
    with open(a.out, "w") as fh:
        fh.write(render(labels) + render_grid(a.grid))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
