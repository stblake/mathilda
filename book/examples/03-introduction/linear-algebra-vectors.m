# Vectors are lists and matrices are lists of rows; the single operator . (Dot)
# serves as the vector inner product, the matrix-vector product, and the
# matrix-matrix product. Norm is the Euclidean length; Cross the 3-D cross product.
{1, 2, 3} . {4, 5, 6}
Norm[{1, 2, 3}]
Cross[{1, 0, 0}, {0, 1, 0}]
{{1, 2}, {3, 4}} . {5, 6}
{{1, 2}, {3, 4}} . {{0, 1}, {1, 0}}
