#!/usr/bin/env python3
"""dsolve_pde_corpus_report.py -- the PDE corpus dashboard.

Reads the runner TSVs DSolve_test_status/pde/reports/<chap>.tsv
(`<tag>\\t<label>\\t<section>\\t<mma>\\t<maple>`, one per record, from
test_dsolve_pde_corpus) and the scraped lookup table raw/lookup.tsv, and writes

  DSolve_test_status/pde/STATUS.md        totals, per chapter and per section,
                                          against Mathematica 15 / Maple 2026.1
  DSolve_test_status/pde/reports/<chap>.md the ranked gap list of one chapter

Gap ranking: records the reference system solves and Mathilda does not come
first (those are the parity target), then Maple-only, then records nobody solves.
FAIL rows are listed separately at the top -- a wrong answer outranks any gap.

Usage:  python3 tools/dsolve_pde_corpus_report.py
"""
import collections
import glob
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
PDE = os.path.join(ROOT, "DSolve_test_status", "pde")

PASS_TAGS = {"P", "I", "S"}
TAG_NAME = {"P": "PASS", "I": "PASS-IMPLICIT", "S": "PASS-SERIES", "K": "UNK",
            "F": "FAIL", "N": "UNFIT", "U": "UNEVAL"}
CHAPTER = {"2": "Miscellaneous", "3": "Parabolic (diffusion)",
           "4": "Elliptic (Laplace, Poisson, Helmholtz)", "5": "Hyperbolic (wave)",
           "6": "Polyanin, first-order handbook", "7": "Polyanin, nonlinear handbook"}


def load_lookup():
    rows = {}
    for line in open(os.path.join(PDE, "raw", "lookup.tsv"), encoding="utf-8"):
        if line.startswith("#"):
            continue
        f = line.rstrip("\n").split("\t")
        rows["pde-" + f[0]] = {"section": f[1], "category": f[2], "desc": f[3],
                               "mma": f[4], "maple": f[6]}
    return rows


def load_classes():
    """classes.tsv from tools/pde_corpus/classify_pde_corpus.m (optional)."""
    path = os.path.join(PDE, "classes.tsv")
    out = {}
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            f = line.rstrip("\n").split("\t")
            if len(f) >= 6:
                out[f[0]] = {"cls": f[1], "nvars": f[2], "order": f[3], "dom": f[5]}
    return out


def load_runs():
    runs = {}
    for path in sorted(glob.glob(os.path.join(PDE, "reports", "*.tsv"))):
        key = os.path.basename(path)[:-4]
        for line in open(path, encoding="utf-8"):
            f = line.rstrip("\n").split("\t")
            if len(f) >= 5:
                runs[f[1]] = {"tag": f[0], "file": key}
    return runs


def pct(a, b):
    return "%.1f%%" % (100.0 * a / b) if b else "-"


def main():
    lookup, runs, classes = load_lookup(), load_runs(), load_classes()
    if not runs:
        print("no runner TSVs under", os.path.join(PDE, "reports"))
        return 1
    by_chap = collections.defaultdict(list)
    by_sect = collections.defaultdict(list)
    for label, r in runs.items():
        lk = lookup.get(label, {"section": "?", "mma": "?", "maple": "?",
                                "category": "", "desc": ""})
        rec = dict(r, label=label, **lk)
        rec.update(classes.get(label, {"cls": "?", "nvars": "?", "order": "?", "dom": "?"}))
        by_chap[lk["section"].split(".")[0]].append(rec)
        by_sect[".".join(lk["section"].split(".")[:2])].append(rec)

    def tally(recs):
        c = collections.Counter(x["tag"] for x in recs)
        ok = sum(c[t] for t in PASS_TAGS)
        mma = sum(1 for x in recs if x["mma"] == "Y")
        maple = sum(1 for x in recs if x["maple"] == "Y")
        gap = sum(1 for x in recs if x["mma"] == "Y" and x["tag"] not in PASS_TAGS)
        return c, ok, mma, maple, gap

    allrecs = [x for v in by_chap.values() for x in v]
    c, ok, mma, maple, gap = tally(allrecs)
    out = ["# DSolve PDE corpus: status", "",
           "Generated by `tools/dsolve_pde_corpus_report.py` from the runner TSVs in",
           "`reports/`. Do not hand-edit. The corpus is N. Abbasi's *PDE in CAS* (see",
           "`README.md`). Reference columns are Abbasi's per-problem results; note that",
           "his are unverified, while every Mathilda PASS here is proved by",
           "back-substitution.", "",
           "## Totals", "",
           "| | records | Mathilda | Mathematica 15 | Maple 2026.1 |",
           "|---|---|---|---|---|",
           "| all | %d | %d (%s) | %d (%s) | %d (%s) |" % (
               len(allrecs), ok, pct(ok, len(allrecs)), mma, pct(mma, len(allrecs)),
               maple, pct(maple, len(allrecs))), "",
           "Verdicts: " + ", ".join("%s %d" % (TAG_NAME[t], c[t]) for t in
                                    ["P", "I", "S", "K", "F", "N", "U"]) + ".", "",
           "Parity gap (Mathematica solves, Mathilda does not): **%d**." % gap, "",
           "## By chapter", "",
           "| ch | topic | records | Mathilda | Mma | Maple | gap | PASS | IMPL | SER | UNK | FAIL | UNFIT | UNEVAL |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for ch in sorted(by_chap):
        recs = by_chap[ch]
        c, ok, mma, maple, gap = tally(recs)
        out.append("| %s | %s | %d | %d (%s) | %s | %s | %d | %s |" % (
            ch, CHAPTER.get(ch, "?"), len(recs), ok, pct(ok, len(recs)),
            pct(mma, len(recs)), pct(maple, len(recs)), gap,
            " | ".join(str(c[t]) for t in ["P", "I", "S", "K", "F", "N", "U"])))
    out += ["", "## By section", "",
            "| section | category | records | Mathilda | Mma | gap | FAIL |",
            "|---|---|---|---|---|---|---|"]
    for s in sorted(by_sect, key=lambda k: [int(p) if p.isdigit() else 0 for p in k.split(".")]):
        recs = by_sect[s]
        c, ok, mma, maple, gap = tally(recs)
        cat = collections.Counter(x["category"] for x in recs).most_common(1)[0][0]
        out.append("| %s | %s | %d | %d | %d | %d | %d |" % (
            s, cat, len(recs), ok, mma, gap, c["F"]))
    # method buckets: structural class x domain (x 2 / 3+ variables for first order)
    def bucket(x):
        nv = "" if not x["cls"].startswith("o1") else (" 2-var" if x["nvars"] == "2" else " 3+-var")
        return x["cls"] + nv + " / " + x["dom"]
    by_b = collections.defaultdict(list)
    for x in allrecs:
        by_b[bucket(x)].append(x)
    out += ["", "## By method bucket (structural class / domain)", "",
            "Class from `classes.tsv` (`tools/pde_corpus/classify_pde_corpus.m`). Ranked by",
            "parity gap, the number Mathematica solves that Mathilda does not.", "",
            "| bucket | records | Mathilda | Mma | Maple | gap |", "|---|---|---|---|---|---|"]
    for b in sorted(by_b, key=lambda k: -tally(by_b[k])[4]):
        c, ok, mma, maple, gap = tally(by_b[b])
        out.append("| %s | %d | %d | %d | %d | %d |" % (b, len(by_b[b]), ok, mma, maple, gap))
    fails = sorted((x for x in allrecs if x["tag"] == "F"),
                   key=lambda x: int(x["label"].split("-")[1]))
    out += ["", "## Wrong answers (FAIL)", ""]
    out += ["- `%s` (%s) %s %s" % (x["label"], x["section"], x["category"], x["desc"][:80])
            for x in fails] or ["None."]
    open(os.path.join(PDE, "STATUS.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")

    files = collections.defaultdict(list)
    for x in allrecs:
        files[x["file"]].append(x)
    for key, recs in files.items():
        recs.sort(key=lambda x: int(x["label"].split("-")[1]))
        rank = [("FAIL: wrong answers", lambda x: x["tag"] == "F"),
                ("Mathematica solves, Mathilda does not",
                 lambda x: x["tag"] not in PASS_TAGS | {"F"} and x["mma"] == "Y"),
                ("Maple only",
                 lambda x: x["tag"] not in PASS_TAGS | {"F"} and x["mma"] != "Y" and x["maple"] == "Y"),
                ("Neither reference system",
                 lambda x: x["tag"] not in PASS_TAGS | {"F"} and x["mma"] != "Y" and x["maple"] != "Y"),
                ("Mathilda solves, Mathematica does not",
                 lambda x: x["tag"] in PASS_TAGS and x["mma"] != "Y")]
        md = ["# DE_PDE_%s.m: gap report" % key, "",
              "Generated by `tools/dsolve_pde_corpus_report.py`. Do not hand-edit.", ""]
        for title, pred in rank:
            sel = [x for x in recs if pred(x)]
            md += ["## %s (%d)" % (title, len(sel)), ""]
            md += ["- `%s` %s [%s] {%s/%s} %s: %s" % (x["label"], x["section"], TAG_NAME[x["tag"]],
                                             x["cls"], x["dom"], x["category"], x["desc"][:90])
                   for x in sel]
            md.append("")
        open(os.path.join(PDE, "reports", key + ".md"), "w", encoding="utf-8").write("\n".join(md))
    print("STATUS.md + %d chapter reports written" % len(files))
    return 0


if __name__ == "__main__":
    sys.exit(main())
