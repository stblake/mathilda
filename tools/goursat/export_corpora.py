def run_example_cases():
    """The case list of run_examples.py (the file runs on import, so its list is
    re-stated here; the V4 / None placeholders are expanded exactly as it does)."""
    R4 = (t**2-1)*(t**2-4)
    rows = [
        ("Ex5.1  t/sqrt((t^2-1)(t^2-4))", t, R4, h),
        ("V4 generic: g-avg(g), g=1/(t-3)", None, R4, h),
        ("exact: d(t sqrt R)", 3*t**4-10*t**2+4, R4, h),
        ("t/sqrt(t^3+1)", t, t**3+1, h),
        ("Legendre-Clausen t/((t^3+8)sqrt(t^3-1))", t/(t**3+8), t**3-1, h),
        ("1/sqrt(t^4+1)", 1, t**4+1, h),
        ("(t^2-1)/((t^2+1)sqrt(t^4+1))", (t**2-1)/(t**2+1), t**4+1, h),
        ("Ex5.2  1/(t^3-1)^(1/3)", 1, t**3-1, q),
        ("Ex5.3  t^2/(t^3-1)^(1/3)", t**2, t**3-1, q),
        ("Ex5.4  t/(t^3-1)^(1/3)", t, t**3-1, q),
        ("CEX A  t(2t^3-1)/(t^3-1)^(1/3)", t*(2*t**3-1), t**3-1, q),
        ("CEX B  1/(t^3+t)^(1/3)", 1, t**3+t, q),
        ("CEX C  Ex5.5 piece t/((t^3+1)(t^3-1)^(1/3))", t/(t**3+1), t**3-1, q),
        ("Ex5.5  full", 1+5*t**2-7*t/(t**3+1), t**3-1, q),
        ("Ex5.7  1/(t^2-1)^(1/3)", 1, t**2-1, q),
        ("(at+b)/(H R^(1/3)), R=(t-1)(t-2)(t-3)", (2*t+5)/(3*t**2-12*t+13), (t-1)*(t-2)*(t-3), q),
        ("1/((t-1)(t-2)(t-3))^(1/3)", 1, (t-1)*(t-2)*(t-3), q),
        ("1/(H R^(1/3)), R=2t^3-3t^2-3t+2", None, 2*t**3-3*t**2-3*t+2, q),
        ("1/(t^3-1)^(2/3)", 1, t**3-1, 2*q),
        ("t/(t^3-1)^(2/3)", t, t**3-1, 2*q),
        ("CEX D  (2t^3-1)/(t^3-1)^(2/3)", 2*t**3-1, t**3-1, 2*q),
        ("(t^3+1)/(t (t^3-1)^(2/3))  [odd in x0]", (t**3+1)/(t**3-1), t**3-1, 2*q),
        ("t/((t-1)(t-2)(t-3))^(2/3)", t, (t-1)*(t-2)*(t-3), 2*q),
        ("irreducible cubic: 1/(H (t^3+t+1)^(1/3))", None, t**3+t+1, q),
        ("irreducible resolvent: (F - F0), F=1/(t-2), R=t^4+t+1", "V4", t**4+t+1, h),
        ("1/sqrt(t^3+t+1)", 1, t**3+t+1, h),
        ("general cubic, no symmetry: 1/(t^3+t+1)^(1/3)", 1, t**3+t+1, q),
        ("1/(t^2+t+1)^(2/3)", 1, t**2+t+1, 2*q),
        ("(t+1)/(t (t^2-1)^(1/3))", (t+1)/t, t**2-1, q),
    ]
    cs = []
    for lab, F, R, p in rows:
        if F == "V4":
            g = 1/(t-2)
            acc = g
            for (L, N, M) in involutions(sp.expand(R), t):
                acc += g.subs(t, (N*t-M)/(L*t-N))
            F = sp.cancel(sp.together(g - acc/4), extension=True)
        elif F is None:
            if p == h:
                g = 1/(t-3)
                F = sp.cancel(g - (g + g.subs(t, -t) + g.subs(t, 2/t) + g.subs(t, -2/t))/4)
            else:
                F = 1/cubic_covariants(sp.expand(R), t)[0]
        cs.append(frp(lab, "examples", F, R, p, None))
    return cs


# ---------------------------------------------------------------- stress_goursat.py
def stress_cases(seed, count=25):
    cs = []
    for name, gen in SG.FAMILIES:
        rng = random.Random(f"{seed}-{name}")
        made, tries = 0, 0
        while made < count and tries < 20 * count:
            tries += 1
            try:
                F, R, p, truth = gen(rng)
            except Exception:
                continue
            if F == 0:
                continue
            cs.append(frp(f"{name} #{made}", name, F, R, p, truth))
            made += 1
    return cs


def literature_cases():
    return [expr(f"literature: {e}   [{why}]", "literature", e, truth)
            for e, truth, why in SG.LITERATURE]


def welz():
    import welz_cases as W
    return [expr(name, "welz", e.subs(W.x, t), "elementary") for name, e in W.CASES]


def wl_list(fname, family):
    """The goursat_examples*.wl lists, verbatim (integrands in x; each was proved
    elementary by goursat.py)."""
    src = open(os.path.join(RESEARCH, fname)).read()
    body = src[src.index("{") + 1: src.rindex("}")]
    items, depth, cur = [], 0, ""
    for ch in body:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            items.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        items.append(cur.strip())
    out = []
    for i, it in enumerate(items):
        it = " ".join(it.split())
        out.append(dict(Label=f"{family} #{i}: {it}", Family=family, Kind="expr",
                        IntegrandWL=it, Truth="elementary"))
    return out


def write_wl(name, cases, header):
    path = os.path.join(OUT, name + ".m")
    with open(path, "w") as f:
        f.write("(* " + header + "\n   Generated by tools/goursat/export_corpora.py; do not edit. *)\n{\n")
        f.write(",\n".join(
            f'  <|"Label" -> {wl(c["Label"])}, "Family" -> {wl(c["Family"])}, "Kind" -> "expr", '
            f'"Integrand" -> ({c["IntegrandWL"]}) /. x -> t, "Var" -> t, "Truth" -> "elementary"|>'
            for c in cases))
        f.write("\n}\n")
    print(f"{path}: {len(cases)} cases")


