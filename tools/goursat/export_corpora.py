"""Export the GeneralisedGoursat test corpora from the sympy reference.

    GOURSAT_RESEARCH=<dir> python3.11 tools/goursat/export_corpora.py

GOURSAT_RESEARCH (default ~/Documents/Research/post_phd_research/algebraic_integration/goursat)
holds goursat.py, test_goursat.py, stress_goursat.py, run_examples.py, welz_cases.py
and the two goursat_examples*.wl lists.  It is only read: its modules are imported to
regenerate exactly the cases its own harnesses run, and nothing is written there.

Writes tests/data/generalised_goursat/<corpus>.m, each file a single expression

    {<|"Label" -> ..., "Family" -> ..., "Kind" -> "FRp" | "expr",
       "F" -> F, "R" -> R, "p" -> p,          (FRp cases: integrand F/R^p in t)
       "Integrand" -> f, "Var" -> t,          (always present)
       "Truth" -> "elementary" | "non-elementary" | "undecided" | None|>, ...}

Truth is the independent ground truth where the source harness has one (constructed
families, Chebyshev's theorem, the literature list); None otherwise.  The sympy
verdict and timing are NOT recorded here -- tools/goursat/bench_sympy.py adds them,
because they need a long parallel run with timeouts.
"""
import os
import random
import sys

RESEARCH = os.path.expanduser(os.environ.get(
    "GOURSAT_RESEARCH", "~/Documents/Research/post_phd_research/algebraic_integration/goursat"))
sys.path.insert(0, RESEARCH)
