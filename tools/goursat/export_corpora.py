    for (n, p) in [(3, q), (3, 2*q), (2, q), (2, 2*q), (3, h), (4, h), (4, h/2), (4, 3*h/2)]:
        for m in range(-5, 8):
            cs.append(frp(f"Chebyshev t^{m}/(t^{n}-1)^({p})", "chebyshev", t**m, t**n - 1, p,
                          cheb(m, n, p)))
    R4 = (t**2 - 1)*(t**2 - 4)
    rows = [
        ("Ex 5.1", t, R4, h, "elementary"),
        ("d(t sqrt R)  [Goursat criterion fails]", 3*t**4 - 10*t**2 + 4, R4, h, "elementary"),
        ("Legendre-Clausen", t/(t**3 + 8), t**3 - 1, h, "elementary"),
        ("Goursat (t^3-4)/((t^3+8)sqrt(t^3-1))", (t**3 - 4)/(t**3 + 8), t**3 - 1, h, "elementary"),
        ("Goursat t^2/((t^3+8)sqrt(t^3-1))", t**2/(t**3 + 8), t**3 - 1, h, "elementary"),
        ("order 3: 1/(t sqrt(t^3-1))", 1/t, t**3 - 1, h, "elementary"),
        ("order 3: shifted (t+1)^3-2", (t+1)**2/((t+1)**3+2), (t+1)**3 - 2, h, "elementary"),
        ("order 3, irrational roots: t^2/((t^3+5)sqrt(t^3-2))", t**2/(t**3+5), t**3 - 2, h, "elementary"),
        ("order 3, quartic j=0 rational root: t/((t^3+2) sqrt(t^4-t))", t/(t**3 + 2), t**4 - t, h, "elementary"),
        ("order 3, quartic j=0: 1/sqrt(t^4-t)", 1, t**4 - t, h, "non-elementary"),
        ("Goursat sec. 4: (t-1)/((t+2) sqrt(t^3-1))", (t-1)/(t+2), t**3 - 1, h, "elementary"),
        ("mixed: (t-1)/(t+2) + t^2/(t^3+8) + 1/t", (t-1)/(t+2) + t**2/(t**3+8) + 1/t, t**3 - 1, h, "elementary"),
        ("order 4: t^2/sqrt(t^4-1)", t**2, t**4 - 1, h, "non-elementary"),
        ("order 4: 1/((t^4+3) sqrt(t^4-1))", 1/(t**4 + 3), t**4 - 1, h, "undecided"),
        ("1/sqrt(t^4+1)", 1, t**4 + 1, h, "non-elementary"),
        ("(t^2-1)/((t^2+1)sqrt(t^4+1))", (t**2 - 1)/(t**2 + 1), t**4 + 1, h, "elementary"),
        ("Ex 5.5 (paper: non-elementary)", 1 + 5*t**2 - 7*t/(t**3 + 1), t**3 - 1, q, "elementary"),
        ("CEX A  t(2t^3-1), V1, polynomial", t*(2*t**3 - 1), t**3 - 1, q, "elementary"),
        ("CEX B  1/(t^3+t)^(1/3), F = 1", 1, t**3 + t, q, "elementary"),
        ("CEX D  (2t^3-1)/(t^3-1)^(2/3)", 2*t**3 - 1, t**3 - 1, 2*q, "elementary"),
        ("(2t+5)/(Hessian R^(1/3))", (2*t + 5)/(3*t**2 - 12*t + 13), (t-1)*(t-2)*(t-3), q, "elementary"),
        ("1/(t^3+t+1)^(1/3)  (needs a torsion test)", 1, t**3 + t + 1, q, "undecided"),
        ("1/sqrt(t^3+t+1)  (irreducible; trace criterion)", 1, t**3 + t + 1, h, "non-elementary"),
    ]
    for lab, F, R, p, tr in rows:
        cs.append(frp(lab, "unit", F, R, p, tr))
    # Goursat's Theorem 2 over an irreducible resolvent cubic: g - F0(g) is elementary
    g, R = 1/(t - 2), t**4 + t + 1
    cs.append(frp("irreducible resolvent: g - F0(g), g=1/(t-2), R=t^4+t+1", "cubic-field",
                  sp.cancel(g - goursat_F0(g, R, t)), R, h, "elementary"))
    return cs


