#!/usr/bin/env python3
"""Join the GeneralisedGoursat runs and write the comparison report.

    python3 tools/goursat/compare.py

Reads, for every corpus tests/data/generalised_goursat/<corpus>.m,
  mathilda_<corpus>.tsv   (tools/goursat/bench_generalised_goursat.m, GG_METHOD=new)
  sympy_<corpus>.tsv      (tools/goursat/bench_sympy.py)
  c_<corpus>.tsv          (bench_generalised_goursat.m, GG_METHOD=c; optional)
and writes tests/data/generalised_goursat/REPORT.md.

Verdicts (as stress_goursat.py's judge):
  OK       the verdict agrees with the truth (or there is none) and the answer verifies
  MISSED   "undecided" although the truth is known (incompleteness, not a bug)
  WRONG    the verdict contradicts the truth, or the verification failed (a bug)
  UNEVAL   "elementary" but part of the answer is an unevaluated integral
  DECLINE / TIMEOUT / MEMORY / ERROR
Exit status 1 if Mathilda has any WRONG or DECLINE/ERROR on a case sympy decides.
"""
import os
import re
import statistics
import sys

D = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                 "tests", "data", "generalised_goursat")
CORPORA = ["unit", "examples", "literature", "welz", "stress_2026", "stress_7", "stress_11",
           "pseudoelliptic_sqrt", "pseudoelliptic_cbrt"]
ROW = re.compile(r'"Label" -> "((?:[^"\\]|\\.)*)", "Family" -> "([^"]*)".*"Truth" -> ("?[\w-]+"?)\|>')


def cases(corpus):
    out = []
    for line in open(os.path.join(D, corpus + ".m")):
        m = ROW.search(line)
        if m:
            lab = m.group(1).replace('\\"', '"').replace('\\\\', '\\')
            truth = m.group(3).strip('"')
            out.append((lab, m.group(2), None if truth == "None" else truth))
    return out


def tsv(path):
    if not os.path.exists(path):
        return None
    rows = {}
    with open(path) as f:
        next(f)
        for line in f:
            p = line.rstrip("\n").split("\t")
            p += [""] * (6 - len(p))
            rows[" ".join(p[0].split())] = dict(status=p[1], secs=float(p[2] or 0), verified=p[3],
                                                 uneval=p[4] == "True", residual=p[5])
    return rows


def judge(r, truth, kind):
    if r is None:
        return "MISSING"
    s = r["status"]
    if s in ("TIMEOUT", "MEMORY", "DECLINE", "ERROR"):
        return s
    if kind == "sympy":
        ok = r["verified"] != "" and float(r["verified"]) < 1e-15
    else:
        ok = r["verified"] == "True"
    if s == "elementary" and r["uneval"]:
        return "UNEVAL"
    if not ok:
        return "WRONG"
    if truth is None or s == truth:
        return "OK"
    return "MISSED" if s == "undecided" else "WRONG"


def fmt(x):
    return "-" if x is None else (f"{x:.3f}" if x < 10 else f"{x:.1f}")


def main():
    lines = ["# GeneralisedGoursat: Mathilda vs the sympy reference (and the C GoursatAlgebraic)", "",
             "Generated by `tools/goursat/compare.py`. Times are the reduction only (no verification), "
             "wall clock, one case at a time per process.", ""]
    summary, details, slower, bad = [], [], [], 0
    for corpus in CORPORA:
        if not os.path.exists(os.path.join(D, corpus + ".m")):
            continue
        cs = cases(corpus)
        M = tsv(os.path.join(D, f"mathilda_{corpus}.tsv"))
        S = tsv(os.path.join(D, f"sympy_{corpus}.tsv"))
        C = tsv(os.path.join(D, f"c_{corpus}.tsv"))
        fams = {}
        for lab, fam, truth in cs:
            key = " ".join(lab.split())
            m = M.get(key) if M else None
            s = S.get(key) if S else None
            c = C.get(key) if C else None
            jm, js = judge(m, truth, "m"), judge(s, truth, "sympy")
            jc = None
            if c is not None:
                jc = "OK" if c["status"] == "elementary" and c["verified"] == "True" else c["status"]
            f = fams.setdefault(fam, dict(m={}, s={}, c={}, tm=[], ts=[], tc=[]))
            f["m"][jm] = f["m"].get(jm, 0) + 1
            f["s"][js] = f["s"].get(js, 0) + 1
            if jc:
                f["c"][jc] = f["c"].get(jc, 0) + 1
            if m and jm not in ("MISSING",):
                f["tm"].append(m["secs"])
            if s and js not in ("MISSING",):
                f["ts"].append(s["secs"])
            if c:
                f["tc"].append(c["secs"])
            if jm != "OK" or (js != "OK" and js != "MISSING"):
                details.append(f"| {corpus} | {lab[:90]} | {truth} | {m['status'] if m else '-'} ({jm}) | "
                               f"{s['status'] if s else '-'} ({js}) | {fmt(m['secs'] if m else None)} | "
                               f"{fmt(s['secs'] if s else None)} |")
            if jm == "WRONG" or (jm in ("DECLINE", "ERROR", "TIMEOUT", "MEMORY", "UNEVAL")
                                 and js == "OK"):
                bad += 1
            if m and s and m["secs"] > s["secs"] and m["secs"] > 0.05:
                slower.append(f"| {corpus} | {lab[:90]} | {m['secs']:.3f} | {s['secs']:.3f} |")
        for fam, f in fams.items():
            med = lambda v: statistics.median(v) if v else None
            mm, ms = med(f["tm"]), med(f["ts"])
            ratio = (ms / mm) if (mm and ms) else None
            cnt = lambda d: " ".join(f"{k}={v}" for k, v in sorted(d.items())) or "-"
            summary.append(f"| {corpus} | {fam} | {cnt(f['m'])} | {cnt(f['s'])} | {cnt(f['c'])} | "
                           f"{fmt(mm)} | {fmt(max(f['tm']) if f['tm'] else None)} | {fmt(ms)} | "
                           f"{fmt(max(f['ts']) if f['ts'] else None)} | "
                           f"{'-' if ratio is None else f'{ratio:.1f}x'} | "
                           f"{fmt(sum(f['tm']) if f['tm'] else None)} | {fmt(sum(f['ts']) if f['ts'] else None)} |")
    lines += ["## Summary by family", "",
              "| corpus | family | Mathilda | sympy | C | M median s | M max s | sympy median s | "
              "sympy max s | speed-up (median) | M total s | sympy total s |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"] + summary
    lines += ["", f"Mathilda cases that are bugs or regressions against sympy: **{bad}**", "",
              "## Cases not OK on either side", "",
              "| corpus | case | truth | Mathilda | sympy | M s | sympy s |", "|---|---|---|---|---|---|---|"] + details
    lines += ["", "## Cases where Mathilda is slower than sympy (> 0.05 s)", "",
              "| corpus | case | Mathilda s | sympy s |", "|---|---|---|---|"] + slower
    open(os.path.join(D, "REPORT.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(summary))
    print(f"bugs/regressions: {bad}; slower cases: {len(slower)}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
