#!/usr/bin/env python3
"""bronstein_paper_table.py -- run the Bronstein gap-log corpus and render it.

Runs ./Mathilda -file tests/bronstein_paper/run.m. That checks every example of
tests/bronstein_paper/examples.m: the gaps the completion campaign closed, each
with non-trivial examples, which are the corpus behind the JSC paper. The
script then writes docs/notes/bronstein_examples_table.tex, a longtable that
docs/notes/bronstein_extensions.tex \\input s.

    python3 tools/bronstein_paper_table.py           # check + write the table
    python3 tools/bronstein_paper_table.py --check   # check only (ctest)
    python3 tools/bronstein_paper_table.py --open-gaps [--check]
        the register of known open gaps (tests/bronstein_paper/open_gaps.m):
        every entry must still behave as recorded (a CHANGED entry fails: move
        it to examples.m with its fix, or update the record); writes
        docs/notes/bronstein_open_gaps_table.tex

Exits 1 when an example fails, 77 (ctest SKIP) without ./Mathilda.
"""
import os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MATH = os.path.join(ROOT, "Mathilda")
OUT = os.path.join(ROOT, "docs", "notes", "bronstein_examples_table.tex")
OUT_GAPS = os.path.join(ROOT, "docs", "notes", "bronstein_open_gaps_table.tex")

OUTCOME = {'"elementary"': "elementary", '"nonelementary"': "not elementary (certified)",
           '"incomplete"': "implementation incomplete", "True": "\\code{True}", "False": "\\code{False}",
           '"InScope"': "in scope"}


def tex(s):
    rep = {"\\": "\\textbackslash{}", "&": "\\&", "%": "\\%", "$": "\\$", "#": "\\#", "_": "\\_",
           "{": "\\{", "}": "\\}", "~": "\\textasciitilde{}", "^": "\\textasciicircum{}"}
    return "".join(rep.get(c, c) for c in s)


def open_gaps():
    p = subprocess.run([MATH, "-file", "tests/bronstein_paper/open_gaps_run.m"], cwd=ROOT,
                       capture_output=True, text=True, timeout=7200)
    rows = [ln.split("\t")[1:] for ln in p.stdout.splitlines() if ln.startswith("GAPROW\t")]
    struct = [ln.split("\t")[1:] for ln in p.stdout.splitlines() if ln.startswith("GAPSTRUCT\t")]
    for ln in p.stdout.splitlines():
        if ln.startswith(("STILL-OPEN", "CHANGED", "OPENGAPS")):
            print(ln)
    if not rows:
        print("no rows: open_gaps_run.m did not complete"); return 1
    if "--check" not in sys.argv:
        L = ["% generated by tools/bronstein_paper_table.py --open-gaps from tests/bronstein_paper/open_gaps.m -- do not edit",
             "\\begin{longtable}{>{\\raggedright\\arraybackslash}p{0.08\\textwidth}>{\\raggedright\\arraybackslash}p{0.42\\textwidth}"
             ">{\\raggedright\\arraybackslash}p{0.13\\textwidth}>{\\raggedright\\arraybackslash}p{0.27\\textwidth}}",
             "\\toprule", "Id & Gap and example & Now & Follow-up (found by) \\\\ \\midrule", "\\endhead"]
        for r in rows:
            rid, area, gap, f, cur, fu, src, st = r
            L.append(f"{tex(rid)} & {tex(gap)}\\newline\\code{{{tex(f)}}} & {tex(cur)} & "
                     f"{{\\footnotesize {tex(fu)} ({tex(src)})}} \\\\")
        L += ["\\midrule", "\\multicolumn{4}{l}{\\emph{Gaps without a single example}} \\\\"]
        for g in struct:
            L.append(f"{tex(g[0])} & \\multicolumn{{2}}{{>{{\\raggedright\\arraybackslash}}p{{0.55\\textwidth}}}}{{{tex(g[1])}}} & {{\\footnotesize {tex(g[2])}}} \\\\")
        L += ["\\bottomrule", "\\end{longtable}"]
        open(OUT_GAPS, "w").write("\n".join(L) + "\n")
        print("wrote", os.path.relpath(OUT_GAPS, ROOT))
    changed = [r[0] for r in rows if r[7] != "open"]
    if changed:
        print("CHANGED:", ", ".join(changed)); return 1
    return 0


def main():
    if not os.access(MATH, os.X_OK):
        print("no ./Mathilda"); return 77
    if "--open-gaps" in sys.argv:
        return open_gaps()
    p = subprocess.run([MATH, "-file", "tests/bronstein_paper/run.m"], cwd=ROOT,
                       capture_output=True, text=True, timeout=7200)
    rows = [ln.split("\t")[1:] for ln in p.stdout.splitlines() if ln.startswith("ROW\t")]
    fails = [r[0] for r in rows if r[8] != "PASS"]
    for ln in p.stdout.splitlines():
        if ln.startswith(("PASS", "FAIL", "SUMMARY")):
            print(ln)
    if not rows:
        print("no rows: run.m did not complete"); return 1
    if "--check" not in sys.argv:
        L = ["% generated by tools/bronstein_paper_table.py from tests/bronstein_paper/examples.m -- do not edit",
             "\\begin{longtable}{>{\\raggedright\\arraybackslash}p{0.06\\textwidth}>{\\raggedright\\arraybackslash}p{0.40\\textwidth}"
             ">{\\raggedright\\arraybackslash}p{0.17\\textwidth}>{\\raggedright\\arraybackslash}p{0.22\\textwidth}r}",
             "\\toprule", "Id & Input & Result (\\S, version) & Before & s \\\\ \\midrule", "\\endhead"]
        for r in rows:
            rid, gap, th, ver, kind, exp, f, secs, ok, before, note = r
            if exp.startswith("Hold[") and exp.endswith("]"):
                exp = exp[5:-1]
            res = OUTCOME.get(exp, "\\code{" + tex(exp) + "}")
            inp = "\\code{" + tex(f) + "}"
            if kind != "Integrate":
                inp = "\\code{" + tex(kind) + "}: " + inp
            L.append(f"{tex(rid)} & {inp}\\newline{{\\footnotesize {tex(note)}}} & {res} ({tex(th)}, {tex(ver)}) "
                     f"& {{\\footnotesize {tex(before)}}} & {tex(secs.strip())} \\\\")
        L += ["\\bottomrule", "\\end{longtable}"]
        open(OUT, "w").write("\n".join(L) + "\n")
        print("wrote", os.path.relpath(OUT, ROOT))
    if fails:
        print("FAIL:", ", ".join(fails)); return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
